def test_модуль_не_зовёт_публикацию_и_не_ходит_в_сеть() -> None:
    дерево = ast.parse((ROOT / "tools" / "case_package.py").read_text(encoding="utf-8"))
    имена = {a.name.split(".")[0] for n in ast.walk(дерево)
             if isinstance(n, ast.Import) for a in n.names}
    имена |= {n.module.split(".")[0] for n in ast.walk(дерево)
              if isinstance(n, ast.ImportFrom) and n.module}

    разрешены = {"__future__", "argparse", "json", "hashlib", "re", "sys",
                 "pathlib", "dataclasses", "typing", "yaml", "datetime"}
    assert имена <= разрешены, f"новые зависимости: {имена - разрешены}"
    исходник = (ROOT / "tools" / "case_package.py").read_text(encoding="utf-8")
    for запрет in ("post_telegram", "content/telegram", "requests", "urllib",
                   "subprocess", "socket"):
        assert запрет not in исходник, f"модуль упоминает {запрет}"


