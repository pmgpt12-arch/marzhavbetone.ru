def образец(tmp: Path, *, official: bool = False) -> str:
    """Кладёт образец в свой каталог и возвращает идентификатор случая."""
    случай = "spor-kc2-proverka" if official else ОБРАЗЕЦ
    источник = dict(ИСТОЧНИК, case_id=случай)
    if official:
        источник["source_kind"] = пакет.OFFICIAL
        источник["source_url"] = "https://example.invalid/act/proverka"
    пакет.save_source(источник, root=tmp)
    манифест = {"case_id": случай,
                "facts": [dict(f) for f in МАНИФЕСТ["facts"]]}
    пакет.save_manifest(манифест, root=tmp)
    return случай


def собрать(tmp: Path, **kwargs) -> dict:
    """Сборка на образце: без официального класса и без записи на диск."""
    случай = образец(tmp)
    return пакет.build(случай, root=tmp, **kwargs)


