#!/usr/bin/env python3
"""Сторож раннера проверок.

ЗАЧЕМ. Раннер решает, красить ли прогон, — то есть он и есть ворота. Если
он ошибётся в пользу зелёного, гейт снова станет украшением, как это уже
было с `bash -e`: список шагов был, а проверки не исполнялись. Поэтому
здесь доказывается не «раннер запускается», а ровно три его обещания:

  1. упала блокирующая — прогон FAIL;
  2. упала не блокирующая — прогон PASS, но провал напечатан;
  3. падение одной не мешает остальным исполниться.

Плюс сам реестр: имена уникальны, команды указывают на существующие
файлы, блокировать может только публичный контур.

    python3 tools/test_run_checks.py
"""
from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
РАННЕР = КОРЕНЬ / "tools" / "run_checks.py"
РЕЕСТР = КОРЕНЬ / "tools" / "ci_checks.yaml"

провалов = 0


def проверить(имя: str, условие: bool, подробность: str = "") -> None:
    global провалов
    if условие:
        print(f"  ✓ {имя}")
    else:
        провалов += 1
        print(f"  ✗ {имя}" + (f": {подробность}" if подробность else ""))


def прогнать(записи: list[dict], контур: str = "public") -> tuple[int, str]:
    """Раннер на игрушечном реестре: настоящий не трогаем."""
    with tempfile.NamedTemporaryFile("w", suffix=".yaml", encoding="utf-8",
                                     delete=False) as ф:
        yaml.safe_dump({"проверки": записи}, ф, allow_unicode=True, sort_keys=False)
        путь = ф.name
    готово = subprocess.run(
        [sys.executable, str(РАННЕР), "--class", контур, "--registry", путь],
        capture_output=True, text=True, cwd=КОРЕНЬ)
    Path(путь).unlink()
    return готово.returncode, готово.stdout + готово.stderr


ЗЕЛЁНАЯ = {"id": "зелёная", "команда": "true", "класс": "public",
           "блокирует": True, "зачем": "заведомо проходит"}
КРАСНАЯ = {"id": "красная", "команда": "false", "класс": "public",
           "блокирует": True, "зачем": "заведомо падает"}
ПРЕДУПРЕЖДАЮЩАЯ = {"id": "предупреждающая", "команда": "false", "класс": "public",
                   "блокирует": False, "зачем": "падает, но не блокирует"}


def main() -> int:
    print("Сторож раннера проверок")

    # 1. Блокирующая красит прогон.
    код, вывод = прогнать([ЗЕЛЁНАЯ, КРАСНАЯ])
    проверить("упала блокирующая — прогон FAIL", код == 1, f"код {код}")
    проверить("в итоге назван виновник",
              "ПРОВАЛ (блокирует)  красная" in вывод)

    # 2. Не блокирующая не красит, но и не молчит. Это главное отличие от
    #    тихого пропуска: провал виден в логе и в сводке.
    код, вывод = прогнать([ЗЕЛЁНАЯ, ПРЕДУПРЕЖДАЮЩАЯ])
    проверить("упала не блокирующая — прогон PASS", код == 0, f"код {код}")
    проверить("но провал напечатан",
              "провал (не блокирует)  предупреждающая" in вывод)

    # 3. Ради чего всё затевалось: падение первой не отменяет следующие.
    #    На `bash -e` третья проверка не исполнилась бы вовсе.
    код, вывод = прогнать([КРАСНАЯ,
                           dict(ЗЕЛЁНАЯ, id="после_красной"),
                           dict(ЗЕЛЁНАЯ, id="ещё_позже")])
    проверить("после падения остальные исполняются",
              "ok" in вывод and "после_красной" in вывод and "ещё_позже" in вывод)
    м = re.search(r"прогнано (\d+), прошли (\d+), упали (\d+)", вывод)
    проверить("сводка считает все три", bool(м) and м.groups() == ("3", "2", "1"),
              м.group(0) if м else "сводки нет")

    # 4. Объявленный, но отсутствующий вход — пропуск с названным путём.
    код, вывод = прогнать([dict(ЗЕЛЁНАЯ, id="без_данных",
                                требует=["data/такого-файла-нет.yaml"])])
    проверить("нет входных данных — проверка не запускается", код == 0, f"код {код}")
    проверить("и путь назван",
              "НЕТ ДАННЫХ" in вывод and "data/такого-файла-нет.yaml" in вывод)
    проверить("пропуск не считается прошедшей проверкой",
              "прогнано 0" in вывод and "пропущено без данных 1" in вывод)

    # 5. Реестр не пускает противоречивую запись.
    код, вывод = прогнать([ЗЕЛЁНАЯ, dict(ЗЕЛЁНАЯ)])
    проверить("дубликат id отвергается", код != 0 and "дубликат" in вывод)
    код, вывод = прогнать([dict(ЗЕЛЁНАЯ, класс="internal", блокирует=True)],
                          контур="internal")
    проверить("внутренняя не может блокировать",
              код != 0 and "не в классе public" in вывод)

    # 6. Настоящий реестр: команды указывают на существующие файлы. Опечатка
    #    в пути дала бы вечно падающую проверку, а не отсутствующую.
    записи = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))["проверки"]
    пропали = []
    for з in записи:
        for кусок in re.findall(r"tools/[\w./-]+\.(?:py|js|php)", з["команда"]):
            if not (КОРЕНЬ / кусок).exists():
                пропали.append(f'{з["id"]}: {кусок}')
    проверить("все инструменты реестра на месте", not пропали, "; ".join(пропали))

    имена = [з["id"] for з in записи]
    проверить("имена в реестре уникальны", len(имена) == len(set(имена)))

    без_объяснения = [з["id"] for з in записи
                      if not з.get("блокирует") and not з.get("решение")]
    проверить("у каждой не блокирующей записано решение", not без_объяснения,
              ", ".join(без_объяснения))

    публичные = [з for з in записи if з["класс"] == "public"]
    проверить("публичный контур не пуст", len(публичные) >= 20,
              f"их {len(публичные)}")

    print(f"\nпровалов: {провалов}")
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
