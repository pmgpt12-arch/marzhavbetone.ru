#!/usr/bin/env python3
"""Страница товара не обещает того, чего нет в его файлах.

Дефект, ради которого написана проверка, прожил полтора месяца и стоил
доверия. Утверждение «Тексты прошли вычитку юристом в типовой редакции»
сняли 15.08.2026 с комплекта P1 — подтвердить его нечем: заключения юриста
в репозитории нет, есть запись владельца с его слов, и относится она к
редакции, которую с тех пор пересобрали. Со ступени «Заказчик не оплачивает
работы» то же утверждение не сняли, и дешёвый товар продолжал обещать
проверку, которой дорогой уже не обещал.

Проверка выводится из файлов, а не из списка запрещённых слов: страница
вправе утверждать про вычитку ровно тогда, когда это же утверждение стоит
хотя бы в одном документе, который покупатель скачивает. Список слов
устарел бы молча; выводимое правило — нет.

Второй случай той же природы — доля совпадения текста с другим комплектом.
На странице ступени стояло «27 процентов у таблицы расчёта». Числа не
производил ни один генератор: оно было посчитано сравнением сырого XML, где
в одном файле кириллица закодирована сущностями, а в другом нет, и занижало
совпадение в пользу продавца. Пока такой меры нет в коде, её нет и на
витрине.

    python3 tools/check_storefront_claims.py

Код возврата 1, если страница обещает непроверяемое.
"""
from __future__ import annotations

import pathlib
import re
import sys
import zipfile

SITE = pathlib.Path(__file__).resolve().parents[1]
STORAGE = SITE / "products-storage"
CONFIG = SITE / "products-config.php"

# Положительное утверждение о вычитке. Отрицание и оговорка («вычитку
# юристом не проходили», «вычиткой юристом она не является») — не обещание,
# а честное ограничение, и его ловить нельзя.
ВЫЧИТКА_НА_СТРАНИЦЕ = re.compile(
    r"(?<!не )(прошли|прошёл|прошла|проходили|проходил) вычитку юристом")
ВЫЧИТКА_В_ФАЙЛЕ = re.compile(r"(прошли|прошёл|прошла) вычитку юристом")

ДОЛЯ_СОВПАДЕНИЯ = re.compile(r"[Сс]овпадени\w*\s+текста[^.]{0,80}процент")

ЗАПИСЬ_КАТАЛОГА = re.compile(
    r"'(?P<sku>[a-z][a-z0-9]*)'\s*=>\s*\[(?P<body>.*?)\]", re.S)
ПАПКА = re.compile(r"'dir'\s*=>\s*'(?P<dir>[^']+)'")


def видимый_текст(html: str) -> str:
    """Текст страницы без скриптов: JSON-LD повторяет ответы FAQ дословно,
    и одно утверждение считалось бы дважды."""
    без_скриптов = re.sub(r"<script.*?</script>", " ", html, flags=re.S)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", без_скриптов))


def текст_документа(path: pathlib.Path) -> str:
    try:
        with zipfile.ZipFile(path) as архив:
            сырое = архив.read("word/document.xml").decode("utf-8")
    except (KeyError, OSError, zipfile.BadZipFile):
        return ""
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", сырое))


def каталог() -> dict[str, str]:
    """sku → папка выдачи, прочитанная из боевого конфига, а не из списка."""
    if not CONFIG.is_file():
        return {}
    текст = CONFIG.read_text(encoding="utf-8")
    начало = текст.find("function mvb_products()")
    if начало < 0:
        return {}
    найдено: dict[str, str] = {}
    for запись in ЗАПИСЬ_КАТАЛОГА.finditer(текст, начало):
        папка = ПАПКА.search(запись.group("body"))
        if папка:
            найдено[запись.group("sku")] = папка.group("dir")
    return найдено


def main() -> int:
    товары = каталог()
    if not товары:
        print("НЕТ ДАННЫХ: каталог товаров не прочитан из products-config.php")
        return 0

    беды: list[str] = []
    проверено = 0
    for sku, папка in sorted(товары.items()):
        страницы = sorted((SITE / "products").glob(f"{sku}-*.html"))
        if not страницы:
            continue
        каталог_выдачи = STORAGE / папка
        файлы = sorted(каталог_выдачи.glob("*.docx")) if каталог_выдачи.is_dir() else []
        в_файлах = any(ВЫЧИТКА_В_ФАЙЛЕ.search(текст_документа(f)) for f in файлы)

        for страница in страницы:
            проверено += 1
            текст = видимый_текст(страница.read_text(encoding="utf-8"))
            имя = страница.relative_to(SITE)
            if ВЫЧИТКА_НА_СТРАНИЦЕ.search(текст) and not в_файлах:
                беды.append(
                    f"{имя}: страница обещает вычитку юристом, но ни один из "
                    f"{len(файлы)} файлов выдачи {папка} её не утверждает. "
                    "Либо снять утверждение со страницы, либо пересобрать файлы")
            доля = ДОЛЯ_СОВПАДЕНИЯ.search(текст)
            if доля:
                беды.append(
                    f"{имя}: названа доля совпадения текста с другим комплектом "
                    f"(«{доля.group(0)[:70]}…»). Такой меры в коде нет, и прежнее "
                    "число было посчитано неверно — сравнением сырого XML")

    for беда in беды:
        print(f"  ✗ {беда}")
    print(f"\nСтраниц товаров проверено: {проверено}, дефектов: {len(беды)}")
    if not беды:
        print("Ни одна страница не обещает того, чего нет в её файлах.")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
