#!/usr/bin/env python3
"""Размеченные случаи ворот доказательства референсов.

Зачем отдельный прогон. Сегодня ни один ролик не стоит на стадии
производства, поэтому `check_reel_refs.py` на репозитории всегда зелёный —
и неотличим от проверки, которой нет. Случаи ниже поднимают стадию нарочно
и требуют отказа с названной причиной.

    python3 tools/test_check_reel_refs.py
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_reel_refs as гейт  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

ЦЕЛАЯ_КАРТОЧКА = {
    "id": "abc123", "source": "file", "url": "https://instagram.com/reel/abc123",
    "author": "nalogi_prosto", "date": "2026-08-14", "duration_sec": 24.0,
    "views": 310000, "likes": 8800, "comments": 540,
    "hook_type": "возражение на первом слове",
    "first_seconds": "крупно документ, поверх три слова",
    "shot_rhythm": "рез каждые 2 с",
    "avg_beat_sec": 2.0,
    "video_static_ratio": "70/30",
    "text_style": "четыре слова по центру",
    "voice_style": "разговорный, без диктора",
    "conflict": "вы платите за то, чего не заказывали",
    "curiosity_gap": "сумму называют на 12-й секунде",
    "escalation": "пример → норма → цена ошибки",
    "payoff": "формулировка, которую надо найти у себя",
    "cta_type": "слово в директ",
    "why_relevant": "та же боль: деньги удерживает вторая сторона",
    "judged_by": "сессия 23.08.2026",
}

ЦЕЛЫЙ_МАНИФЕСТ = {
    "reel": "99-proverka",
    "candidates": [
        {"card": "a", "verdict": "selected", "why": "механика ближе всех"},
        {"card": "b", "verdict": "rejected", "why": "личный блог, лицо в кадре"},
        {"card": "c", "verdict": "rejected", "why": "тема не про деньги"},
    ],
    "what_to_adapt": ["структура крючка", "ритм резов", "разворот на 12-й секунде"],
    "what_not_to_copy": [
        "чужой текст и реплики",
        "бренд и автора",
        "лицо в кадре",
        "музыку без прав",
    ],
}

провалов = 0


def случай(имя: str, беды: list[str], ожидание: str) -> None:
    global провалов
    if any(ожидание in беда for беда in беды):
        print(f"ок        {имя}")
    else:
        провалов += 1
        print(f"НЕ ЛОВИТ  {имя}: ждали «{ожидание}»")
        for беда in беды:
            print(f"    видим: {беда}")


def подготовить(каталог: Path, манифест: dict, карточки: dict[str, dict]) -> Path:
    (каталог / "cards").mkdir(parents=True, exist_ok=True)
    for имя, данные in карточки.items():
        (каталог / "cards" / f"{имя}.yaml").write_text(
            yaml.safe_dump(данные, allow_unicode=True), encoding="utf-8")
    путь = каталог / "99-proverka.yaml"
    путь.write_text(yaml.safe_dump(манифест, allow_unicode=True), encoding="utf-8")
    return путь


def прогнать(манифест: dict, карточки: dict[str, dict]) -> list[str]:
    with tempfile.TemporaryDirectory() as каталог:
        корень = Path(каталог)
        путь = подготовить(корень, манифест, карточки)
        прежний = гейт.КАРТОЧКИ
        гейт.КАРТОЧКИ = корень / "cards"
        try:
            return гейт.проверить(путь)
        finally:
            гейт.КАРТОЧКИ = прежний


def main() -> int:
    три = {имя: dict(ЦЕЛАЯ_КАРТОЧКА, id=f"id-{имя}") for имя in ("a", "b", "c")}

    # Эталон обязан проходить: иначе испорченные случаи ничего не доказывают —
    # они отказывали бы по той же причине, что и целый манифест.
    беды_эталона = прогнать(ЦЕЛЫЙ_МАНИФЕСТ, три)
    случай("эталон_проходит",
           ["нет расхождений"] if not беды_эталона else беды_эталона,
           "нет расхождений")

    мало = dict(ЦЕЛЫЙ_МАНИФЕСТ, candidates=ЦЕЛЫЙ_МАНИФЕСТ["candidates"][:1])
    случай("один_кандидат_не_выбор", прогнать(мало, три), "это не выбор")

    двое = dict(ЦЕЛЫЙ_МАНИФЕСТ, candidates=[
        dict(к, verdict="selected") for к in ЦЕЛЫЙ_МАНИФЕСТ["candidates"]])
    случай("два_выбранных", прогнать(двое, три), "нужен ровно один")

    без_основания = dict(ЦЕЛЫЙ_МАНИФЕСТ, candidates=[
        {"card": "a", "verdict": "selected"},
        *ЦЕЛЫЙ_МАНИФЕСТ["candidates"][1:]])
    случай("вердикт_без_основания", прогнать(без_основания, три),
           "не названо основание")

    сырая = {**три, "a": {k: v for k, v in ЦЕЛАЯ_КАРТОЧКА.items()
                          if k not in ("conflict", "payoff")}}
    случай("карточка_без_разбора", прогнать(ЦЕЛЫЙ_МАНИФЕСТ, сырая),
           "не разобрана")

    без_замера = {**три, "a": {k: v for k, v in ЦЕЛАЯ_КАРТОЧКА.items()
                               if k != "views"}}
    случай("карточка_без_чисел", прогнать(ЦЕЛЫЙ_МАНИФЕСТ, без_замера),
           "источник не дал полей")

    без_автора_разбора = {**три, "a": dict(ЦЕЛАЯ_КАРТОЧКА, judged_by="pending")}
    случай("разбор_без_автора", прогнать(ЦЕЛЫЙ_МАНИФЕСТ, без_автора_разбора),
           "кто его сделал — не назван")

    пропала = dict(ЦЕЛЫЙ_МАНИФЕСТ, candidates=[
        {"card": "нет-такой", "verdict": "selected", "why": "х"},
        *ЦЕЛЫЙ_МАНИФЕСТ["candidates"][1:]])
    случай("карточки_нет_на_диске", прогнать(пропала, три),
           "карточки нет-такой нет")

    бедный_перенос = dict(ЦЕЛЫЙ_МАНИФЕСТ, what_to_adapt=["крючок"])
    случай("перенос_одним_словом", прогнать(бедный_перенос, три),
           "механика переносится приёмами")

    for запрет, выкинуть in (("лицо", "лицо в кадре"), ("музыка", "музыку без прав"),
                             ("текст", "чужой текст и реплики")):
        урезанный = dict(ЦЕЛЫЙ_МАНИФЕСТ, what_not_to_copy=[
            п for п in ЦЕЛЫЙ_МАНИФЕСТ["what_not_to_copy"] if п != выкинуть])
        случай(f"не_назван_запрет_{запрет}", прогнать(урезанный, три),
               "не назван запрет")

    print(f"\nСлучаев: 12, не поймано: {провалов}")
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
