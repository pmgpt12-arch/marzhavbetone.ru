<?php
/**
 * Регресс: издания выдачи P5. Запуск: php tools/test_p5_editions.php
 *
 * Решением владельца 17.09.2026 из состава P5 снята сравнительная таблица
 * `09-sravnitelnaya-tablica.docx`: она сравнивала покупку со снятым с
 * продажи «Полным комплектом». Новые покупатели её получать не должны,
 * старые оплаченные заказы — не должны потерять то, за что заплатили.
 *
 * Почему одного удаления файла мало. Заказ запоминает только ИМЯ архива
 * (`delivery.items[sku]`), а download.php, не найдя файл в кэше,
 * пересобирает его из мастеров. Кэш чистится штатно: `rm -f
 * orders/delivery/*.zip` стоит в runbook выкладки. Значит после первой же
 * чистки старый оплаченный заказ получил бы новый состав под прежним
 * именем. Воспроизведено 17.09.2026: 12 файлов до, 11 после, имя одно.
 *
 * Отсюда издания: у каждого своё имя архива, таблица `editions` в каталоге
 * говорит, чего в издании нет, а download.php пересобирает ИМЕННО то
 * издание, что записано в заказе.
 *
 * Тест поднимает два заказа P5 — исторический с прежним именем и новый — и
 * требует: прежний архив с таблицей, новый без неё. Сети, кассы и секретов
 * не нужно; письма не отправляются (у заказов нет поля email).
 */
declare(strict_types=1);

$root = dirname(__DIR__);
$tmp = sys_get_temp_dir() . '/mvb-p5-editions-' . getmypid();
@mkdir($tmp, 0777, true);

foreach ([
    'ORDERS_DIR' => $tmp,
    'PRODUCTS_DIR' => $root . '/products-storage',
    'SITE_URL' => 'https://example.invalid',
    'ADMIN_EMAIL' => 'admin@example.invalid',
    'DELIVERY_TTL_DAYS' => 7,
    'YOOKASSA_SHOP_ID' => 'test',
    'YOOKASSA_SECRET_KEY' => 'test',
    'YOOKASSA_API_URL' => 'https://example.invalid',
    'YOOKASSA_MODE' => 'test',
] as $имя => $значение) {
    if (!defined($имя)) {
        define($имя, $значение);
    }
}
require $root . '/products-config.php';

const ТАБЛИЦА = '09-sravnitelnaya-tablica.docx';
const ПРЕЖНЕЕ = '07-uderzhaniya-shtrafy-zachety.zip';

$провалов = 0;
function проверка(string $имя, bool $ок, string $чем = ''): void
{
    global $провалов;
    if ($ок) { echo "  ок   {$имя}\n"; return; }
    $провалов++;
    echo "  ПРОВАЛ {$имя}" . ($чем !== '' ? ": {$чем}" : '') . "\n";
}

function состав(string $путь): array
{
    $z = new ZipArchive();
    if ($z->open($путь) !== true) { return []; }
    $r = [];
    for ($i = 0; $i < $z->numFiles; $i++) { $r[] = $z->getNameIndex($i); }
    $z->close();
    sort($r);
    return $r;
}

echo "Издания выдачи P5\n";

$каталог = mvb_products();
$текущее = (string)$каталог['p5']['zip'];

проверка('текущее издание — не прежнее имя', $текущее !== ПРЕЖНЕЕ, $текущее);
проверка('прежнее издание объявлено в каталоге',
    array_key_exists(ПРЕЖНЕЕ, mvb_zip_editions('p5')),
    implode(', ', array_keys(mvb_zip_editions('p5'))));

// --- Новый заказ: получает текущее издание --------------------------------
$новый = [
    'id'     => 'order_20260917_160000_new111',
    'status' => 'paid',
    'items'  => [['sku' => 'p5', 'name' => $каталог['p5']['name'], 'price' => $каталог['p5']['price']]],
    'total'  => $каталог['p5']['price'],
];
$ссылкиН = mvb_deliver_and_notify($новый);
$имяН = (string)($новый['delivery']['items']['p5'] ?? '');
$составН = состав(DELIVERY_DIR . '/' . $имяН);

проверка('новый заказ: выдача подготовлена', count($ссылкиН) === 1);
проверка('новый заказ: имя архива — текущее издание', $имяН === $текущее, $имяН);
проверка('новый заказ: таблицы в архиве нет',
    !in_array(ТАБЛИЦА, $составН, true), implode(', ', $составН));
проверка('новый заказ: файлов 11', count($составН) === 11, (string)count($составН));

// --- Исторический заказ: прежнее имя, прежний состав -----------------------
// Так выглядит запись заказа, оплаченного до 17.09.2026: в ней стоит имя
// архива, каким оно было на момент покупки.
$старый = [
    'id'     => 'order_20260101_120000_old222',
    'status' => 'paid',
    'items'  => [['sku' => 'p5', 'name' => $каталог['p5']['name'], 'price' => $каталог['p5']['price']]],
    'total'  => $каталог['p5']['price'],
    'delivery' => [
        'token'      => str_repeat('a', 32),
        'created_at' => '2026-01-01T12:00:00+00:00',
        'expires_at' => date('c', time() + 86400),
        'downloads'  => 0,
        'items'      => ['p5' => ПРЕЖНЕЕ],
    ],
];

// Кэш очищен — ровно шаг runbook `rm -f orders/delivery/*.zip`.
foreach (glob(DELIVERY_DIR . '/*.zip') ?: [] as $f) { unlink($f); }
проверка('кэш очищен: прежнего архива на диске нет',
    !is_file(DELIVERY_DIR . '/' . ПРЕЖНЕЕ));

// Ровно та строка, что стоит в download.php при отсутствии файла в кэше.
$имяС = (string)$старый['delivery']['items']['p5'];
$путьС = mvb_build_product_zip('p5', $имяС);
$составС = $путьС ? состав($путьС) : [];

проверка('старый заказ: архив пересобран под прежним именем',
    $путьС !== null && basename((string)$путьС) === ПРЕЖНЕЕ, (string)$путьС);
проверка('старый заказ: таблица в архиве ЕСТЬ',
    in_array(ТАБЛИЦА, $составС, true), implode(', ', $составС));
проверка('старый заказ: файлов 12', count($составС) === 12, (string)count($составС));
проверка('старый заказ: состав не совпал с новым', $составС !== $составН);

// --- Издания не путаются между собой --------------------------------------
$путьН2 = mvb_build_product_zip('p5');
проверка('два издания лежат под разными именами',
    basename((string)$путьН2) !== basename((string)$путьС));
проверка('текущее издание не перезаписало прежнее',
    in_array(ТАБЛИЦА, состав((string)$путьС), true));

// --- Имя издания из заказа не подставляется в путь как есть ---------------
проверка('неизвестное имя издания отвергнуто',
    mvb_build_product_zip('p5', 'чужое-имя.zip') === null);
проверка('выход из каталога отвергнут',
    mvb_build_product_zip('p5', '../../../etc/passwd.zip') === null);

// --- Комплекты без изданий не задеты --------------------------------------
$p1 = mvb_build_product_zip('p1');
проверка('комплект без объявленных изданий собирается как прежде',
    $p1 !== null && basename((string)$p1) === (string)$каталог['p1']['zip'],
    (string)$p1);

// Уборка
foreach (glob(DELIVERY_DIR . '/*') ?: [] as $f) { @unlink($f); }
@rmdir(DELIVERY_DIR);
foreach (glob($tmp . '/*') ?: [] as $f) { if (is_file($f)) { @unlink($f); } }
@rmdir($tmp);

if ($провалов) { echo "\nпровалов: {$провалов}\n"; exit(1); }
echo "\nновые покупатели получают 11 файлов без сравнительной таблицы; "
   . "заказ, оплаченный прежде, пересобирает свои 12 — включая её\n";
exit(0);
