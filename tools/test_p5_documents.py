def test_тексты_совпадают_с_отчётами() -> None:
    """Тексты теста — блоки отчётов, а не пересказ."""
    проблемы = []
    for текст, ключ, раздел in ИСТОЧНИКИ:
        блоки = блоки_text(отчёт(ключ))
        кандидаты = {норм(б) for б in блоки} | {норм(с) for б in блоки for с in б.split("\n")}
        if норм(текст) not in кандидаты:
            проблемы.append(f"{ключ} {раздел}: нет блока «{норм(текст)[:60]}…»")
    исходные = [норм(б).casefold() for б in блоки_text(отчёт("FOLLOW_UP"))]
    for имя in (DOCX_02, DOCX_03):
        for фраза in ЗАПРЕЩЕНО[имя]:
            if not any(норм(фраза).casefold() in б for б in исходные):
                проблемы.append(f"{имя}: запрет «{фраза}» не цитата FOLLOW_UP")
    for фраза in list(ЗАПРЕЩЕНО[PDF_07])[1:]:
        if not any(норм(фраза).casefold() in б for б in исходные):
            проблемы.append(f"{PDF_07}: запрет «{фраза}» не цитата FOLLOW_UP")
    assert not проблемы, "\n  ".join(["тексты теста разошлись с отчётами Р-026:"] + проблемы)


