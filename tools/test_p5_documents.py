def test_03_вариант_2а_отдельной_строкой() -> None:
    """§2.4 PLENUM_RECHECK_2: неоднородность — отдельный вариант, только для неденежного.

    Строка стоит отдельным абзацем между сроком (2) и договорным запретом (3),
    а не слита со сроком, и несёт все три ограничения своей оговорки.
    """
    абзацы = абзацы_docx(DOCX_03)
    нужные = [норм(в) for в in (ВАРИАНТ_1_03, ВАРИАНТ_2_03, ВАРИАНТ_2А_03, ВАРИАНТ_3_03)]
    for н in нужные:
        assert н in абзацы, f"{DOCX_03}: нет отдельного абзаца «{н[:70]}…»"
    i = абзацы.index(нужные[2])
    assert абзацы[i - 1] == нужные[1] and абзацы[i + 1] == нужные[3], (
        f"{DOCX_03}: вариант 2-а не между сроком и договорным запретом: {абзацы[i-1:i+2]}")
    for условие in ("не денежное", "на дату заявления о зачёте",
                    "к неустойке, процентам и убыткам не применяется",
                    "не однородно с денежным требованием Подрядчика"):
        assert условие in абзацы[i], f"{DOCX_03}: в варианте 2-а нет «{условие}»"
    assert not any("срок" in а and "однородно" in а for а in абзацы), (
        f"{DOCX_03}: неоднородность слита со сроком в одну строку")


