#!/usr/bin/env python3
"""Формы P2 01–06 в архиве покупателя: только текст документа.

Класс ошибки: служебный текст продавца в выдаваемой форме → нет разделения
текста для покупателя и текста для автора → покупатель получает документ,
который нельзя передать контрагенту как есть.

Правило: в формах, входящих в покупательский ZIP, допускаются только текст
документа, нейтральные поля и подтверждённые реквизиты. Внутренний текст
продавца в них запрещён.

Что проверяется:

1. Состав берётся из архива, который собирает настоящий
   `mvb_build_product_zip('p2')` (PHP), а не из списка в тесте. Нет PHP или
   сборщик не вернул архив — проверка падает, а не пропускается: без
   сборщика неизвестно, что уходит покупателю.
2. Фразы Baseline (отчёт `tools/candidates/MB001_R2_P2_FORMS_R3.md`) ищутся
   в пользовательском тексте DOCX: абзацы тела, ячейки таблиц, колонтитулы.
   Не в сыром XML — там фраза может быть разбита на несколько `<w:t>`.
   Перед сравнением: регистр, кавычки и пробелы нормализуются.
3. Реквизиты (дата, подпись, расшифровка) — по таблице решений из отчёта.
4. Изменённые формы лежат в архиве и совпадают с исходником по sha256.

Формы, по которым решение не принято, помечены `xfail(strict=True)` с номером
STOP. Они не исключаются молча: если такая форма начнёт проходить, strict
xfail уронит прогон — STOP нужно пересмотреть и снять отдельным решением.

Запуск: python3 -m pytest tools/test_p2_forms_buyer_text.py
    или python3 tools/test_p2_forms_buyer_text.py
"""
from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

SITE = Path(__file__).resolve().parent.parent
STORAGE = SITE / "products-storage"
KIT = STORAGE / "02-dopraboty-bez-poter"
SKU = "p2"

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
КОЛОНТИТУЛ = re.compile(r"word/(header|footer)\d*\.xml$")

# ── Baseline ────────────────────────────────────────────────────────────
# Дословно из форм на голове #312 (0bc99fc). Каждая фраза — пометка для
# покупателя или продавца, а не текст документа для второй стороны.
# 00-INSTRUKCIYA §6 сама называет их «пометками для вас».
ВО_ВСЕХ_ФОРМАХ = (
    # прежнее имя товара; в формах на 0bc99fc не найдено — держится сторожем
    "Допработы без потерь",
    # строка-подсказка под заголовком
    "Заполните поля в квадратных скобках и удалите подсказки перед отправкой",
    # чек-лист продавца: заголовок и пять пунктов таблицы
    "Контроль перед использованием",
    "Сверено с договором и приложениями",
    "Проверены полномочия подписанта и адресат",
    "Приложения названы и приложены",
    "Зафиксирован доказуемый канал отправки",
    "Юридически значимые формулировки проверены специалистом",
    # оговорка для покупателя под таблицей
    "Важно: шаблон не заменяет анализ договора",
    # верхний колонтитул
    "МАРЖА В БЕТОНЕ / РАБОЧИЙ ШАБЛОН",
    # нижний колонтитул: сайт продавца
    "marzhavbetone.ru",
)
# нижний колонтитул: внутренняя редакция «версия 21.07.2026»
ВНУТРЕННЯЯ_РЕДАКЦИЯ = re.compile(r"версия \d{2}\.\d{2}\.\d{4}")

ПО_ФОРМАМ = {
    "04": (
        # указание покупателю, как готовить акт, — не текст акта
        "Форму и состав подписантов сверить с актуальными требованиями",
        # пометка о характере файла в заголовке
        "рабочая заготовка",
    ),
    "06": (
        # указание покупателю до отправки; оно же — 00-INSTRUKCIYA, шаг А7
        "Основание и допустимость приостановки обязательно проверить "
        "по договору и закону до отправки",
    ),
}

# ── Решения по реквизитам ──────────────────────────────────────────────
# True — поле нужно, False — не нужно, None — решения нет (STOP).
# Основания — в отчёте, раздел «Таблица решений по реквизитам».
РЕКВИЗИТЫ = {
    "01": {"дата": True, "подпись": True, "расшифровка": True},
    "02": None,
    "03": {"дата": True, "подпись": True, "расшифровка": True},
    "04": None,
    "05": None,
    "06": {"дата": True, "подпись": True, "расшифровка": True},
}
ПОЛЕ = {
    "дата": "Дата: [___]",
    "подпись": "Подпись: [___]",
    "расшифровка": "Расшифровка подписи: [___]",
}

STOP = {
    "02": "STOP-P2-R3-1: 02 — приложение к допсоглашению 11 (случай А) и "
          "вложение к уведомлению 03 (случай Б); состав подписей у них разный, "
          "из назначения формы он не выводится",
    "04": "STOP-P2-R3-2: 04 — форма и состав подписантов акта заданы "
          "требованиями, проектом и системой заказчика; форма сама велит их "
          "сверять — подпись не выводится из назначения",
    "05": "STOP-P2-R3-3: 05 — заголовок «Соглашение / уведомление»: у "
          "соглашения подписывают обе стороны, у уведомления — отправитель; "
          "инструкция применяет 05 как расчёт перед 12",
}
ФОРМЫ = ("01", "02", "03", "04", "05", "06")


def _параметры():
    return [pytest.param(н, id=н,
                         marks=pytest.mark.xfail(strict=True, reason=STOP[н]))
            if н in STOP else pytest.param(н, id=н)
            for н in ФОРМЫ]


# ── Извлечение и нормализация ──────────────────────────────────────────
def нормализовать(текст: str) -> str:
    текст = текст.casefold().replace("ё", "е")
    текст = re.sub(r"[«»„“”‟\"'’‘`]", '"', текст)
    return re.sub(r"\s+", " ", текст).strip()


def _абзацы_части(xml: bytes) -> list[str]:
    """Текст каждого `<w:p>` части, включая абзацы в ячейках таблиц."""
    корень = ET.fromstring(xml)
    абзацы = []
    for p in корень.iter(W + "p"):
        куски = []
        for узел in p.iter():
            if узел.tag == W + "t" and узел.text:
                куски.append(узел.text)
            elif узел.tag in (W + "tab", W + "br"):
                куски.append(" ")
        текст = "".join(куски).strip()
        if текст:
            абзацы.append(текст)
    return абзацы


def части_docx(данные: bytes) -> dict[str, list[str]]:
    """{часть: абзацы} для тела и колонтитулов документа."""
    with zipfile.ZipFile(__import__("io").BytesIO(данные)) as z:
        имена = [n for n in z.namelist()
                 if n == "word/document.xml" or КОЛОНТИТУЛ.match(n)]
        return {n: _абзацы_части(z.read(n)) for n in sorted(имена)}


def пользовательский_текст(данные: bytes) -> str:
    return нормализовать(" \n".join(
        a for абзацы in части_docx(данные).values() for a in абзацы))


def найденные_фразы(номер: str, данные: bytes) -> list[str]:
    текст = пользовательский_текст(данные)
    найдено = [ф for ф in ВО_ВСЕХ_ФОРМАХ + ПО_ФОРМАМ.get(номер, ())
               if нормализовать(ф) in текст]
    найдено += [m.group(0) for m in ВНУТРЕННЯЯ_РЕДАКЦИЯ.finditer(текст)]
    return найдено


# ── Архив настоящим сборщиком ──────────────────────────────────────────
def собрать_архив(каталог: Path) -> Path:
    php = shutil.which("php")
    if not php:
        pytest.fail("BLOCKED: нет PHP — фактический состав выдачи P2 "
                    "не проверить. Это ошибка, а не пропуск.")
    заказы = каталог / "orders"
    заказы.mkdir()
    код = (f"define('ORDERS_DIR', {str(заказы)!r});"
           f"define('PRODUCTS_DIR', {str(STORAGE)!r});"
           f"require {str(SITE / 'products-config.php')!r};"
           f"echo (string)mvb_build_product_zip({SKU!r});")
    r = subprocess.run([php, "-r", код], capture_output=True, text=True)
    путь = Path(r.stdout.strip()) if r.stdout.strip() else None
    if r.returncode != 0 or not путь or not путь.is_file():
        pytest.fail(f"BLOCKED: mvb_build_product_zip('{SKU}') не вернул "
                    f"архив (код {r.returncode}): {r.stdout} {r.stderr}")
    return путь


@pytest.fixture(scope="module")
def архив() -> dict[str, bytes]:
    with tempfile.TemporaryDirectory() as tmp:
        путь = собрать_архив(Path(tmp))
        with zipfile.ZipFile(путь) as z:
            assert z.testzip() is None, "архив P2 повреждён"
            return {n: z.read(n) for n in z.namelist()}


def форма(архив: dict[str, bytes], номер: str) -> tuple[str, bytes]:
    имена = [n for n in архив if re.fullmatch(rf"{номер}-[^/]+\.docx", n)]
    assert len(имена) == 1, f"в архиве P2 форм {номер}: {имена}"
    return имена[0], архив[имена[0]]


# ── Проверки ───────────────────────────────────────────────────────────
def test_архив_содержит_формы_01_06(архив) -> None:
    for номер in ФОРМЫ:
        форма(архив, номер)


@pytest.mark.parametrize("номер", _параметры())
def test_в_форме_нет_служебного_текста(архив, номер) -> None:
    имя, данные = форма(архив, номер)
    найдено = найденные_фразы(номер, данные)
    assert not найдено, (f"{имя}: служебный текст продавца в форме "
                         f"покупателя:\n  " + "\n  ".join(найдено))


@pytest.mark.parametrize("номер", _параметры())
def test_реквизиты_по_таблице_решений(архив, номер) -> None:
    решение = РЕКВИЗИТЫ[номер]
    assert решение is not None, f"{номер}: решения по реквизитам нет"
    имя, данные = форма(архив, номер)
    тело = {нормализовать(a) for a in части_docx(данные)["word/document.xml"]}
    ошибки = []
    for реквизит, нужен in решение.items():
        есть = нормализовать(ПОЛЕ[реквизит]) in тело
        if есть != нужен:
            ошибки.append(f"{реквизит}: поле {'нужно' if нужен else 'не нужно'}, "
                          f"в форме {'есть' if есть else 'нет'}")
    assert not ошибки, f"{имя}: " + "; ".join(ошибки)


@pytest.mark.parametrize("номер", [н for н in ФОРМЫ if РЕКВИЗИТЫ[н]])
def test_изменённая_форма_уходит_покупателю(архив, номер) -> None:
    имя, данные = форма(архив, номер)
    исходник = KIT / имя
    assert исходник.is_file(), f"{имя} есть в архиве, но нет в {KIT}"
    assert (hashlib.sha256(данные).hexdigest()
            == hashlib.sha256(исходник.read_bytes()).hexdigest()), (
        f"{имя}: в архиве не та версия, что в репозитории")


# ── Сторож самого детектора ────────────────────────────────────────────
def test_детектор_видит_фразу_разбитую_на_куски_и_в_колонтитуле() -> None:
    """Фраза в двух `<w:t>`, другой регистр и кавычки — всё равно находится."""
    import io
    тело = (f'<w:document xmlns:w="{W[1:-1]}"><w:body><w:p>'
            '<w:r><w:t>Контроль  перед</w:t></w:r>'
            '<w:r><w:t xml:space="preserve"> ИСПОЛЬЗОВАНИЕМ</w:t></w:r>'
            '</w:p><w:p><w:r><w:t>Комплект «ДОПРАБОТЫ\u00a0БЕЗ ПОТЕРЬ»</w:t></w:r></w:p>'
            '</w:body></w:document>')
    низ = (f'<w:ftr xmlns:w="{W[1:-1]}"><w:p><w:r><w:t>'
           'Форма  •  версия 01.02.2026</w:t></w:r></w:p></w:ftr>')
    буфер = io.BytesIO()
    with zipfile.ZipFile(буфер, "w") as z:
        z.writestr("word/document.xml", тело)
        z.writestr("word/footer1.xml", низ)
    найдено = найденные_фразы("01", буфер.getvalue())
    assert "Контроль перед использованием" in найдено
    assert "версия 01.02.2026" in найдено
    assert "Допработы без потерь" in найдено
    assert нормализовать("«Шаблон»") == нормализовать('"шаблон"')


