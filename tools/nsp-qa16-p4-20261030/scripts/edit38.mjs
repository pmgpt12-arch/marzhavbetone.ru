import fs from 'node:fs/promises';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
const root='/workspace/scratch/1c70cef937ec/qa16-p4';
const outputDir='/workspace/scratch/1c70cef937ec/outputs/qa16-p4';
await fs.mkdir(outputDir,{recursive:true});
const w=await SpreadsheetFile.importXlsx(await FileBlob.load(root+'/source/38-reestr-id.xlsx'));
await fs.writeFile(root+'/internal/38-before.png',new Uint8Array(await(await w.render({sheetName:'Реестр',range:'A1:K6',scale:1})).arrayBuffer()));
console.log(w.help('worksheet.*',{search:'print|pageSetup|PageSetup|paper',include:'index,examples,notes',maxChars:4500}).ndjson);
await fs.writeFile(root+'/internal/38-import-inspect.json',(await w.inspect({kind:'sheet,definedName',maxChars:3000})).ndjson);
const s=w.worksheets.getItem('Реестр');
s.getRange('L3:Q103').copyFrom(s.getRange('F3:K103'),'all');
s.getRange('L3:Q3').values=[['Версия документа','Опись номер и дата','Адресат и представитель','Дата получения','Подтверждение получения','Ответ номер и дата']];
s.getRange('L4:Q103').clear({applyTo:'contents'});
s.getRange('L3:Q103').format.columnWidth=22;
s.getRange('L3:Q103').format.wrapText=true;
s.getRange('A3:Q3').format.rowHeight=42;
s.getRange('O4:O103').setNumberFormat('dd.mm.yyyy');
s.getRange('L3:Q3').format.font={name:'Arial',size:10,bold:true,color:'#FFFFFF'};
const instructions=w.worksheets.getItem('Инструкция');
instructions.getRange('A3').values=[['По каждой позиции сохраните исходные реквизиты в A:K. В L укажите версию документа, в M номер и дату описи, в N адресата и уполномоченного представителя, в O фактическую дату получения, в P номер квитанции ЭДО или ссылку на подтверждение, в Q реквизиты ответа. Отправка и получение являются отдельными событиями. Исправленную версию регистрируйте новой строкой с тем же шифром и новой версией, сохраняя предыдущую запись.']];
instructions.getRange('A3').format.rowHeight=150;
instructions.getRange('A3').format.wrapText=true;
w.recalculate();
await fs.writeFile(root+'/internal/38-after-right.png',new Uint8Array(await(await w.render({sheetName:'Реестр',range:'L1:Q7',scale:1.3})).arrayBuffer()));
await fs.writeFile(root+'/internal/38-after-instruction.png',new Uint8Array(await(await w.render({sheetName:'Инструкция',range:'A1:A3',scale:1.3})).arrayBuffer()));
await fs.writeFile(root+'/internal/38-final-inspect.json',(await w.inspect({kind:'table',range:'Реестр!L3:Q5',maxChars:2500,tableMaxRows:3,tableMaxCols:6})).ndjson);
await (await SpreadsheetFile.exportXlsx(w)).save(outputDir+'/38-reestr-id.xlsx');
console.log('38 EXPORTED');
