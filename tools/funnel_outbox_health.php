<?php
/**
 * Здоровье сборщика событий числами. Запуск на хостинге: php tools/funnel_outbox_health.php
 *
 * ЗАЧЕМ. Сборщик пишет молча и обязан писать молча: отказ записи не имеет
 * права дойти до посетителя. Значит единственный способ узнать, что он не
 * пишет уже вторые сутки, — спросить его самого.
 *
 * ТОЛЬКО ИЗ КОМАНДНОЙ СТРОКИ. Файл лежит в каталоге сайта, то есть после
 * заливки доступен по HTTP. Отдавать через веб путь к сборщику и число
 * накопленных событий незачем никому: запуск из веба отклоняется.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require_once dirname(__DIR__) . '/mvb_funnel.php';

$здоровье = mvb_funnel_outbox_status();

if (in_array('--json', $argv, true)) {
    echo json_encode($здоровье, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), "\n";
    exit($здоровье['usable'] ? 0 : 1);
}

echo "каталог сборщика: {$здоровье['dir']}\n";
echo 'пригоден: ' . ($здоровье['usable'] ? 'да' : 'НЕТ — ' . $здоровье['reason']) . "\n";
echo "ждут слива: {$здоровье['pending_count']}\n";
echo "в карантине: {$здоровье['quarantined_count']}\n";
echo "отказов записи: {$здоровье['append_failures']}\n";
$доля = $здоровье['max_bytes'] > 0
    ? round(100 * $здоровье['total_bytes'] / $здоровье['max_bytes'], 1) : 0;
echo "занято: {$здоровье['total_bytes']} из {$здоровье['max_bytes']} байт ({$доля}%)\n";
echo 'возраст старейшего файла, с: '
     . ($здоровье['oldest_pending_age_seconds'] ?? '—') . "\n";

// Ненулевой код — повод посмотреть, а не повод чинить сайт: сайт работает
// и при непригодном сборщике, это и есть главный инвариант этапа.
exit($здоровье['usable'] ? 0 : 1);
