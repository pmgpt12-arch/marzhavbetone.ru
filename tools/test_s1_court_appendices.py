def blocks(doc):
    for el in doc.element.body.iterchildren():
        tag = el.tag.rsplit("}", 1)[-1]
        if tag == "p":
            yield Paragraph(el, doc)
        elif tag == "tbl":
            yield Table(el, doc)


def section(doc, start: str) -> list:
    out, on = [], False
    for b in blocks(doc):
        if isinstance(b, Paragraph) and b.style.name.startswith("Heading"):
            if on:
                break
            on = b.text.startswith(start)
            continue
        if on:
            out.append(b)
    return out


def text_of(items) -> str:
    parts = []
    for b in items:
        if isinstance(b, Paragraph):
            parts.append(b.text)
        else:
            parts += [c.text for row in b.rows for c in row.cells]
    return "\n".join(parts)


def rows(t: Table) -> list[list[str]]:
    return [[c.text for c in r.cells] for r in t.rows]


def attachment_table(items) -> Table:
    found = [b for b in items if isinstance(b, Table) and rows(b)[0] == LIST_HEAD]
    assert len(found) == 1, f"в разделе Б нет одного перечня приложений {LIST_HEAD}"
    return found[0]


def selected(book: Path) -> list[tuple[str, str, int]]:
    """Строки «Реестра приложений» с «Да» в колонке «К иску», в порядке реестра."""
    ws = load_workbook(book)["Реестр приложений"]
    return [(ws.cell(r, 2).value, ws.cell(r, 3).value, ws.cell(r, 4).value)
            for r in range(5, 55) if ws.cell(r, 7).value == "Да"]


def make_register(dst: Path) -> Path:
    """Копия настоящего файла 04 с заполненным «Реестром приложений»."""
    shutil.copyfile(N04, dst)
    wb = load_workbook(dst)
    ws = wb["Реестр приложений"]
    for r, (nd, sheets, to_court) in REGISTER.items():
        ws.cell(r, 3).value = nd or None
        ws.cell(r, 4).value = sheets
        ws.cell(r, 5).value = "Копия" if to_court == "Да" else None
        ws.cell(r, 6).value = "Нет"
        ws.cell(r, 7).value = to_court
        ws.cell(r, 9).value = "Да" if to_court == "Да" else None
    wb.save(dst)
    return dst


def fill_claim(src: Path, book: Path, dst: Path) -> Path:
    """Иск, заполненный покупателем: плейсхолдеры, перечень из реестра,
    лишние пустые строки перечня удалены."""
    doc = Document(src)
    for b in blocks(doc):
        pars = [b] if isinstance(b, Paragraph) else [p for r in b.rows for c in r.cells for p in c.paragraphs]
        for p in pars:
            for run in p.runs:
                for k, v in FILL.items():
                    run.text = run.text.replace(k, v)
    t = attachment_table(section(doc, "Раздел Б."))
    entries = selected(book)
    body = t.rows[1:]
    assert len(entries) <= len(body)
    for row, (name, nd, sheets) in zip(body, entries):
        row.cells[1].text = f"{name}: {nd}"
        row.cells[2].text = str(sheets)
    for row in body[len(entries):]:
        t._tbl.remove(row._tr)
    doc.save(dst)
    return dst


