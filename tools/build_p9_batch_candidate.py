def fill(d,block):
 for line in block.strip().split('\n'):
  x=line.strip()
  if not x:continue
  p=d.add_paragraph()
  if x.startswith('# '):
   r=p.add_run(x[2:]);r.bold=True;r.font.size=Pt(11);r.font.color.rgb=G
  else:p.add_run(x)
def tab(d,heads,rows):
 t=d.add_table(rows=1,cols=len(heads));t.style='Table Grid'
 for i,h in enumerate(heads):t.rows[0].cells[i].text=h
 for row in rows:
  cells=t.add_row().cells
  for i,v in enumerate(row):cells[i].text=v
 for row in t.rows:
  for c in row.cells:
   for p in c.paragraphs:
    p.paragraph_format.space_after=Pt(2)
    for r in p.runs:r.font.name='Arial';r.font.size=Pt(8)
