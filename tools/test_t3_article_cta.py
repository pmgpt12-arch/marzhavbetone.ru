#!/usr/bin/env python3
"""Ступень t3 доступна из статей, которые разбирают её ситуацию.

Комплект «Односторонний акт или зачёт: возражения в срок» стоит 990 ₽ и
является входной ступенью двух кластеров диагностики: «Работы выполнены,
но не приняты» (S-2) и «Часть суммы удержана» (S-4). До 19.09.2026 из
статей на него не вело ни одной ссылки: замер `grep -rl "products/t3-"
--include=*.html` давал каталог, один бесплатный материал и диагностику,
и ноль статей.

Проверка закрывает именно этот разрыв и ровно на утверждённом списке.
Требовать ссылку на t3 со всех статей сайта она не должна и не требует:
статья про аванс или про дополнительные работы к этой ситуации отношения
не имеет, и ссылка оттуда была бы навязыванием, а не маршрутом.

Список статей здесь не «где уже стоит ссылка», а «где связка доказана»:
у каждой названа причина, и причина проверяема текстом статьи и графом
продукта в `diagnostika.html`. Ожидаемые название и адрес товара берутся
из `products-config.php` — единственного места, где они заданы; своей
копии у проверки нет, иначе она согласилась бы с расхождением.

    python3 tools/test_t3_article_cta.py
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ARTICLES = ROOT / "articles"

SKU = "t3"

# Статьи, где связка с t3 доказана содержанием и графом продукта.
# Значение — причина, она же читается в отчёте о падении.
ОБЯЗАНЫ_ВЕСТИ = {
    "raboty-ne-prinyaty":
        "разбирает односторонний акт (9 упоминаний) и прямо называет "
        "действие t3: «первым действием становится возражение в срок»; "
        "t3 — входная ступень кластера ks, чей основной комплект p3 в "
        "статье уже стоит",
    "garantiynoe-uderzhanie-v-ks-2-i-ks-3":
        "разбирает переименование удержания в зачёт по ст. 410 ГК РФ "
        "(7 упоминаний зачёта); t3 — входная ступень кластера uderzhanie, "
        "чей основной комплект p5 в статье уже стоит",
}

# Статьи, где связка спорна и ссылка не ставится намеренно. Проверка
# держит и это: молчаливое расползание ссылки по соседним темам — тот же
# дефект, что и её отсутствие, только в другую сторону.
НЕ_ДОЛЖНЫ_ВЕСТИ = {
    "avans-eto-ne-dengi-eto-kryuchok":
        "«односторонний» здесь про расторжение договора, а «зачёт» — про "
        "зачёт аванса в счёт работ; ситуации t3 в статье нет",
    "zakazchik-ne-oplachivaet-vypolnennye-raboty":
        "статья сама называет зачёт границей, где «шаблон бесполезен» и "
        "нужен юрист; ступень 990 ₽ этого кластера уже занята t1",
    "pretenziya-za-chuzhuyu-kommunalku":
        "решение владельца о составе товаров этой статьи не принято "
        "(p10 против p12), и ответ на претензию покрывает возражение",
}


def канон() -> tuple[str, str, int]:
    """Название, адрес карточки и цена t3 — из конфигурации сайта."""
    config = (ROOT / "products-config.php").read_text(encoding="utf-8")
    block = config[config.index("function mvb_products()"):]
    m = re.search(rf"'{SKU}'\s*=>\s*\[\s*\n\s*'name'\s*=>\s*'([^']*)',"
                  rf"\s*\n\s*'price'\s*=>\s*(\d+)", block)
    assert m, f"{SKU} не найден в products-config.php"

    карточки = sorted(p.name for p in (ROOT / "products").glob(f"{SKU}-*.html"))
    assert len(карточки) == 1, f"ожидалась одна карточка {SKU}, найдено {карточки}"
    return m.group(1), f"/products/{карточки[0]}", int(m.group(2)) // 100


def статья(slug: str) -> str:
    return html.unescape((ARTICLES / f"{slug}.html").read_text(encoding="utf-8"))


def test_канонические_значения_читаются_из_конфигурации() -> None:
    имя, адрес, цена = канон()
    assert имя and адрес.startswith("/products/") and цена > 0, (имя, адрес, цена)


def test_утверждённые_статьи_ведут_на_t3() -> None:
    имя, адрес, _ = канон()
    нет = []
    for slug, причина in sorted(ОБЯЗАНЫ_ВЕСТИ.items()):
        if адрес not in статья(slug):
            нет.append(f"{slug}: нет ссылки на {адрес} — {причина}")
    assert not нет, "\n      ".join([""] + нет)


def test_ссылка_названа_именем_из_конфигурации() -> None:
    """Подпись ссылки — название товара, а не пересказ.

    Пересказанное название расходится с карточкой молча: покупатель видит
    одно слово в статье и другое на странице оплаты.
    """
    имя, адрес, _ = канон()
    расхождения = []
    for slug in sorted(ОБЯЗАНЫ_ВЕСТИ):
        текст = статья(slug)
        for m in re.finditer(rf'<a[^>]+href="{re.escape(адрес)}"[^>]*>(.*?)</a>',
                             текст, re.S):
            подпись = re.sub(r"<[^>]+>", "", m.group(1)).strip(" «»").strip()
            if подпись != имя:
                расхождения.append(f"{slug}: «{подпись}» вместо «{имя}»")
    assert not расхождения, "\n      ".join([""] + расхождения)


def test_спорные_статьи_на_t3_не_ведут() -> None:
    _, адрес, _ = канон()
    лишние = [f"{slug}: ссылка появилась, хотя связка спорна — {причина}"
              for slug, причина in sorted(НЕ_ДОЛЖНЫ_ВЕСТИ.items())
              if адрес in статья(slug)]
    assert not лишние, "\n      ".join([""] + лишние)


def test_проверка_не_требует_правок_во_всех_статьях() -> None:
    """Список утверждённых — меньшинство, и это условие осмысленности.

    Проверка, требующая ссылку отовсюду, меряет не маршрут, а саму себя.
    """
    всего = len([p for p in ARTICLES.glob("*.html") if p.name != "index.html"])
    assert всего > 0
    assert len(ОБЯЗАНЫ_ВЕСТИ) < всего / 2, (len(ОБЯЗАНЫ_ВЕСТИ), всего)


def test_у_каждой_статьи_списков_названа_причина() -> None:
    пустые = [s for s, r in {**ОБЯЗАНЫ_ВЕСТИ, **НЕ_ДОЛЖНЫ_ВЕСТИ}.items()
              if not r.strip()]
    assert not пустые, пустые


def test_статьи_списков_существуют() -> None:
    нет = [s for s in {**ОБЯЗАНЫ_ВЕСТИ, **НЕ_ДОЛЖНЫ_ВЕСТИ}
           if not (ARTICLES / f"{s}.html").exists()]
    assert not нет, нет


def test_t3_остаётся_входной_ступенью_своих_кластеров() -> None:
    """Связка держится на графе продукта, а не на памяти автора.

    Если t3 перестанет быть входной ступенью кластеров ks и uderzhanie,
    основание ставить его в эти статьи исчезнет — и проверка об этом
    скажет, а не промолчит.
    """
    _, адрес, _ = канон()
    source = (ROOT / "diagnostika.html").read_text(encoding="utf-8")
    scenarios = json.loads(re.search(r"const SCENARIOS = (\[.*?\]);",
                                     source, re.S).group(1))
    кластеры = {sc["pain_id"] for sc in scenarios
                if (sc.get("entry") or {}).get("url") == адрес}
    assert {"ks", "uderzhanie"} <= кластеры, кластеры


def main() -> int:
    tests = [v for k, v in sorted(globals().items()) if k.startswith("test_")]
    failed = 0
    for t in tests:
        try:
            t()
        except AssertionError as e:
            failed += 1
            print(f"  ✗ {t.__name__}: {str(e)[:400]}")
        else:
            print(f"  ✓ {t.__name__}")
    print(f"\nПроверок {len(tests)}, упало {failed}.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
