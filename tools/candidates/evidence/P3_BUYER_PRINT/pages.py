"""По страницам PDF (pdftotext): где лежат роли участников/подписей, повторы шапки
подписей, наличие подсказок комплекта. Пишет pages-<name>.json рядом."""
import json, re, subprocess, sys
from pathlib import Path

pdf = Path(sys.argv[1])
n = int(re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout).group(1))
norm = lambda s: re.sub(r"\s+", " ", s.replace("", "")).strip()
pages = [norm(subprocess.run(["pdftotext", "-f", str(i), "-l", str(i), str(pdf), "-"],
                             capture_output=True, text=True).stdout) for i in range(1, n + 1)]
ROLES = {
 "R1 застройщик СК": ("Представитель застройщика", "по вопросам строительного контроля"),
 "R4 проектировщик": ("Представитель лица, осуществляющего подготовку проектной документации",
                      "статьи 53 Градостроительного кодекса Российской Федерации)"),
 "R5 выполнивший работы": ("Представитель лица, выполнившего работы",
                           "заключенным с иными лицами)"),
}
FULL = {
 "R4 проектировщик": "Представитель лица, осуществляющего подготовку проектной документации (в случае "
   "привлечения застройщиком лица, осуществляющего подготовку проектной документации, для проверки "
   "соответствия выполняемых работ проектной документации согласно части 2 статьи 53 "
   "Градостроительного кодекса Российской Федерации)",
 "R5 выполнивший работы": "Представитель лица, выполнившего работы, подлежащие освидетельствованию (в "
   "случае выполнения работ по договорам о строительстве, реконструкции, капитальном ремонте объектов "
   "капитального строительства, заключенным с иными лицами)",
}
HELPERS = ["в рекомендуемый образец не входят", "Номер в национальном реестре специалистов",
           "Если документов больше пяти", "в образец акта не входит", "Если есть замечания",
           "Пять рабочих форм", "Как пользоваться формами", "Для работ, которые закрывает бетонирование"]
SIGHEAD = "Представитель Должность, Ф. И. О. Подпись Дата подписания"
res = {"pdf": pdf.name, "pages": n, "per_page": []}
for i, t in enumerate(pages, 1):
    res["per_page"].append({
        "page": i,
        "full_R4": t.count(FULL["R4 проектировщик"]),
        "full_R5": t.count(FULL["R5 выполнивший работы"]),
        "start_R4": t.count(ROLES["R4 проектировщик"][0]),
        "end_R4": t.count(ROLES["R4 проектировщик"][1]),
        "sig_header": t.count(SIGHEAD),
        "participants_header": t.count("Номер в НРС"),
        "fixture_sign": t.count("/подпись — вымысел/"),
        "full_R1": t.count("Представитель застройщика, технического заказчика, лица, ответственного за "
                           "эксплуатацию здания, сооружения, или регионального оператора по вопросам "
                           "строительного контроля"),
        # данные строк участников/подписей фикстуры A: ФИО и распорядительный документ
        "row1_data": [t.count("Альфа А. А."), t.count("ТЕСТ-01 от"), t.count("С-00-000001")],
        "row4_data": [t.count("Дельта Д. Д."), t.count("ТЕСТ-04 от")],
        "row5_data": [t.count("Эпсилон Е. Е."), t.count("ТЕСТ-05 от")],
        "helpers": [h for h in HELPERS if h in t],
    })
(pdf.parent / f"pages-{pdf.stem}.json").write_text(json.dumps(res, ensure_ascii=False, indent=1), encoding="utf-8")
for p in res["per_page"]:
    if any(v for k, v in p.items() if k != "page"):
        print(p)
print("pages", n)
