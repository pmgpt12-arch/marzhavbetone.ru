def money(x): return f'{x:,.2f}'.replace(',',' ').replace('.',',')
def fill(src,dst,vals,tables=None,drop_brackets=True):
    d=docx.Document(src)
    counters={}
    def sub(text):
        if drop_brackets: text=re.sub(r'\[с учётом дополнительного соглашения[^\]]*\]\s*','',text)
        def rep(m):
            k=m.group(1); v=vals.get(k, COMMON.get(k))
            if v is None: return m.group(0)
            if isinstance(v,list):
                i=counters.get(k,0); counters[k]=i+1; return v[min(i,len(v)-1)]
            return v
        return re.sub(r'\{\{([^}]*)\}\}',rep,text)
    def paras(container):
        for p in container.paragraphs: yield p
        for t in container.tables:
            for r in t.rows:
                for c in r.cells:
                    yield from paras(c)
    # document order: body paragraphs and tables interleaved
    from docx.text.paragraph import Paragraph
    from docx.table import Table
    def walk(body_el, parent):
        for el in body_el.iterchildren():
            tag=el.tag.split('}')[1]
            if tag=='p': yield Paragraph(el,parent)
            elif tag=='tbl':
                t=Table(el,parent); seen=set()
                for r in t.rows:
                    for c in r.cells:
                        if id(c._tc) in seen: continue
                        seen.add(id(c._tc)); yield from walk(c._tc, c)
    for p in walk(d.element.body,d):
        t=p.text
        if '{{' in t or '[с учётом' in t:
            nt=sub(t)
            if p.runs:
                p.runs[0].text=nt
                for r in p.runs[1:]: r.text=''
    if tables:
        for ti,rows in tables.items():
            t=d.tables[ti]
            for ri,row in enumerate(rows):
                for ci,val in enumerate(row):
                    cell=t.rows[1+ri].cells[ci]
                    if cell.paragraphs and cell.paragraphs[0].runs: cell.paragraphs[0].runs[0].text=str(val)
                    else: cell.paragraphs[0].add_run(str(val))
    d.save(dst)
    left=[m for p in walk(d.element.body,d) for m in re.findall(r'\{\{[^}]*\}\}',p.text)]
    return left
