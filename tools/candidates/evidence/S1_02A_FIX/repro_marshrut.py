import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
import test_s1_candidate as T  # noqa: E402

варианты = {
    "С-3: только гарантийное письмо (вопрос 15 = Да)": {"q14": "Да"},
    "письмо и соглашение (вопросы 14, 15 = Да)": {"q14": "Да", "q13": "Да"},
    "С-4: B4 и B5 (вопросы 6 и 9 = Да)": {"q6": "Да", "q17": "Да"},
    "чистый случай А": {},
}
ключи = {k: f"v{i}" for i, k in enumerate(варианты)}
r = T._маршрут_в_calc({ключи[k]: v for k, v in варианты.items()})
for k in варианты:
    print(f"== {k}")
    for поле in ("ИТОГ", "Следующий шаг", "Предупреждение о сроке", "Ещё границы"):
        if поле in r[ключи[k]]:
            print(f"  {поле}: {r[ключи[k]][поле]}")
