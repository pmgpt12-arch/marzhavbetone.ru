#!/usr/bin/env python3
"""Что сервер отдаёт наружу. Запуск: python3 tools/test_web_exposure.py

ЗАЧЕМ. В корне сайта лежат каталоги, которых посетителю видеть нельзя:
`orders/` с заказами и `products-storage/` с мастерами товаров. Файл заказа
содержит почту, телефон И токен выдачи — тот самый, который `download.php`
сверяет перед тем, как отдать оплаченный товар. То есть один прочитанный
файл заказа это не только утечка персональных данных, но и бесплатный доступ
к платному товару.

ПОЧЕМУ ПРОВЕРЯЕТСЯ ИМЕННО `.htaccess` КОРНЯ, А НЕ ФАЙЛ В КАТАЛОГЕ. Каталог
`orders/` до боевого сервера не доезжает: он в списке исключений деплоя
(`.github/workflows/deploy.yml`) и создаётся там сам вызовом `mkdir` из
`config.php`. Положить в него `.htaccess` из репозитория невозможно —
значит запрет обязан стоять в том файле, который деплоится, то есть в
`.htaccess` корня.

ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ. Она не ходит по HTTP и не подтверждает
поведение боевого Apache: из облачной сессии домен закрыт политикой шлюза
(`CONNECT 403`). Проверяется наличие правила, а не его срабатывание. Живая
проверка кодом ответа остаётся шагом процедуры включения.
"""
from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
HTACCESS = КОРЕНЬ / ".htaccess"

# Каталоги в корне сайта, которые обязаны быть закрыты от прямого запроса.
# Перечень закрытый: новый каталог с чувствительным содержимым нужно внести
# сюда руками, и это намеренно — молчаливое добавление незамеченным не пройдёт.
ЗАКРЫТЫЕ = {
    "orders": "заказы: почта, телефон и токен выдачи оплаченного товара",
    "products-storage": "мастера платных товаров",
}

провалов = 0


def проверка(имя: str, тело) -> None:
    global провалов
    try:
        тело()
        print(f"  ok   {имя}")
    except Exception as ошибка:
        провалов += 1
        print(f"  FAIL {имя}\n         {ошибка}")


def текст() -> str:
    assert HTACCESS.is_file(), ".htaccess корня отсутствует"
    return HTACCESS.read_text(encoding="utf-8")


def каталоги_закрыты() -> None:
    содержимое = текст()
    открытые = []
    for каталог, чем_опасен in ЗАКРЫТЫЕ.items():
        # Годится любое из двух: правило перезаписи, отдающее отказ, либо
        # блок с явным запретом на этот путь.
        # Путь может быть записан как `^orders/`, `^orders(/|$)` или `^orders`.
        # Требуется одно: правило начинается с имени каталога и отдаёт отказ
        # флагом F. Первая редакция требовала слеш сразу после имени и не
        # видела `^orders(/|$)` — то есть проверка падала на верном правиле.
        по_rewrite = re.search(
            rf"^\s*RewriteRule\s+\^{re.escape(каталог)}(?![\w-]).*\[[^\]]*F[,\]]",
            содержимое, re.M | re.I)
        по_блоку = re.search(
            rf"<(Directory|DirectoryMatch|LocationMatch|Files|FilesMatch)[^>]*"
            rf"{re.escape(каталог)}[^>]*>(.|\n)*?(Deny from all|Require all denied)",
            содержимое, re.I)
        if not (по_rewrite or по_блоку):
            открытые.append(f"{каталог} ({чем_опасен})")
    assert not открытые, (
        "в .htaccess корня нет запрета на: " + "; ".join(открытые)
        + ". Каталог исключён из деплоя и своего .htaccess получить не может, "
          "поэтому запрет обязан стоять здесь")


def листинг_подавлен() -> None:
    """Годится `Options -Indexes` ИЛИ `IndexIgnore *`, и это осознанно.

    `Options` в .htaccess действует только при `AllowOverride Options`; если
    хостинг его не даёт, Apache отвечает 500 на весь сайт. `IndexIgnore` из
    класса `Indexes` таким свойством не обладает. Требовать именно `Options`
    значило бы требовать риска, который отсюда не проверяется.
    """
    содержимое = текст()
    есть = (re.search(r"^\s*Options\s+.*-Indexes", содержимое, re.M | re.I)
            or re.search(r"^\s*IndexIgnore\s+\*", содержимое, re.M | re.I))
    assert есть, ("листинг каталогов ничем не подавлен: нужен либо "
                  "`Options -Indexes`, либо `IndexIgnore *`")


def имя_заказа_остаётся_предсказуемым() -> None:
    """Не запрет, а зафиксированный факт: имя файла заказа — не токен.

    `substr(uniqid(), -6)` это не случайность, а младшие разряды времени в
    микросекундах. Вместе с `date('Ymd_His')` в том же имени это перебираемо.
    Проверка стоит здесь, чтобы смена схемы имени на настоящий токен не
    прошла незамеченной, а до неё — чтобы никто не считал имя защитой.
    """
    payment = (КОРЕНЬ / "payment.php").read_text(encoding="utf-8")
    строка = re.search(r"\$orderId\s*=\s*(.+);", payment)
    assert строка, "не нашёл, как формируется имя заказа"
    выражение = строка.group(1)
    assert "uniqid()" in выражение, (
        "схема имени заказа изменилась: " + выражение.strip()
        + ". Если это переход на случайный токен — обновить эту проверку и "
          "снять оговорку о предсказуемости из отчёта по безопасности")


def здоровье_сборщика_доезжает_до_сервера() -> None:
    """Инструмент, которого нет на сервере, инструментом не является.

    `tools/` целиком в списке исключений деплоя. Проверка здоровья сборщика,
    положенная туда, на боевой сервер не попадала бы никогда — а процедура
    включения требует запустить её именно там.
    """
    деплой = (КОРЕНЬ / ".github" / "workflows" / "deploy.yml").read_text(
        encoding="utf-8")
    исключения = re.search(r"EXCLUDES=\((.*?)\)", деплой, re.S)
    assert исключения, "не нашёл список исключений деплоя"
    исключено = set(re.findall(r"'([^']+)'", исключения.group(1)))

    здоровье = None
    for кандидат in КОРЕНЬ.glob("*funnel*health*.php"):
        здоровье = кандидат
        break
    assert здоровье is not None, (
        "проверки здоровья сборщика нет в корне сайта. В tools/ она "
        f"недоступна: каталог исключён из деплоя ({sorted(исключено)})")
    assert здоровье.name not in исключено, (
        f"{здоровье.name} исключён из деплоя")


def здоровье_не_отдаётся_вебом() -> None:
    здоровье = next(КОРЕНЬ.glob("*funnel*health*.php"))
    содержимое = здоровье.read_text(encoding="utf-8")
    assert "PHP_SAPI" in содержимое and "cli" in содержимое, (
        f"{здоровье.name} лежит в корне сайта и доступен по HTTP, но не "
        "отказывает запросу из веба")


print("что сервер отдаёт наружу")
проверка("каталоги с заказами и товарами закрыты", каталоги_закрыты)
проверка("листинг каталогов подавлен", листинг_подавлен)
проверка("имя файла заказа не считается защитой", имя_заказа_остаётся_предсказуемым)
проверка("проверка здоровья доезжает до сервера", здоровье_сборщика_доезжает_до_сервера)
проверка("проверка здоровья не отдаётся вебом", здоровье_не_отдаётся_вебом)

print()
if провалов:
    print(f"провалов: {провалов}")
    sys.exit(1)
print("все проверки пройдены")
