<?php
/**
 * Регресс: покупателю уходит архив, собранный из текущих файлов продукта.
 * Запуск: php tools/test_delivery_cache_freshness.php
 *
 * Почему это отдельный тест. Архив продукта собирается один раз и кладётся
 * в `orders/delivery`. Условием переиспользования было одно его
 * существование — и это молча превращало любое исправление файлов продукта
 * в ничто: мастера в репозитории новые, архив на сервере старый, покупатель
 * скачивает старый. Заметить это по коду нельзя, а по выдаче — можно только
 * купив.
 *
 * Каталог `orders/` исключён из заливки (`.github/workflows/deploy.yml`),
 * поэтому сам по себе устаревший архив не исчезает и живёт до тех пор, пока
 * его не удалят руками.
 *
 * Проверяется поведение `mvb_build_product_zip()`: собранный архив
 * переиспользуется, пока файлы не тронуты, и пересобирается, как только
 * среди них появился более новый.
 */
declare(strict_types=1);

$root = dirname(__DIR__);
$tmp = sys_get_temp_dir() . '/mvb-cache-' . bin2hex(random_bytes(4));
mkdir($tmp . '/delivery', 0755, true);
mkdir($tmp . '/masters', 0755, true);

foreach ([
    'ORDERS_DIR' => $tmp,
    'DELIVERY_DIR' => $tmp . '/delivery',
    'PRODUCTS_DIR' => $tmp . '/masters',
    'SITE_URL' => 'https://example.invalid',
    'ADMIN_EMAIL' => 'a@example.invalid',
    'DELIVERY_TTL_DAYS' => 7,
    'YOOKASSA_SHOP_ID' => 't',
    'YOOKASSA_SECRET_KEY' => 't',
    'YOOKASSA_API_URL' => 'https://example.invalid',
    'YOOKASSA_MODE' => 'test',
] as $name => $value) {
    if (!defined($name)) {
        define($name, $value);
    }
}
require $root . '/products-config.php';

$failures = [];

// Берём любой товар каталога: тест не должен зависеть от его состава,
// он меняется решением владельца.
$catalog = mvb_products();
$sku = array_key_first($catalog);
if ($sku === null) {
    echo "Тест не запускался: каталог пуст\n";
    exit(2);
}
$dir = PRODUCTS_DIR . '/' . $catalog[$sku]['dir'];
$zip = DELIVERY_DIR . '/' . $catalog[$sku]['zip'];
mkdir($dir, 0755, true);
file_put_contents($dir . '/01-документ.txt', 'редакция первая');

// 1. Первая выдача собирает архив.
$path = mvb_build_product_zip($sku);
if ($path === null || !is_file($zip)) {
    echo "Тест не запускался: архив не собрался (нет ZipArchive?)\n";
    exit(2);
}
$первый = filemtime($zip);

// 2. Файлы не тронуты — архив переиспользуется, а не собирается заново.
// Иначе каждая выдача перепаковывала бы комплект.
//
// Время отодвигается в прошлое намеренно: пересборка поставила бы архиву
// текущую секунду, а сравнение «текущая секунда против текущей секунды»
// ничего не различает — на этом тест один раз уже не заметил подмены.
$старое = $первый - 3600;
touch($dir . '/01-документ.txt', $старое - 60);
touch($zip, $старое);
clearstatcache();
mvb_build_product_zip($sku);
clearstatcache();
if (filemtime($zip) !== $старое) {
    $failures[] = 'архив пересобран, хотя файлы продукта не менялись: время '
        . filemtime($zip) . ' вместо ' . $старое;
}

// 3. Файл продукта стал новее архива — архив обязан быть пересобран,
// и покупатель обязан получить новое содержимое.
file_put_contents($dir . '/01-документ.txt', 'редакция вторая, исправленная');
touch($dir . '/01-документ.txt', $старое + 10);
clearstatcache();
mvb_build_product_zip($sku);

$внутри = null;
$архив = new ZipArchive();
if ($архив->open($zip) === true) {
    $внутри = $архив->getFromName('01-документ.txt');
    $архив->close();
}
if ($внутри !== 'редакция вторая, исправленная') {
    $failures[] = 'после правки файла продукта покупателю уходит старое содержимое: '
        . var_export($внутри, true);
}

// 4. Новый файл в папке продукта тоже обновляет архив: добавленный документ
// не должен ждать, пока тронут один из прежних.
// Архив после предыдущей пересборки помечен текущей секундой — отодвигаем
// его назад, иначе «новый файл» окажется старше архива и пересобирать его
// не понадобится по делу.
touch($zip, $старое);
file_put_contents($dir . '/02-добавленный.txt', 'новый документ');
touch($dir . '/02-добавленный.txt', $старое + 20);
clearstatcache();
mvb_build_product_zip($sku);
$естьНовый = false;
if ($архив->open($zip) === true) {
    $естьНовый = $архив->locateName('02-добавленный.txt') !== false;
    $архив->close();
}
if (!$естьНовый) {
    $failures[] = 'добавленный в комплект файл не попал в архив покупателя';
}

$убрать = function (string $путь) use (&$убрать) {
    foreach (glob($путь . '/*') ?: [] as $f) {
        is_dir($f) ? $убрать($f) : @unlink($f);
    }
    @rmdir($путь);
};
$убрать($tmp);

if ($failures) {
    echo "Свежесть архива выдачи: ДЕФЕКТ\n";
    foreach ($failures as $f) {
        echo "  ✗ {$f}\n";
    }
    exit(1);
}
echo "Свежесть архива выдачи: 4 проверки пройдено — архив переиспользуется, "
   . "пока файлы продукта не тронуты, и пересобирается, как только они новее.\n";
exit(0);
