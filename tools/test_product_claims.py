#!/usr/bin/env python3
"""Страница товара не обещает чужого и называет товар одним именем.

Два дефекта, найденные 17.09.2026, и оба — про расхождение витрины с тем,
что лежит в папке выдачи.

**P10 обещал три документа, которых в нём нет.** Абзац «Отдельно про
профилактику: три документа комплекта подписываются до спора» называл
соглашение о разграничении ответственности, акт передачи фронта работ и
акт входного контроля давальческих материалов. Все три лежат только в P12.
Ещё два места — буллит «Профилактика: разграничение ответственности до
спора» и хвост строки «На выходе» — обещали то же самое. Соседний раздел
«Где заканчивается этот комплект» при этом говорил верно: эти документы в
«Споре с суммой». То есть страница одновременно и отсылала к чужому
комплекту, и присваивала его содержимое.

**P12 назывался по-разному.** `<title>`, `og:title` и `<h1>` несли «ответ
на претензию», а корзина, карточка каталога и JSON-LD — «ответ», как в
`products-config.php`. Покупатель видел одно имя на странице и другое в
корзине.

Проверка читает **фактический состав**: имена файлов в папках выдачи и
заголовки внутри самих `.docx`. Второго списка документов здесь нет —
разойдясь с папкой, он проверял бы сам себя.

Исключение — блок перекрёстной продажи: раздел, в котором стоит ссылка на
страницу другого товара, вправе называть его документы. Именно так устроен
раздел «Где заканчивается этот комплект».

Запуск без pytest: python3 tools/test_product_claims.py
"""
from __future__ import annotations

import re
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_packages as cp                                   # noqa: E402

ROOT = cp.ROOT
STORAGE = cp.STORAGE
PAGES = cp.PAGES
CONFIG = cp.CONFIG

СЛУЖЕБНЫЕ = cp.NOT_DELIVERED | cp.NOT_LISTED
SKU_СТРАНИЦЫ = re.compile(r'data-sku="([a-z0-9]+)"')
ИМЯ_КАТАЛОГА = re.compile(
    r"'(?P<sku>[a-z0-9]+)'\s*=>\s*\[\s*'name'\s*=>\s*'(?P<name>(?:[^'\\]|\\.)*)'",
    re.S,
)
# Раздел страницы: от <section до </section>
РАЗДЕЛ = re.compile(r"<section\b.*?</section>", re.S)
ССЫЛКА_НА_ТОВАР = re.compile(r'href="(?:\./)?p\d+[a-z0-9-]*\.html"')
ТЕГИ = re.compile(r"<[^>]+>")

# Заголовок документа — первый непустой абзац word/document.xml. Слишком
# короткие и слишком общие заголовки в признак не годятся: «Приложение» или
# «Акт» встретятся на любой странице и дадут ложное срабатывание.
МИН_ДЛИНА_ЗАГОЛОВКА = 25


def имена_каталога() -> dict[str, str]:
    """sku → имя товара из products-config.php."""
    if not CONFIG.is_file():
        return {}
    text = CONFIG.read_text(encoding="utf-8")
    return {m.group("sku"): m.group("name").replace("\\'", "'")
            for m in ИМЯ_КАТАЛОГА.finditer(text)}


def заголовок_docx(путь: Path) -> str:
    """Первая непустая строка документа — то, как он сам себя называет."""
    try:
        with zipfile.ZipFile(путь) as z:
            xml = z.read("word/document.xml").decode("utf-8")
    except Exception:
        return ""
    текст = ТЕГИ.sub("", xml.replace("</w:p>", "\n"))
    for строка in текст.splitlines():
        строка = " ".join(строка.split())
        if строка:
            return строка
    return ""


def состав(sku: str, dirs: dict[str, str]) -> dict[str, Path]:
    """Файлы, которые покупатель получает по этому sku: имя → путь."""
    папка = dirs.get(sku)
    if not папка:
        return {}
    корень = STORAGE / папка
    if not корень.is_dir():
        return {}
    # Тот же отбор, что у сборщика архива: служебные файлы покупателю не
    # уходят. Второго списка здесь не заводится — он берётся из check_packages.
    return {f.name: f for f in sorted(корень.rglob("*"))
            if f.is_file() and f.name not in СЛУЖЕБНЫЕ}


def страницы_товаров(dirs: dict[str, str]) -> dict[str, Path]:
    """sku → страница товара. Берутся только страницы с одной кнопкой."""
    out: dict[str, Path] = {}
    for page in sorted(PAGES.glob("*.html")):
        skus = set(SKU_СТРАНИЦЫ.findall(page.read_text(encoding="utf-8")))
        if len(skus) == 1:
            sku = skus.pop()
            if sku in dirs:
                out[sku] = page
    return out


def видимый_текст(html: str) -> str:
    без = re.sub(r"<script.*?</script>|<style.*?</style>", " ", html, flags=re.S)
    return " ".join(ТЕГИ.sub(" ", без).split())


def test_страница_не_обещает_чужих_документов() -> None:
    """Документ, которого нет в выдаче этого sku, страница не называет своим.

    Заголовки берутся из самих файлов соседних комплектов, поэтому список
    не надо поддерживать руками: появился документ — признак появился сам.
    """
    dirs = cp.catalog()
    страницы = страницы_товаров(dirs)
    assert страницы, "страниц товаров не найдено — проверка ничего не проверяет"

    составы = {sku: состав(sku, dirs) for sku in dirs}
    нарушения: list[str] = []

    for sku, page in страницы.items():
        свои = составы.get(sku, {})
        if not свои:
            continue
        html = page.read_text(encoding="utf-8")

        # Свои заголовки — то, что этот комплект вправе называть. Сравнение
        # идёт по заголовку, а не по имени файла: один и тот же документ
        # лежит в нескольких комплектах под разными номерами, и это норма.
        свои_заголовки = {
            заголовок_docx(путь).lower()
            for путь in свои.values() if путь.suffix.lower() == ".docx"
        }

        чужие: dict[str, str] = {}
        for другой, файлы in составы.items():
            if другой == sku:
                continue
            for имя, путь in файлы.items():
                if путь.suffix.lower() != ".docx":
                    continue
                заголовок = заголовок_docx(путь)
                if len(заголовок) < МИН_ДЛИНА_ЗАГОЛОВКА:
                    continue
                низ = заголовок.lower()
                # Один документ у разных комплектов называется с уточнением:
                # «Дополнительное соглашение об изменении объёма и цены» у P7
                # и «…(дополнительные работы)» у P2. Вхождение одного
                # заголовка в другой — тот же документ, а не чужой.
                if any(низ in свой or свой in низ for свой in свои_заголовки):
                    continue
                чужие.setdefault(заголовок.lower(), f"{другой}/{имя}")

        for раздел in РАЗДЕЛ.findall(html):
            if ССЫЛКА_НА_ТОВАР.search(раздел):
                continue          # блок перекрёстной продажи — чужое называть вправе
            текст = видимый_текст(раздел).lower()
            for заголовок, откуда in чужие.items():
                if заголовок in текст:
                    нарушения.append(
                        f"{page.name}: раздел без ссылки на другой товар называет "
                        f"«{заголовок[:60]}» — это {откуда}")

    assert not нарушения, "страница обещает чужие документы:\n  " + "\n  ".join(нарушения)


def test_число_файлов_в_шапке_равно_выдаче() -> None:
    """Шапка страницы считает то, что действительно уходит покупателю."""
    dirs = cp.catalog()
    беды = []
    for sku, page in страницы_товаров(dirs).items():
        html = page.read_text(encoding="utf-8")
        число = cp.EYEBROW.search(html)
        if not число:
            continue
        факт = len(состав(sku, dirs))
        if int(число.group(1)) != факт:
            беды.append(f"{page.name}: обещано {число.group(1)}, уходит {факт}")
    assert not беды, "\n  ".join(беды)


# Страницы, заголовок которых обязан дословно нести имя каталога.
#
# У остальных `<title>` и `og:title` — маркетинговые и от каталога
# отличаются намеренно: «Акты выполненных работ, КС-2 и КС-3: образцы,
# претензия, иск» против «…: закрытие и взыскание оплаты». Это решение
# владельца, а не дефект, и навязывать всему сайту одно правило значило бы
# объявить дефектом семь страниц, которых никто не просил трогать.
#
# p12 попал сюда замером: `<title>`, `og:title` и `<h1>` несли «ответ на
# претензию», а корзина, карточка каталога и JSON-LD — «ответ», как в
# каталоге. Покупатель видел на странице одно имя, а в корзине другое.
ТОЧНОЕ_ИМЯ_СТРАНИЦЫ = {"p12"}


def test_товар_называется_одним_именем() -> None:
    """Имя из products-config.php стоит на покупательских поверхностях.

    Безусловно проверяются `data-product` (то, что попадает в корзину) и
    первое `"name"` в JSON-LD: эти две поверхности обязаны нести имя
    каталога целиком у всех товаров. Заголовок страницы сверяется дословно
    только там, где это объявлено в ТОЧНОЕ_ИМЯ_СТРАНИЦЫ.
    """
    dirs = cp.catalog()
    имена = имена_каталога()
    беды = []

    for sku, page in страницы_товаров(dirs).items():
        имя = имена.get(sku)
        if not имя:
            continue
        html = page.read_text(encoding="utf-8")

        for метка, найдено in [
            ("data-product", re.findall(r'data-product="([^"]*)"', html)),
            ("JSON-LD name", re.findall(r'"name"\s*:\s*"([^"]*)"', html)[:1]),
        ]:
            for значение in найдено:
                if значение != имя:
                    беды.append(f"{page.name}: {метка} = «{значение}», каталог = «{имя}»")

        if sku not in ТОЧНОЕ_ИМЯ_СТРАНИЦЫ:
            continue
        внутри = re.search(r"«(.+)»", имя)
        короткое = внутри.group(1) if внутри else имя
        for метка, rx in [
            ("<title>", r"<title>([^<]*)</title>"),
            ("og:title", r'og:title"\s+content="([^"]*)"'),
            ("<h1>", r"<h1[^>]*>([^<]*)</h1>"),
        ]:
            m = re.search(rx, html)
            if not m:
                continue
            значение = m.group(1).strip()
            if короткое not in значение:
                беды.append(f"{page.name}: {метка} = «{значение}» не содержит «{короткое}»")

    assert not беды, "имя товара расходится:\n  " + "\n  ".join(беды)


def main() -> int:
    провал = 0
    for имя, проверка in sorted(globals().items()):
        if not имя.startswith("test_"):
            continue
        try:
            проверка()
        except AssertionError as ошибка:
            провал += 1
            print(f"ПРОВАЛ  {имя}\n{ошибка}")
        else:
            print(f"ок  {имя}")
    return 1 if провал else 0


if __name__ == "__main__":
    sys.exit(main())
