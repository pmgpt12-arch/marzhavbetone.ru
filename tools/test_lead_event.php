проверка('test_event_failure_does_not_change_user_response', function () use ($ROOT, $роутер, $журнал, $поля) {
    // Ответ человеку обязан быть побайтово одним и тем же при работающем
    // сборщике и при любом его отказе. Совпадение проверяется сравнением, а
    // не чтением глазами: расхождение в одном поле — уже утечка состояния
    // наблюдаемости в коммерческий контур.
    $ответы = [];
    foreach (['ok', 'blocked', 'occupied'] as $режим) {
        [$сайт, $приём, $порт, $лог] = запустить_сценарий($ROOT, $роутер, $журнал, $режим);
        try { $ответы[$режим] = послать($порт, $поля)['json']; }
        finally { погасить($сайт); if ($приём) погасить($приём); }
    }
    равно($ответы['blocked'], $ответы['ok'], 'ответ при несоздаваемом сборщике');
    равно($ответы['occupied'], $ответы['ok'], 'ответ при незаписываемом сборщике');
});

