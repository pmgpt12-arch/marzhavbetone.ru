function каталог_сборщика(string $метка): string
{
    $путь = sys_get_temp_dir() . '/mvb_lead_outbox_' . getmypid() . '_' . $метка;
    foreach ((array)glob($путь . '/*') as $файл) {
        is_dir($файл) ? @rmdir($файл) : @unlink($файл);
    }
    @rmdir($путь);
    @unlink($путь);              // режим blocked оставляет файл на месте каталога
    return $путь;
}

/**
 * Поднять сайт с заданным состоянием сборщика.
 *
 * Режимы больше не про приёмник: сайт в сеть не ходит вовсе. Отказать
 * теперь может файл, и отказывает он иначе — каталога нет, каталог закрыт
 * на запись. Прежние режимы `slow` и `error` описывали чужой HTTP-ответ, и
 * повторять их здесь было бы проверкой несуществующего пути.
 */
function запустить_сценарий(string $ROOT, string $роутер, string $журнал,
                            string $режим, bool $приёмник_жив = true): array
{
    $каталог = каталог_сборщика($режим);
    if ($режим === 'occupied') {
        // Каталог есть, а имя сегодняшнего файла занято каталогом: дописать
        // в него нельзя никому. Права 0500 для этого не годятся — под root
        // они не действуют, и проверка молча проходила бы на любом коде.
        @mkdir($каталог . '/' . gmdate('Y-m-d') . '.pending.jsonl', 0700, true);
    } elseif ($режим === 'blocked') {
        // Каталог создать нельзя: на его месте файл.
        @mkdir(dirname($каталог), 0700, true);
        @file_put_contents($каталог, 'не каталог');
    }
    putenv("MVB_FUNNEL_OUTBOX={$каталог}");
    $порт_сайта = свободный_порт();
    $сервер_сайта = поднять($ROOT, $порт_сайта);
    return [$сервер_сайта, null, $порт_сайта, $каталог];
}

/**
 * События сборщика в том виде, в каком их получит приёмник.
 *
 * В файле лежит плоский канонный конверт; приёмник ждёт `event_type` и
 * `payload`. Пересборка живёт здесь и в сливщике — по разные стороны одного
 * контракта, и проверка обязана смотреть на ту сторону, куда событие едет.
 */
function события(string $каталог): array
{
    $записи = [];
    foreach ((array)glob($каталог . '/*.pending.jsonl') as $файл) {
        if (!is_file($файл)) { continue; }   // имя может быть занято каталогом
        foreach (explode("\n", (string)file_get_contents($файл)) as $строка) {
            if (trim($строка) === '') { continue; }
            $конверт = json_decode($строка, true);
            if (!is_array($конверт)) { continue; }
            $тип = $конверт['event_type'] ?? null;
            unset($конверт['event_type']);
            $записи[] = ['event_type' => $тип, 'payload' => $конверт];
        }
    }
    return $записи;
}

/** Дождаться записи: сборщик пишет ПОСЛЕ ответа человеку. */
function дождаться(string $каталог, int $сколько): array
{
    for ($i = 0; $i < 50; $i++) {
        $записи = события($каталог);
        if (count($записи) >= $сколько) { return $записи; }
        usleep(10000);
    }
    return события($каталог);
}

