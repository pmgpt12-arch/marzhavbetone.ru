def shade(cell, fill):
    tcPr=cell._tc.get_or_add_tcPr()
    sh=OxmlElement('w:shd'); sh.set(qn('w:fill'),fill); tcPr.append(sh)

def margins(cell, top=100, start=100, bottom=100, end=100):
    tc=cell._tc; tcPr=tc.get_or_add_tcPr(); m=OxmlElement('w:tcMar')
    for name,val in [('top',top),('start',start),('bottom',bottom),('end',end)]:
        node=OxmlElement('w:'+name); node.set(qn('w:w'),str(val)); node.set(qn('w:type'),'dxa'); m.append(node)
    tcPr.append(m)

def add_table(d, heads, empty=3, widths=None):
    t=d.add_table(rows=1+empty, cols=len(heads))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER; t.style='Table Grid'
    t.autofit=False
    for j,h in enumerate(heads): t.cell(0,j).text=h
    for i,row in enumerate(t.rows):
        for j,c in enumerate(row.cells):
            c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            margins(c,90,90,90,90)
            if widths: c.width=Cm(widths[j])
            for p in c.paragraphs:
                p.paragraph_format.space_after=Pt(0)
                for run in p.runs:
                    run.font.name='Arial'; run.font.size=Pt(8 if len(heads)>6 else 9)
                    if i==0: run.font.bold=True
            if i==0: shade(c,'F2EFE9')
    t.rows[0]._tr.get_or_add_trPr().append(OxmlElement('w:tblHeader'))
    return t

def make_doc(path, title, source, landscape=False):
    d=Document()
    sec=d.sections[0]
    if landscape: sec.page_width,sec.page_height=sec.page_height,sec.page_width
    sec.top_margin=sec.bottom_margin=Cm(1.55)
    sec.left_margin=sec.right_margin=Cm(1.65)
    normal=d.styles['Normal']; normal.font.name='Arial'; normal.font.size=Pt(9.4)
    normal.paragraph_format.space_after=Pt(5)
    normal.paragraph_format.line_spacing=1.12
    ti=d.add_paragraph(style='Title'); ti.add_run(title)
    ti.alignment=WD_ALIGN_PARAGRAPH.CENTER
    pPr=ti._p.get_or_add_pPr()
    borders=OxmlElement('w:pBdr')
    bottom=OxmlElement('w:bottom');bottom.set(qn('w:val'),'nil');borders.append(bottom);pPr.append(borders)
    for run in ti.runs: run.font.name='Arial'; run.font.size=Pt(15); run.font.color.rgb=RGBColor(0,0,0)
    p=d.add_paragraph(source); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    for r in p.runs: r.font.size=Pt(8); r.font.color.rgb=RGBColor(55,55,55)
    return d

def line(d,label,hint=''):
    p=d.add_paragraph()
    r=p.add_run(label+'  ');r.bold=True
    p.add_run('__________________________________________________')
    if hint:
        p=d.add_paragraph(hint);p.paragraph_format.space_after=Pt(3)
        for r in p.runs: r.font.size=Pt(7.5);r.font.color.rgb=RGBColor(78,78,78)

def heading(d, text):
    p=d.add_paragraph(text,style='Heading 2')
    for r in p.runs: r.font.color.rgb=RGBColor(0,0,0);r.font.size=Pt(10)
    return p

def sign(d,role):
    p=d.add_paragraph(role);p.paragraph_format.space_before=Pt(6)
    for r in p.runs: r.bold=True
    d.add_paragraph('Должность __________________   Подпись _____________   Фамилия и инициалы __________________')

