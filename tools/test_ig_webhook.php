<?php
/**
 * Размеченные случаи автовыдачи по комментарию.
 *
 * Проверяется то, что ломается молча: разбор соответствий без библиотеки
 * YAML, приведение слова к сравнимому виду, выбор ссылки и защита от
 * повторной доставки уведомления. Ошибка здесь стоит дорого в обе стороны:
 * не ответили человеку, который попросил файл, или ответили дважды.
 *
 *     php tools/test_ig_webhook.php
 */
declare(strict_types=1);

define('IG_WEBHOOK_AS_LIBRARY', true);
// Боевые ключи для разбора текста не нужны, а config.php закрыт от чтения
foreach (['IG_APP_SECRET', 'IG_VERIFY_TOKEN', 'IG_ACCESS_TOKEN', 'IG_USER_ID'] as $имя) {
    if (!defined($имя)) {
        define($имя, 'test');
    }
}
require __DIR__ . '/../ig-webhook.php';

$провалов = 0;

function проверка(string $имя, $ожидалось, $вышло): void
{
    global $провалов;
    if ($ожидалось === $вышло) {
        echo "ок        $имя\n";
        return;
    }
    $провалов++;
    echo "НЕ СОШЛОСЬ $имя\n";
    echo "    ждали: " . var_export($ожидалось, true) . "\n";
    echo "    вышло: " . var_export($вышло, true) . "\n";
}

$соответствия = ig_load_keywords(__DIR__ . '/../data/social/ig-keywords.yaml');
$правила = $соответствия['rules'];

проверка('файл соответствий разобран', true, count($правила) >= 10);
проверка('умолчание — страница, а не архив', 'page', $соответствия['defaults']['deliver']);

// Человек пишет с телефона как придётся, и все эти написания — одно слово
foreach (['КС2', 'кс-2', 'Кс 2', 'кс2!'] as $написание) {
    $правило = ig_match($написание, $правила);
    проверка("«{$написание}» ведёт на dengi", 'dengi', $правило['материал'] ?? null);
}

проверка('слово в предложении находится', 'avans',
    ig_match('Ребят, а можно про аванс подробнее?', $правила)['материал'] ?? null);
проверка('«ё» и «е» не различаются', 'raschet-metrami',
    ig_match('взаимозачет', $правила)['материал'] ?? null);
проверка('чужое слово не выдаёт ничего', null, ig_match('привет всем', $правила));
проверка('пустой комментарий не выдаёт ничего', null, ig_match('', $правила));

// Частичное совпадение не считается: «доработки» — не «допработы», и
// выдать по нему материал значит ответить не на тот вопрос
проверка('часть слова не срабатывает', null, ig_match('доработки', $правила));

$удержание = ig_match('удержание', $правила);
проверка('ссылка ведёт на страницу материала с метками',
    'https://marzhavbetone.ru/materialy/uderzhaniya.html?utm_source=instagram&utm_medium=dm&utm_campaign=dm-uderzhaniya',
    ig_link($удержание, $соответствия['defaults']));
проверка('переключение на архив меняет только адрес',
    'https://marzhavbetone.ru/downloads/uderzhaniya.zip?utm_source=instagram&utm_medium=dm&utm_campaign=dm-uderzhaniya',
    ig_link($удержание + ['deliver' => 'file'], $соответствия['defaults']));

$текст = ig_message($удержание, 'ССЫЛКА');
проверка('в сообщении есть ссылка', true, str_contains($текст, 'ССЫЛКА'));
проверка('подписка — просьба, а не условие выдачи', true,
    str_contains($текст, 'Если материал пригодится'));
проверка('оговорка на месте', true, str_contains($текст, 'проверка юристом'));

// Каждый материал из соответствий должен существовать в выдаче lead.php:
// ключ, которого там нет, — это сообщение со ссылкой в никуда
$lead = file_get_contents(__DIR__ . '/../lead.php');
foreach ($правила as $правило) {
    $ключ = $правило['материал'];
    проверка("материал «{$ключ}» объявлен в lead.php", true,
        str_contains($lead, "'" . $ключ . "'"));
    проверка("страница материала «{$ключ}» на месте", true,
        is_file(__DIR__ . '/../materialy/' . $ключ . '.html'));
}

echo "\nСлучаев с ошибкой: $провалов\n";
exit($провалов ? 1 : 0);
