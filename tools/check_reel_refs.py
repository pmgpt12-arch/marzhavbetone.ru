#!/usr/bin/env python3
"""Ворота доказательства референсов: ролик не идёт в производство вслепую.

ЗАЧЕМ. Требование владельца 23.08.2026: до сценария на руках 3–5 реальных
роликов с числами, разобранных по механике, и явно названо, что из
выбранного переносится, а что не копируется. Без этого «механика» — просто
слово в шапке сценария.

ЧТО ПРОВЕРЯЕТСЯ. Ролик, объявивший стадию `pre_production` и дальше,
обязан иметь манифест `content/reels/references/<имя>.yaml`, а в нём:

  - не меньше трёх кандидатов, у каждого свой вердикт и основание;
  - ровно один выбранный;
  - у каждой карточки заполнены поля замера (их приносит источник) и поля
    суждения (их ставит смотревший);
  - у выбранного названо, что переносится и что не копируется;
  - в списке «не копировать» стоят чужой текст, бренд, лицо и музыка —
    не как формальность, а потому что именно они утекают первыми.

ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ. Она не судит, хорош ли референс и похож ли
наш ролик на него. Это смотрит человек. Проверяется наличие и полнота
доказательства, а не вкус.

    python3 tools/check_reel_refs.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
РОЛИКИ = ROOT / "content" / "reels"
РЕФЕРЕНСЫ = РОЛИКИ / "references"
КАРТОЧКИ = РЕФЕРЕНСЫ / "cards"

# Стадии, начиная с которых доказательство обязательно. `concept` ещё нет:
# на нём как раз и идёт поиск референсов.
ТРЕБУЮТ = ("pre_production", "approved_for_generation", "production",
           "final_review", "approved_for_publish", "published")

МИНИМУМ_КАНДИДАТОВ = 3

# Что обязано стоять в списке «не копировать». Это не бюрократия: именно
# эти четыре вещи переносятся в чужой ролик незаметно для автора.
ЗАПРЕТЫ = {
    "текст": ("текст", "сценарий", "реплик"),
    "бренд или автор": ("бренд", "автор", "аккаунт", "логотип"),
    "лицо": ("лицо", "внешность", "персона"),
    "музыка": ("музык", "трек", "звуковую дорожк"),
}

# Поля карточки, которые обязан принести источник, и поля, которые ставит
# посмотревший. Имена совпадают с `tools/trend_provider.py` намеренно:
# разойдутся — проверка начнёт требовать несуществующее.
ЗАМЕР = ("id", "source", "url", "author", "date", "duration_sec", "views")
СУЖДЕНИЕ = ("hook_type", "first_seconds", "shot_rhythm", "avg_beat_sec",
            "video_static_ratio", "text_style", "voice_style", "conflict",
            "curiosity_gap", "escalation", "payoff", "cta_type", "why_relevant")


def стадия(текст: str) -> str:
    совпадение = re.search(r"^\*\*Стадия:\*\*\s*(\S+)", текст, re.M)
    return совпадение.group(1).strip() if совпадение else ""


def _кратко(путь: Path) -> str:
    """Путь от корня репозитория, а если он вне его — как есть.

    Безусловный `relative_to` ронял проверку трейсбеком, когда каталог
    карточек подменён на временный: разбор пропавшей карточки падал вместо
    того, чтобы её назвать.
    """
    try:
        return str(путь.relative_to(ROOT))
    except ValueError:
        return str(путь)


def карточка(имя: str) -> tuple[dict, str]:
    """Карточка референса по имени файла. Второе значение — причина отказа."""
    путь = КАРТОЧКИ / имя if not имя.endswith((".yaml", ".yml")) else КАРТОЧКИ / имя
    if not путь.exists():
        путь = КАРТОЧКИ / f"{имя}.yaml"
    if not путь.exists():
        return {}, f"карточки {имя} нет в {_кратко(КАРТОЧКИ)}"
    данные = yaml.safe_load(путь.read_text(encoding="utf-8")) or {}
    return данные, ""


def проверить_карточку(имя: str, данные: dict) -> list[str]:
    беды = []
    пустой_замер = [п for п in ЗАМЕР if not данные.get(п)]
    if пустой_замер:
        беды.append(f"карточка {имя}: источник не дал полей "
                    f"{', '.join(пустой_замер)} — дописывать их руками нельзя")
    пустое_суждение = [п for п in СУЖДЕНИЕ if данные.get(п) in ("", None)]
    if пустое_суждение:
        беды.append(f"карточка {имя}: не разобрана — пусто в "
                    f"{', '.join(пустое_суждение)}")
    if данные.get("judged_by", "pending") == "pending" and not пустое_суждение:
        беды.append(f"карточка {имя}: разбор есть, а кто его сделал — не назван "
                    "(поле judged_by)")
    return беды


def проверить(манифест: Path) -> list[str]:
    данные = yaml.safe_load(манифест.read_text(encoding="utf-8")) or {}
    беды: list[str] = []
    имя = манифест.name

    кандидаты = данные.get("candidates") or []
    if len(кандидаты) < МИНИМУМ_КАНДИДАТОВ:
        беды.append(f"{имя}: кандидатов {len(кандидаты)}, нужно не меньше "
                    f"{МИНИМУМ_КАНДИДАТОВ} — один референс это не выбор")

    выбранные = [к for к in кандидаты if к.get("verdict") == "selected"]
    if len(выбранные) != 1:
        беды.append(f"{имя}: выбранных референсов {len(выбранные)}, нужен ровно один")

    for кандидат in кандидаты:
        ссылка = кандидат.get("card", "")
        if not кандидат.get("why"):
            беды.append(f"{имя}: у кандидата {ссылка or '?'} не названо основание "
                        "вердикта")
        if not ссылка:
            беды.append(f"{имя}: у кандидата нет ссылки на карточку")
            continue
        данные_карточки, отказ = карточка(ссылка)
        if отказ:
            беды.append(f"{имя}: {отказ}")
            continue
        беды.extend(проверить_карточку(ссылка, данные_карточки))

    переносим = данные.get("what_to_adapt") or []
    if len(переносим) < 3:
        беды.append(f"{имя}: в «что переносим» {len(переносим)} пунктов — "
                    "механика переносится приёмами, а не одним словом")

    не_копируем = " ".join(данные.get("what_not_to_copy") or []).lower()
    for название, слова in ЗАПРЕТЫ.items():
        if not any(слово in не_копируем for слово in слова):
            беды.append(f"{имя}: в «что не копируем» не назван запрет — {название}")

    return беды


def main() -> int:
    беды: list[str] = []
    проверено = 0
    for сценарий in sorted(РОЛИКИ.glob("[0-9][0-9]-*.md")):
        текст = сценарий.read_text(encoding="utf-8")
        текущая = стадия(текст)
        if текущая not in ТРЕБУЮТ:
            continue
        проверено += 1
        манифест = РЕФЕРЕНСЫ / f"{сценарий.stem}.yaml"
        if not манифест.exists():
            беды.append(
                f"{сценарий.name}: стадия {текущая}, а доказательства референсов нет "
                f"({манифест.relative_to(ROOT)}). Собрать: "
                "python3 tools/trend_provider.py --out content/reels/references/cards/")
            continue
        for беда in проверить(манифест):
            беды.append(f"{сценарий.name}: {беда}")

    if not проверено:
        print("Роликов на стадии производства нет — проверять нечего")
        return 0
    for беда in беды:
        print(f"  {беда}")
    print(f"\nПроверено роликов: {проверено}, расхождений: {len(беды)}")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
