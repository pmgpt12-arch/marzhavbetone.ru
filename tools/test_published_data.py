#!/usr/bin/env python3
"""Граница публикации каталога data/. Запуск: python3 tools/test_published_data.py

ЗАЧЕМ ЭТОТ ТЕСТ. У репозитория сайта две несвязанные истории: исходная, где
`data/` цел, и опубликованная, где его нет вовсе (`.gitignore`: `data/`).
Каталог не потерян по недосмотру — внутренние материалы не публикуются
намеренно. Но одна строка оттуда внутренней не является: `navigation.yaml`
это меню сайта, видное любому посетителю, и без него проверка шапки
(`tools/check_nav.py`) падает на `FileNotFoundError` — то есть гейт сайта не
исполняется вовсе.

Отсюда две стороны одной границы, и обе проверяются здесь:
публичный файл обязан быть опубликован, внутренние каталоги — нет.

Тест намеренно спрашивает git, а не файловую систему: файл, лежащий в
рабочем дереве, но не отслеживаемый, до боевого сервера не доедет.
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПУБЛИЧНЫЙ = "data/site/navigation.yaml"

# Каталоги, которых в опубликованной истории быть не должно. Перечень закрытый
# и совпадает с тем, что перечислено в `.gitignore` как внутренние материалы.
ВНУТРЕННИЕ = ("data/business/", "data/ai/", "data/content/", "data/research/")

провалов = 0


def проверка(имя: str, тело) -> None:
    global провалов
    try:
        тело()
        print(f"  ok   {имя}")
    except Exception as ошибка:
        # Не только AssertionError: отсутствующий файл роняет проверку
        # исключением, и оно должно быть провалом строки, а не концом прогона.
        провалов += 1
        print(f"  FAIL {имя}\n         {ошибка!r}" if not isinstance(
            ошибка, AssertionError) else f"  FAIL {имя}\n         {ошибка}")


def отслеживаемые() -> list[str]:
    вывод = subprocess.run(["git", "ls-files", "data"], cwd=КОРЕНЬ,
                           capture_output=True, text=True, check=True).stdout
    return [с for с in вывод.splitlines() if с]


def меню_опубликовано() -> None:
    файлы = отслеживаемые()
    assert ПУБЛИЧНЫЙ in файлы, (
        f"{ПУБЛИЧНЫЙ} не отслеживается git. Без него tools/check_nav.py "
        f"падает на FileNotFoundError, и гейт шапки не исполняется. "
        f"Отслеживается в data/: {файлы or 'ничего'}")


def файл_на_месте() -> None:
    assert (КОРЕНЬ / ПУБЛИЧНЫЙ).is_file(), f"{ПУБЛИЧНЫЙ} нет в рабочем дереве"


def внутреннее_не_опубликовано() -> None:
    файлы = отслеживаемые()
    лишние = [ф for ф in файлы if ф.startswith(ВНУТРЕННИЕ)]
    assert not лишние, ("в опубликованную историю попали внутренние "
                        f"материалы: {лишние}")


def меню_только_публичное() -> None:
    """Содержимое — навигация, а не секреты. Проверяется признаками, а не на глаз."""
    текст = (КОРЕНЬ / ПУБЛИЧНЫЙ).read_text(encoding="utf-8")
    приметы = {
        "почта": r"[\w.+-]+@[\w-]+\.[a-zA-Z]{2,}",
        "телефон": r"\+?\d[\d\s()-]{9,}\d",
        "ключ или токен": r"(?i)(secret|token|api[_-]?key|password|passwd)\s*[:=]",
        "цена": r"(?i)\b\d{3,}\s*(?:руб|₽|rub)\b",
        "абсолютный путь машины": r"(?m)^\s*[-\w]*:?\s*/(?:home|Users|var|etc)/",
    }
    найдено = {имя: re.findall(шаблон, текст)
               for имя, шаблон in приметы.items()}
    найдено = {и: з for и, з in найдено.items() if з}
    assert not найдено, f"в публичном файле найдено непубличное: {найдено}"


def ссылки_относительны_сайту() -> None:
    """Все href — адреса самого сайта, а не внутренние адреса чего-то ещё."""
    текст = (КОРЕНЬ / ПУБЛИЧНЫЙ).read_text(encoding="utf-8")
    адреса = re.findall(r"^\s*href:\s*(\S+)", текст, re.M)
    assert адреса, "в файле нет ни одной ссылки — он ли это?"
    чужие = [а for а in адреса if not а.startswith("/")]
    assert not чужие, f"ссылки не на свой сайт: {чужие}"


def правило_игнора_держит_границу() -> None:
    """`.gitignore` обязан пускать один файл и по-прежнему держать остальное."""
    проба = "data/business/secret.yaml"
    вывод = subprocess.run(["git", "check-ignore", "-q", проба], cwd=КОРЕНЬ)
    assert вывод.returncode == 0, (
        f"{проба} НЕ игнорируется — правило исключения открыло весь data/")
    вывод = subprocess.run(["git", "check-ignore", "-q", ПУБЛИЧНЫЙ], cwd=КОРЕНЬ)
    assert вывод.returncode == 1, f"{ПУБЛИЧНЫЙ} игнорируется — его не закоммитить"


print("граница публикации data/")
проверка("меню сайта опубликовано", меню_опубликовано)
проверка("файл есть в рабочем дереве", файл_на_месте)
проверка("внутренние каталоги не опубликованы", внутреннее_не_опубликовано)
проверка("в меню нет непубличного", меню_только_публичное)
проверка("все ссылки — адреса своего сайта", ссылки_относительны_сайту)
проверка("правило игнора пускает один файл", правило_игнора_держит_границу)

print()
if провалов:
    print(f"провалов: {провалов}")
    sys.exit(1)
print("все проверки пройдены")
