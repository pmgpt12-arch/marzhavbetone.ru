    norm.paragraph_format.space_after=Pt(5); norm.paragraph_format.line_spacing=1.14
    for key,pt in [('Title',17),('Heading 1',12),('Heading 2',10.5)]:
        st=styles[key]; st.font.name='Arial'; st.font.size=Pt(pt); st.font.bold=True; st.font.color.rgb=GRAPHITE
        st.paragraph_format.space_before=Pt(11); st.paragraph_format.space_after=Pt(5)
        st.paragraph_format.keep_with_next=True
    styles['Title'].font.color.rgb=GOLD
