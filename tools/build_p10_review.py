def setup(d):
    s=d.sections[0]; s.page_height=Cm(29.7); s.page_width=Cm(21)
    s.top_margin=Cm(1.8); s.bottom_margin=Cm(1.7); s.left_margin=Cm(2); s.right_margin=Cm(2)
