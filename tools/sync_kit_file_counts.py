#!/usr/bin/env python3
"""Приводит обещанное число файлов комплекта к тому, что лежит в папке.

ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. Число файлов покупатель читает не в двух местах,
а в четырёх: шапка страницы товара, описание на ней же, карточка товара на
чужих страницах (каталог, статьи, бесплатные материалы) и строка «Покупателю
уходит N файлов» в манифесте. `tools/check_packages.py` стережёт первое и
последнее — на остальные у сайта сторожа не было, и они расходились молча:
страница полного комплекта одновременно держала 78 в шапке и 96 в описании
при 86 на диске.

КАК ОПРЕДЕЛЯЕТСЯ ХОЗЯИН ЧИСЛА. Число «N файлов» относится к тому товару,
ссылка на который стоит рядом и у которого сейчас ровно N файлов. Порядок
поиска — от узкого к широкому: своя страница товара, затем блок вокруг
(карточка, врезка, элемент списка), затем окно в 2500 знаков, затем вся
страница. Число, для которого хозяин не нашёлся однозначно, НЕ правится: оно
печатается списком, и разбирается руками. Догадка здесь дороже пропуска —
неверное число на странице товара это обещание, которого не выполнят.

    python3 tools/sync_kit_file_counts.py            # показать
    python3 tools/sync_kit_file_counts.py --write    # записать
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СКЛАД = КОРЕНЬ / "products-storage"
КОНФИГ = КОРЕНЬ / "products-config.php"

# Тот же перечень, что в mvb_build_product_zip: покупателю уходит всё,
# кроме него. Список именно перечислением, а не маской.
СЛУЖЕБНЫЕ = {".htaccess", "00-PISMO-POSLE-POKUPKI.txt", "MANIFEST.md"}

# Шапка страницы кричит заглавными: «КОМПЛЕКТ P1 / 18 ФАЙЛОВ». Регистр
# сохраняется при замене — иначе шапка поедет в нижний регистр.
ЧИСЛО = re.compile(r"(\d+)(\s+)(файл|ФАЙЛ)([а-яА-Я]*)")
ССЫЛКА = re.compile(r"(?:products/|href=\")([pt]\d+)-[a-z0-9-]*\.html")
ОБЕЩАНО = re.compile(r"(Покупателю уходит\s+)(\d+)(\s+файл[а-я]*)")
БЛОК = re.compile(r"<(article|aside|li|details)\b", re.I)
КОНЕЦ_БЛОКА = re.compile(r"</(article|aside|li|details)>", re.I)


def склонение(n: int) -> str:
    """файл / файла / файлов — по числу, а не по последней цифре наугад."""
    if 11 <= n % 100 <= 14:
        return "ов"
    последняя = n % 10
    if последняя == 1:
        return ""
    if последняя in (2, 3, 4):
        return "а"
    return "ов"


def папки() -> dict[str, str]:
    текст = КОНФИГ.read_text(encoding="utf-8")
    return dict(re.findall(
        r"^\s*'([pt]\d+)'\s*=>\s*\[.*?'dir'\s*=>\s*'([^']+)'",
        текст, re.S | re.M))


def счёт() -> dict[str, int]:
    return {sku: len([f for f in (СКЛАД / d).iterdir()
                      if f.is_file() and f.name not in СЛУЖЕБНЫЕ])
            for sku, d in папки().items() if (СКЛАД / d).is_dir()}


# Насколько число может отличаться от фактического, чтобы считаться тем же
# счётом. Ноль означал бы «правим только то, что и так верно»; большой допуск
# позволил бы переписать «18 месяцев», стоящее рядом со ссылкой на товар.
ДОПУСК = 3


def хозяин(текст: str, позиция: int, свой: str | None) -> str | None:
    """Чей это счёт. Определяется соседством, а не самим числом.

    По числу определять нельзя: до правки страница держит СТАРОЕ значение, и
    поиск «у кого сейчас столько файлов» не находит никого. Поэтому сначала
    ищется товар, а потом уже сверяется его счёт.

    Порядок важен, и он выведен из поломки. Сначала блок — карточка или
    врезка, ограниченная своим закрывающим тегом. Блок с одной ссылкой
    называет хозяина; блок с несколькими — спор, и число не трогается.
    Блок БЕЗ ссылок (так устроен `<details>` «Что входит в комплект?») отдаёт
    число своей странице, и только потом идут окно и вся страница.

    Прежняя редакция ставила окно вперёд своей страницы, и блок «Что входит
    в комплект?» доставался соседней карточке: странице p8 записали 13 файлов
    вместо 11 — счёт стоявшего рядом p7. Ошибку поймал повторный прогон этого
    же инструмента, а не глаз.
    """
    начала = [m.start() for m in БЛОК.finditer(текст, 0, позиция)]
    if начала:
        закрытие = КОНЕЦ_БЛОКА.search(текст, позиция)
        блок = текст[начала[-1]:закрытие.end() if закрытие else позиция + 600]
        свои = set(ССЫЛКА.findall(блок))
        if len(свои) == 1:
            return свои.pop()
        if len(свои) > 1:
            return None
    if свой:
        return свой
    for радиус in (900, 2000):
        окно = текст[max(0, позиция - радиус):позиция + радиус]
        свои = set(ССЫЛКА.findall(окно))
        if len(свои) == 1:
            return свои.pop()
    свои = set(ССЫЛКА.findall(текст))
    return свои.pop() if len(свои) == 1 else None


def главная(argv=None) -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--write", action="store_true")
    аргументы = разбор.parse_args(argv)

    факт = счёт()
    правок, спорных = 0, []

    # 1. Манифесты: «Покупателю уходит N файлов». По всем папкам склада, а не
    # только по товарам каталога: полный комплект отключён в products-config,
    # но его манифест тоже обещает число, и оно тоже расходится с диском.
    for манифест in sorted(СКЛАД.glob("*/MANIFEST.md")):
        каталог = манифест.parent.name
        текст = манифест.read_text(encoding="utf-8")
        нужно = len([f for f in манифест.parent.rglob("*")
                     if f.is_file() and f.name not in СЛУЖЕБНЫЕ])

        def заменить(m, нужно=нужно):
            if int(m.group(2)) == нужно:
                return m.group(0)
            return f"{m.group(1)}{нужно} файл{склонение(нужно)}"

        новый = ОБЕЩАНО.sub(заменить, текст)
        if новый != текст:
            правок += 1
            print(f"манифест {каталог}: обещано → {нужно}")
            if аргументы.write:
                манифест.write_text(новый, encoding="utf-8")

    # 2. Страницы: любое «N файлов», у которого нашёлся однозначный хозяин.
    for файл in sorted(КОРЕНЬ.glob("**/*.html")):
        if ".git" in файл.parts or "products-storage" in файл.parts:
            continue
        текст = файл.read_text(encoding="utf-8")
        свой = None
        если_товар = re.match(r"([pt]\d+)-", файл.name)
        if если_товар and файл.parent.name == "products":
            свой = если_товар.group(1)
        куски, конец, менялось = [], 0, []
        for m in ЧИСЛО.finditer(текст):
            n = int(m.group(1))
            владелец = хозяин(текст, m.start(), свой)
            путь = str(файл.relative_to(КОРЕНЬ))
            if владелец is None or владелец not in факт:
                спорных.append((путь, n, "хозяин не определился"))
                continue
            нужно = факт[владелец]
            if нужно == n:
                continue
            if abs(нужно - n) > ДОПУСК:
                спорных.append((путь, n,
                                f"рядом {владелец}, у него {нужно} — не похоже "
                                f"на тот же счёт"))
                continue
            куски.append(текст[конец:m.start()])
            корень = m.group(3)
            хвост = склонение(нужно)
            if корень.isupper():
                хвост = хвост.upper()
            куски.append(f"{нужно}{m.group(2)}{корень}{хвост}")
            конец = m.end()
            менялось.append((владелец, n, нужно))
        if менялось:
            куски.append(текст[конец:])
            правок += len(менялось)
            свод = ", ".join(f"{s}: {a}→{b}" for s, a, b in менялось)
            print(f"страница {файл.relative_to(КОРЕНЬ)}: {свод}")
            if аргументы.write:
                файл.write_text("".join(куски), encoding="utf-8")

    if спорных:
        print("\nНЕ ОПРЕДЕЛИЛОСЬ — разобрать руками:")
        for путь, n, почему in спорных:
            print(f"  {путь}: «{n} файл…» — {почему}")
    print(f"\nмест исправлено: {правок}, спорных: {len(спорных)}, "
          f"{'записано' if аргументы.write else 'показ без записи'}")
    return 1 if спорных and not аргументы.write else 0


if __name__ == "__main__":
    sys.exit(главная())
