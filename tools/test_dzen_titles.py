#!/usr/bin/env python3
"""Договор о заголовках ленты Дзена: источник, откат и шесть отказов.

ЗАЧЕМ. Заголовок под ленту и заголовок под поиск — разные строки, и вторая
в ленте стоит клика. Прежний источник — заготовки `content/dzen/*.md` —
удалён из публичного репозитория коммитом a1373b0, и сборщик на это не упал:
он возвращал пустой словарь и уходил на поисковые заголовки. Замер
28.08.2026: старый код на сегодняшнем дереве даёт «заголовок из заготовки
Дзена: 0 из 29», новый — 16 изменённых из 29 при 12 объявленных откатах.

Поэтому здесь проверяется не «функция что-то вернула», а сам договор:

  1. источник объявлен файлом данных и он на месте;
  2. переопределения доезжают до самого фида, а не только до словаря;
  3. откат случается ровно там, где записи нет, и назван поимённо;
  4. шесть способов потерять заголовок роняют сборку, а не проходят молча;
  5. флаг USE_DZEN_TITLES поднят — снятие перестаёт быть незаметным.

    python3 tools/test_dzen_titles.py
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_rss

ROOT = Path(__file__).resolve().parent.parent
ARTICLES = ROOT / "articles"

# Размеченные случаи. Слева slug статьи, справа — строка, которую этот
# заголовок нёс в заготовке Дзена до её удаления. Набор небольшой намеренно:
# он ловит подмену значений, а не пересчитывает файл сам собой.
CASES = [
    ("garantiynoe-uderzhanie-chto-eto",
     "Пять процентов, которые вы больше не увидите"),
    ("akt-osvidetelstvovaniya-skrytyh-rabot",
     "Скрытые работы закрыли. Акт подписать забыли"),
    ("stroitelnyy-musor-v-smete",
     "Мусор вывозите вы. В смете его нет"),
]

# Нижняя граница числа соответствий. Ставится руками и только вверх.
#
# Зачем она нужна: три размеченных случая ловят подмену значения, отсутствие
# файла ловит сам сборщик, — а вот тихое удаление одной записи для статьи, не
# попавшей в CASES, не ловил никто. Откат на заголовок статьи законен, и
# отличить «здесь записи никогда не было» от «запись удалили» можно только
# по счёту. Новая статья без заголовка под ленту границу не двигает: она
# растёт, когда соответствий становится больше, и никогда не опускается,
# чтобы пропустить потерю.
МИНИМУМ = 28

problems: list[str] = []


def дефект(строка: str) -> None:
    problems.append(строка)


def упасть_на(подпись: str, данные: object, статьи: Path | None = None) -> None:
    """Испорченный файл обязан ронять сборку, а не возвращать словарь."""
    with tempfile.TemporaryDirectory() as каталог:
        файл = Path(каталог) / "dzen-titles.json"
        файл.write_text(данные if isinstance(данные, str)
                        else json.dumps(данные, ensure_ascii=False),
                        encoding="utf-8")
        try:
            получено = build_rss.dzen_titles(файл, статьи or ARTICLES)
        except SystemExit:
            return
        дефект(f"{подпись}: сборка не упала, вернулось {получено!r}")


def main() -> int:
    # 1. Флаг. Снятый флаг — законная ручка на случай требования Дзена, но
    #    незаметной она быть не должна: гейт обязан её показать.
    if not build_rss.USE_DZEN_TITLES:
        дефект("USE_DZEN_TITLES снят: фид уйдёт с поисковыми заголовками")

    # 2. Источник. Файла нет — это отказ сборки, а не пустой словарь.
    if not build_rss.DZEN_TITLES.is_file():
        дефект(f"нет файла соответствий {build_rss.DZEN_TITLES}")
        for line in problems:
            print(f"ДЕФЕКТ: {line}")
        return 1

    titles = build_rss.dzen_titles()
    if not titles:
        дефект("dzen_titles() пуст — переопределений нет вовсе")
    if len(titles) < МИНИМУМ:
        дефект(f"соответствий {len(titles)}, а объявленный минимум {МИНИМУМ}: "
               "запись удалена, и статья ушла бы в ленту с поисковым "
               "заголовком молча. Снимать границу можно только вместе с "
               "решением, что заголовок под ленту этой статье не нужен")

    for slug, expected in CASES:
        if titles.get(slug) != expected:
            дефект(f"{slug}: ожидался «{expected}», получен «{titles.get(slug)}»")

    # 3. Словарь детерминирован: тот же файл — тот же порядок и те же пары.
    if titles != build_rss.dzen_titles():
        дефект("два чтения одного файла дали разное")
    if list(titles) != sorted(titles):
        дефект("порядок ключей не отсортирован — сборка недетерминирована")

    # 4. Переопределение обязано доехать до фида. Между словарём и лентой
    #    стоит ветка выпуска, и она однажды уже съедала содержимое молча.
    items = build_rss.collect()
    feed = {i["title"] for i in items}
    for slug, expected in CASES:
        if not (ARTICLES / f"{slug}.html").is_file():
            дефект(f"{slug}: статьи нет, случай проверить нечем")
            continue
        if slug in build_rss.PUBLISHED_BY_HAND:
            continue
        if expected not in feed:
            дефект(f"{slug}: заголовок «{expected}» до фида не доехал")

    # 5. Откат — только там, где записи нет. Статья с записью, уехавшая в
    #    ленту с заголовком сайта, означает, что переопределение потерялось
    #    по дороге, и это ровно тот дефект, ради которого всё написано.
    в_ленте = {i["link"].rsplit("/", 1)[-1][: -len(".html")]: i["title"]
               for i in items}
    for slug, заголовок in в_ленте.items():
        ожидаемый = titles.get(slug)
        if ожидаемый is not None and заголовок != ожидаемый:
            дефект(f"{slug}: в ленте «{заголовок}», а объявлен «{ожидаемый}»")
    откаты = sorted(s for s in в_ленте if s not in titles)

    # 6. Шесть способов потерять заголовок молча. Первый — тот самый, что
    #    случился с content/dzen: источника нет, и прежний код на это лишь
    #    возвращал пустой словарь. Последний ловит переименование slug, после
    #    которого запись перестаёт на что-либо влиять.
    with tempfile.TemporaryDirectory() as каталог:
        try:
            получено = build_rss.dzen_titles(Path(каталог) / "нет-такого.json",
                                             ARTICLES)
            дефект(f"файла нет, а сборка не упала: вернулось {получено!r}")
        except SystemExit:
            pass
    упасть_на("сломанный JSON", "{ не json")
    упасть_на("нет раздела «заголовки»", {"зачем": "…"})
    упасть_на("значение не строка", {"заголовки": {"akt-skrytyh-rabot-obrazec": 17}})
    упасть_на("дубликат slug",
              '{"заголовки": {"akt-skrytyh-rabot-obrazec": "Первый", '
              '"akt-skrytyh-rabot-obrazec": "Второй"}}')
    упасть_на("запись на несуществующую статью",
              {"заголовки": {"takoy-stati-net": "Заголовок в никуда"}})

    # 7. Фид остаётся собираемым и валидным по разбору XML.
    xml = build_rss.build(items)
    try:
        import xml.etree.ElementTree as ET
        дерево = ET.fromstring(xml)
        сколько = len(дерево.findall("./channel/item"))
        if сколько != len(items):
            дефект(f"в XML {сколько} элементов против {len(items)} собранных")
    except ET.ParseError as ошибка:
        дефект(f"фид не разбирается как XML: {ошибка}")

    if problems:
        for line in problems:
            print(f"ДЕФЕКТ: {line}")
        return 1

    print(f"Соответствий в файле: {len(titles)}; в ленте {len(items)} статей, "
          f"из них с откатом на заголовок статьи {len(откаты)}.")
    if откаты:
        print("Откат (записи нет, идёт заголовок сайта): " + ", ".join(откаты))
    print(f"Размеченных случаев сошлось: {len(CASES)}; "
          "способов потерять заголовок, роняющих сборку: 6 из 6.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
