def _текст(v) -> str:
    return re.sub(r"\s+", " ", str(v or "")).strip()


def строка(ws, начало: str, после: int = 0) -> int | None:
    """Первая строка ниже `после`, где столбец A начинается с `начало`."""
    for r in range(после + 1, ws.max_row + 1):
        if _текст(ws.cell(r, 1).value).startswith(начало):
            return r
    return None


def раскладка(ws) -> str:
    if строка(ws, "2.3.") and строка(ws, "Итого пени"):
        return "периоды"
    if строка(ws, "Неустойка по договору (%/день)") and строка(ws, "Дни просрочки"):
        return "прежняя"
    raise Раскладка(f"РАСКЛАДКА: лист «{ws.title}» не распознан ни как прежний, ни как новый")


def _строки_таблицы(ws, заголовок_блока: str, итог: str) -> tuple[list[int], int]:
    r0, r1 = строка(ws, заголовок_блока), строка(ws, итог)
    if not r0 or not r1:
        raise Раскладка(f"РАСКЛАДКА: нет блока «{заголовок_блока}» / «{итог}»")
    # r0 — заголовок блока, r0+1 — шапка таблицы, дальше строки периодов
    return list(range(r0 + 2, r1)), r1


def _вписать_периоды(ws, строки, периоды) -> None:
    if len(периоды) > len(строки):
        raise Раскладка(f"РАСКЛАДКА: периодов {len(периоды)}, строк в таблице {len(строки)}")
    for r, (нач, кон, _, база, ставка) in zip(строки, периоды):
        ws.cell(r, 2).value, ws.cell(r, 3).value = нач, кон
        ws.cell(r, 5).value, ws.cell(r, 6).value = база, ставка


def заполнить_пени(ws, периоды) -> str:
    """Вписывает периоды пеней, возвращает адрес ячейки результата."""
    if раскладка(ws) == "прежняя":
        if len(периоды) > 1:
            raise Раскладка("РАСКЛАДКА: в прежней книге одна строка неустойки, несколько периодов не ввести")
        _, _, дней, база, ставка = периоды[0]
        r_ст = строка(ws, "Неустойка по договору (%/день)")
        # Ячейки базы неустойки в прежней книге нет. Ввод — как в копиях
        # #322: для примера 1 заполнены суммы КС-2, оплаты и удержания
        # (04-S1), для примера 2 — только ставка и дни (04-S2).
        if база == 240_000:
            ws["B2"], ws["B3"], ws["B4"] = 2_400_000, 2_040_000, 360_000
        ws.cell(r_ст, 2).value = ставка
        ws.cell(строка(ws, "Дни просрочки"), 2).value = дней
        return f"D{r_ст}"
    строки, r_итог = _строки_таблицы(ws, "2.3.", "Итого пени")
    _вписать_периоды(ws, строки, периоды)
    return f"G{r_итог}"


def заполнить_395(ws, периоды) -> str:
    if раскладка(ws) == "прежняя":
        (_, _, дней, база, ставка), = периоды
        # как в копии 04-S1-B7-baza: база в B7, ставка в B5, дни в B9
        r = строка(ws, "Проценты по ст. 395")
        ws.cell(r, 2).value = база
        ws.cell(строка(ws, "Ключевая ставка"), 2).value = ставка
        ws.cell(строка(ws, "Дни просрочки"), 2).value = дней
        return f"D{r}"
    строки, r_итог = _строки_таблицы(ws, "3.", "Итого проценты")
    _вписать_периоды(ws, строки, периоды)
    return f"G{r_итог}"


def _новая(ws, что: str) -> None:
    if раскладка(ws) == "прежняя":
        raise Раскладка(f"РАСКЛАДКА: в прежней книге нет строки под «{что}»")


def _ячейка(ws, начало: str, после: int = 0) -> int:
    r = строка(ws, начало, после)
    if not r:
        raise Раскладка(f"РАСКЛАДКА: нет строки «{начало}»")
    return r


def _сводка(ws) -> int:
    r = строка(ws, "4.")
    if not r:
        raise Раскладка("РАСКЛАДКА: нет раздела «4.» со сводкой")
    return r


def заполнить_штраф_твёрдый(ws) -> str:
    _новая(ws, "штраф в твёрдой сумме")
    ws.cell(_ячейка(ws, "2.1."), 7).value = ШТРАФ_ТВЁРДЫЙ
    return f"G{_ячейка(ws, 'Штраф в твёрдой сумме', _сводка(ws))}"


def заполнить_штраф_процентный(ws, процент=ШТРАФ_ПРОЦЕНТНЫЙ[1]) -> str:
    _новая(ws, "штраф в процентах")
    ws.cell(_ячейка(ws, "2.2."), 7).value = ШТРАФ_ПРОЦЕНТНЫЙ[0]
    ws.cell(_ячейка(ws, "процент штрафа"), 7).value = процент
    return f"G{_ячейка(ws, 'сумма штрафа')}"


def заполнить_долг(ws, кс2, оплачено, удержание) -> None:
    _новая(ws, "неоплаченная сумма")
    ws.cell(_ячейка(ws, "Сумма по КС-2"), 7).value = кс2
    ws.cell(_ячейка(ws, "Фактически оплачено"), 7).value = оплачено
    ws.cell(_ячейка(ws, "из них удержание"), 7).value = удержание


def заполнить_долг_отказ(ws, кс2, оплачено) -> str:
    заполнить_долг(ws, кс2, оплачено, None)
    return f"G{_ячейка(ws, 'Неоплачено по КС-2')}"


def заполнить_сводку(ws) -> dict[str, str]:
    """Дело С1 целиком; адреса строк сводки."""
    заполнить_долг(ws, *ДОЛГ)
    заполнить_пени(ws, ПЕНИ["пример_1_из_322"][0])
    заполнить_395(ws, ПРОЦЕНТЫ_395[0])
    r4 = _сводка(ws)
    return {подпись: f"G{_ячейка(ws, подпись, r4)}" for подпись in СВОДКА_С1}


def _сценарии():
    """(имя, заполнить, ожидание): ожидание — число, словарь «подпись →
    число» для сводки или ("отказ", ключевое слово)."""
    for имя, (периоды, ожидание) in ПЕНИ.items():
        yield f"пени_{имя}", functools.partial(заполнить_пени, периоды=периоды), ожидание
    for имя, (периоды, слово) in ПЕНИ_ОТКАЗ.items():
        yield f"отказ_пени_{имя}", functools.partial(заполнить_пени, периоды=периоды), ("отказ", слово)
    yield "проценты_395_контроль", functools.partial(заполнить_395, периоды=ПРОЦЕНТЫ_395[0]), ПРОЦЕНТЫ_395[1]
    yield ("отказ_395_окончание_раньше_начала",
           functools.partial(заполнить_395, периоды=ПРОЦЕНТЫ_395_ОТКАЗ[0]), ("отказ", ПРОЦЕНТЫ_395_ОТКАЗ[1]))
    yield "штраф_твёрдый", заполнить_штраф_твёрдый, ШТРАФ_ТВЁРДЫЙ
    yield "штраф_процентный", заполнить_штраф_процентный, ШТРАФ_ПРОЦЕНТНЫЙ[2]
    yield ("отказ_штраф_отрицательный_процент",
           functools.partial(заполнить_штраф_процентный, процент=-5), ("отказ", "меньше нуля"))
    yield ("отказ_долг_оплачено_больше_КС2",
           functools.partial(заполнить_долг_отказ, кс2=100_000, оплачено=200_000), ("отказ", "больше"))
    yield ("отказ_долг_нет_суммы_КС2",
           functools.partial(заполнить_долг_отказ, кс2=None, оплачено=2_040_000), ("отказ", "заполните"))
    yield ("отказ_долг_отрицательная_оплата",
           functools.partial(заполнить_долг_отказ, кс2=2_400_000, оплачено=-1), ("отказ", "меньше нуля"))
    yield "сводка_дела_С1", заполнить_сводку, dict(СВОДКА_С1)


@functools.lru_cache(maxsize=None)
def результаты_04() -> dict[str, tuple]:
    """Сценарий → (состояние, адрес(а), значение(я) Calc, сообщения H, ожидание)."""
    try:
        import openpyxl
    except ImportError:
        raise Среда("СРЕДА: нет openpyxl") from None
    tmp = Path(tempfile.mkdtemp(prefix="p5-calc-results-"))
    try:
        исходник = tmp / КНИГА_04
        исходник.write_bytes(книги_из_архива()[КНИГА_04])
        копии, адреса, итог = [], {}, {}
        for имя, заполнить, ожидание in _сценарии():
            wb = openpyxl.load_workbook(исходник)
            try:
                адрес = заполнить(wb.worksheets[0])
            except Раскладка as e:
                итог[имя] = (str(e), None, None, [], ожидание)
                continue
            копия = tmp / f"{имя}.xlsx"
            wb.save(копия)
            копии.append(копия)
            адреса[копия.name] = (имя, адрес, ожидание)
        if копии:
            calc = пересчитать(копии, tmp)
            for файл, (имя, адрес, ожидание) in адреса.items():
                ws = openpyxl.load_workbook(calc[файл], data_only=True).worksheets[0]
                значение = ({k: ws[a].value for k, a in адрес.items()} if isinstance(адрес, dict)
                            else ws[адрес].value)
                сообщения = [_текст(ws.cell(r, СТОЛБЕЦ_ПРОВЕРКИ).value) for r in range(1, ws.max_row + 1)
                             if _текст(ws.cell(r, СТОЛБЕЦ_ПРОВЕРКИ).value)]
                итог[имя] = ("ok", адрес, значение, сообщения, ожидание)
        return итог
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _число(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _проверить(*имена: str) -> None:
    провалы = []
    for имя in имена:
        состояние, адрес, v, сообщения, ожидание = результаты_04()[имя]
        if состояние != "ok":
            провалы.append(f"{имя}: {состояние}")
        elif isinstance(ожидание, tuple):
            _, слово = ожидание
            if _число(v):
                провалы.append(f"ВВОД: {имя}: Calc {адрес} = {v!r} — некорректный ввод дал сумму")
            if not any(слово in с.lower() for с in сообщения):
                провалы.append(f"ВВОД: {имя}: нет сообщения со словом «{слово}» в столбце «Проверка»; "
                               f"сообщения {сообщения}")
        elif isinstance(ожидание, dict):
            for подпись, ждём in ожидание.items():
                x = v[подпись]
                if not _число(x) or abs(x - ждём) > ТОЧНОСТЬ:
                    провалы.append(f"АРИФМЕТИКА: {имя}: «{подпись}» {адрес[подпись]} = {x!r}, "
                                   f"ожидалось {ждём:.2f}")
        elif not _число(v) or abs(v - ожидание) > ТОЧНОСТЬ:
            провалы.append(f"АРИФМЕТИКА: {имя}: Calc {адрес} = {v!r}, ожидалось {ожидание:.2f}")
    if провалы:
        класс = Раскладка if all("РАСКЛАДКА" in п for п in провалы) else AssertionError
        raise класс("\n  ".join(провалы))


