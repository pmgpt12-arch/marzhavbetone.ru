@functools.lru_cache(maxsize=None)
def книги_из_архива() -> dict[str, bytes]:
    try:
        архив = архив_выдачи()
    except AssertionError as e:
        raise Среда(f"СРЕДА: архив P5 не собран: {e}") from None
    нет = [n for n in (КНИГА_04, КНИГА_05) if n not in архив]
    if нет:
        raise Раскладка(f"РАСКЛАДКА: в архиве выдачи нет {нет}")
    return {n: архив[n] for n in (КНИГА_04, КНИГА_05)}


def _среда_calc() -> None:
    причина = _calc_ready()
    if причина:
        raise Среда(f"СРЕДА: {причина}")


def пересчитать(файлы: list[Path], tmp: Path, формат: str = "xlsx") -> dict[str, Path]:
    """Calc headless открывает, пересчитывает и сохраняет в `формат`."""
    _среда_calc()
    out = tmp / f"calc-{формат}"
    cmd = ["soffice", f"-env:UserInstallation=file://{tmp}/profile", "--headless",
           "--norestore", "--calc", "--convert-to", формат, "--outdir", str(out),
           *map(str, файлы)]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise Среда(f"СРЕДА: запуск Calc: {e}") from None
    итог = {f.name: out / f"{f.stem}.{формат}" for f in файлы}
    нет = [n for n, p in итог.items() if not p.exists()]
    if нет:
        raise Среда(f"СРЕДА: Calc не открыл/не сохранил {нет}: {r.stderr[-400:]}")
    return итог


