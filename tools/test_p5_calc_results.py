def _текст(v) -> str:
    return re.sub(r"\s+", " ", str(v or "")).strip()


def строка(ws, начало: str) -> int | None:
    """Первая строка, где столбец A начинается с `начало`."""
    for r in range(1, ws.max_row + 1):
        if _текст(ws.cell(r, 1).value).startswith(начало):
            return r
    return None


def раскладка(ws) -> str:
    if строка(ws, "2.3.") and строка(ws, "Итого пени"):
        return "периоды"
    if строка(ws, "Неустойка по договору (%/день)") and строка(ws, "Дни просрочки"):
        return "прежняя"
    raise Раскладка(f"РАСКЛАДКА: лист «{ws.title}» не распознан ни как прежний, ни как новый")


def _строки_таблицы(ws, заголовок_блока: str, итог: str) -> tuple[list[int], int]:
    r0, r1 = строка(ws, заголовок_блока), строка(ws, итог)
    if not r0 or not r1:
        raise Раскладка(f"РАСКЛАДКА: нет блока «{заголовок_блока}» / «{итог}»")
    # r0 — заголовок блока, r0+1 — шапка таблицы, дальше строки периодов
    return list(range(r0 + 2, r1)), r1


def заполнить_пени(ws, периоды) -> str:
    """Вписывает периоды пеней, возвращает адрес ячейки результата."""
    if раскладка(ws) == "прежняя":
        if len(периоды) > 1:
            raise Раскладка("РАСКЛАДКА: в прежней книге одна строка неустойки, несколько периодов не ввести")
        _, _, дней, база, ставка = периоды[0]
        r_ст = строка(ws, "Неустойка по договору (%/день)")
        # Ячейки базы неустойки в прежней книге нет. Ввод — как в копиях
        # #322: для примера 1 заполнены суммы КС-2, оплаты и удержания
        # (04-S1), для примера 2 — только ставка и дни (04-S2).
        if база == 240_000:
            ws["B2"], ws["B3"], ws["B4"] = 2_400_000, 2_040_000, 360_000
        ws.cell(r_ст, 2).value = ставка
        ws.cell(строка(ws, "Дни просрочки"), 2).value = дней
        return f"D{r_ст}"
    строки, r_итог = _строки_таблицы(ws, "2.3.", "Итого пени")
    if len(периоды) > len(строки):
        raise Раскладка(f"РАСКЛАДКА: периодов {len(периоды)}, строк в таблице {len(строки)}")
    for r, (нач, кон, _, база, ставка) in zip(строки, периоды):
        ws.cell(r, 2).value, ws.cell(r, 3).value = нач, кон
        ws.cell(r, 5).value, ws.cell(r, 6).value = база, ставка
    return f"G{r_итог}"


def заполнить_395(ws, периоды) -> str:
    if раскладка(ws) == "прежняя":
        (_, _, дней, база, ставка), = периоды
        # как в копии 04-S1-B7-baza: база в B7, ставка в B5, дни в B9
        r = строка(ws, "Проценты по ст. 395")
        ws.cell(r, 2).value = база
        ws.cell(строка(ws, "Ключевая ставка"), 2).value = ставка
        ws.cell(строка(ws, "Дни просрочки"), 2).value = дней
        return f"D{r}"
    строки, r_итог = _строки_таблицы(ws, "3.", "Итого проценты")
    for r, (нач, кон, _, база, ставка) in zip(строки, периоды):
        ws.cell(r, 2).value, ws.cell(r, 3).value = нач, кон
        ws.cell(r, 5).value, ws.cell(r, 6).value = база, ставка
    return f"G{r_итог}"


def _новая(ws, что: str) -> None:
    if раскладка(ws) == "прежняя":
        raise Раскладка(f"РАСКЛАДКА: в прежней книге нет строки под «{что}»")


def заполнить_штраф_твёрдый(ws) -> str:
    _новая(ws, "штраф в твёрдой сумме")
    r = строка(ws, "2.1.")
    ws.cell(r, 7).value = ШТРАФ_ТВЁРДЫЙ
    return f"G{строка(ws, 'Итого неустойка')}"


def заполнить_штраф_процентный(ws) -> str:
    _новая(ws, "штраф в процентах")
    база, процент, _ = ШТРАФ_ПРОЦЕНТНЫЙ
    ws.cell(строка(ws, "2.2."), 7).value = база
    ws.cell(строка(ws, "процент штрафа"), 7).value = процент
    return f"G{строка(ws, 'сумма штрафа')}"


def заполнить_итог(ws) -> str:
    _новая(ws, "основной долг без гарантийного удержания")
    кс2, оплачено, гарантийное, _ = ДОЛГ
    ws.cell(строка(ws, "Сумма по КС-2"), 7).value = кс2
    ws.cell(строка(ws, "Фактически оплачено"), 7).value = оплачено
    ws.cell(строка(ws, "Из неоплаченного"), 7).value = гарантийное
    заполнить_пени(ws, ПЕНИ["пример_1_из_322"][0])
    заполнить_395(ws, ПРОЦЕНТЫ_395[0])
    return f"G{строка(ws, 'ИТОГО к взысканию')}"


def _сценарии():
    for имя, (периоды, ожидание) in ПЕНИ.items():
        yield f"пени_{имя}", functools.partial(заполнить_пени, периоды=периоды), ожидание
    yield "проценты_395_контроль", functools.partial(заполнить_395, периоды=ПРОЦЕНТЫ_395[0]), ПРОЦЕНТЫ_395[1]
    yield "штраф_твёрдый", заполнить_штраф_твёрдый, ШТРАФ_ТВЁРДЫЙ
    yield "штраф_процентный", заполнить_штраф_процентный, ШТРАФ_ПРОЦЕНТНЫЙ[2]
    yield "итог_дела_С1", заполнить_итог, ИТОГ


@functools.lru_cache(maxsize=None)
def результаты_04() -> dict[str, tuple[str, float | None, float, str]]:
    """Сценарий → (раскладка или провал, значение Calc, ожидание, адрес)."""
    try:
        import openpyxl
    except ImportError:
        raise Среда("СРЕДА: нет openpyxl") from None
    tmp = Path(tempfile.mkdtemp(prefix="p5-calc-results-"))
    try:
        исходник = tmp / КНИГА_04
        исходник.write_bytes(книги_из_архива()[КНИГА_04])
        копии, адреса, итог = [], {}, {}
        for имя, заполнить, ожидание in _сценарии():
            wb = openpyxl.load_workbook(исходник)
            try:
                адрес = заполнить(wb.worksheets[0])
            except Раскладка as e:
                итог[имя] = (str(e), None, ожидание, "")
                continue
            копия = tmp / f"{имя}.xlsx"
            wb.save(копия)
            копии.append(копия)
            адреса[копия.name] = (имя, адрес, ожидание)
        if копии:
            calc = пересчитать(копии, tmp)
            for файл, (имя, адрес, ожидание) in адреса.items():
                v = openpyxl.load_workbook(calc[файл], data_only=True).worksheets[0][адрес].value
                итог[имя] = ("ok", v if isinstance(v, (int, float)) else None, ожидание,
                             f"{адрес} = {v!r}")
        return итог
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _проверить(*имена: str) -> None:
    провалы = []
    for имя in имена:
        состояние, v, ожидание, где = результаты_04()[имя]
        if состояние != "ok":
            провалы.append(f"{имя}: {состояние}")
        elif v is None or abs(v - ожидание) > ТОЧНОСТЬ:
            провалы.append(f"АРИФМЕТИКА: {имя}: Calc {где}, ожидалось {ожидание:.2f}")
    if провалы:
        класс = Раскладка if all("РАСКЛАДКА" in п for п in провалы) else AssertionError
        raise класс("\n  ".join(провалы))


