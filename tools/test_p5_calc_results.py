#!/usr/bin/env python3
"""Книги 04 и 05 P5 считают верно после пересчёта в LibreOffice Calc.

MB001-P5-FIX-1. Покупательская приёмка (`MB001_P5_BUYER_ACCEPTANCE.md`,
PR #322, коммит `5640580`, дефект К-1) нашла, что `04-raschet-ubytkov.xlsx`
считает договорную неустойку формулой `=B8*B9` — «%/день × дни» без базы.
Calc выдавал 1,95 вместо 4 680,00 и 1,5 вместо 36 000,00.
`test_p5_spreadsheets.py` этого не ловил: он проверяет текст формул и
отсутствие ошибок, но не число, которое получает покупатель.

Здесь проверяется результат после пересчёта Calc:
- книги берутся из настоящего архива выдачи `mvb_build_product_zip('p5')`
  (харнесс `test_p5_documents.архив_выдачи`), а не из генератора;
- в копию книги вписываются исходные данные, Calc пересчитывает и
  сохраняет, и значение читается из сохранённого файла;
- ожидаемые суммы посчитаны вручную и записаны числом рядом со сценарием.

Сценарии: оба примера #322, нулевая база, один день, два периода с разной
базой, проценты по ст. 395 (контроль, этот расчёт и был верным), штрафы в
твёрдой сумме и в процентах, сводка по делу.

Дополнение FIX-1: некорректный ввод (окончание раньше начала, отрицательные
сумма, база и ставка, незаполненное обязательное поле) не даёт суммы в
рублях — ячейка результата пуста, в столбце «Проверка» сообщение. Сводка
показывает долг, проценты и каждый вид неустойки отдельно и не складывает
их в «сумму к взысканию»: совместимость требований — вопрос Р-026 (В-1).
Неоплаченная сумма показана и целиком, и без удержания с ненаступившим
сроком возврата — исходные суммы не теряются. Итог реестра 05 подписан как
сумма записей, а не размер требования: одна сумма может стоять в нём
несколько раз.

Дополнение FIX-2 (приёмка #333): ставка, набранная со знаком % («0,05%»,
«16%»), не даёт суммы — Calc хранит её в 100 раз меньше, поэтому ставка
пеней ниже 0,01 % в день и ключевая ставка ниже 1 % годовых не считаются
(Н-1). Набор проверяется настоящим вводом строк в Calc с профилем ru-RU.
«Срок ответа» в 05 — дата ДД.ММ.ГГГГ и на печати не превращается в «###»
(Н-2).

Дополнение #364 (приёмка #357, §4): порог ловил только малые числа, «1%» в
день давал 1 162,50 вместо 116 250,00. Теперь ставка F в таблицах пеней и
ст. 395 — текстовая ячейка: набор «1%», «0,05%», «16%» остаётся строкой и
считается как 1, 0,05, 16. Число в F (вставка, формула) знака % не хранит —
строка не считается, в «Проверке» сообщение «вставлена числом». Поэтому в
сценариях ставка — строка, как при наборе; `Число(...)` — число в ячейке.

Причины провала разделены, чтобы отказ среды не выдавался за дефект книги:
- `СРЕДА:` — нет PHP, Calc, openpyxl или pdfinfo, Calc не открыл файл;
- `РАСКЛАДКА:` — в книге нет места под сценарий (например, нет таблицы
  периодов). Это дефект книги, но не арифметический;
- `АРИФМЕТИКА:` — Calc посчитал, и число не совпало с ожидаемым;
- `ВВОД:` — при некорректном вводе книга всё равно выдала сумму или не
  назвала ошибку.

    python3 tools/test_p5_calc_results.py
    python3 -m pytest tools/test_p5_calc_results.py -q
    P5_PRODUCTS_DIR=/другое/дерево/products-storage python3 tools/test_p5_calc_results.py
"""
