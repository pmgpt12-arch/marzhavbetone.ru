def _страницы_pdf(pdf: Path) -> int:
    pdfinfo = shutil.which("pdfinfo")
    if not pdfinfo:
        raise Среда("СРЕДА: нет pdfinfo (poppler-utils)")
    r = subprocess.run([pdfinfo, str(pdf)], capture_output=True, text=True)
    m = re.search(r"^Pages:\s+(\d+)", r.stdout, re.M)
    if not m:
        raise Среда(f"СРЕДА: pdfinfo не прочитал {pdf.name}: {r.stderr}")
    return int(m.group(1))


