"""Карточка одного товара на странице другого не должна врать о нём.

Два утверждения, которые витрина делает про чужой комплект и которые
проверяются файлами, а не вычиткой:

* число файлов («12 файлов») — против фактического состава папки выдачи;
* название комплекта («комплект «…»») — против каталога `mvb_products()`.

Ни `check_packages.py`, ни `build_preview.py --check` этого не смотрят: первый
сверяет папки между собой, второй — предпросмотр со своим комплектом. Обе
находки аудита T1–T6 (Д-1 и Д-2) жили ровно в этой щели: карточка P5 на
странице t3 обещала 12 файлов при 11 в выдаче, а t5 называла P8 снятым именем.
Цена щели измерена — правка состава в одном месте оставляет ложное число во
всех, кто на него ссылается.
"""
import re
import unittest
from html import unescape
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СТРАНИЦЫ = КОРЕНЬ / 'products'
МАСТЕРА = КОРЕНЬ / 'products-storage'

# То же, что исключает mvb_build_product_zip() при сборке архива покупателю.
НЕ_В_ВЫДАЧУ = {'.htaccess', '00-PISMO-POSLE-POKUPKI.txt', 'MANIFEST.md'}


def каталог():
    """sku → {name, dir} из живых записей mvb_products(). Закомментированные не в счёт."""
    текст = (КОРЕНЬ / 'products-config.php').read_text()
    начало = текст.index('function mvb_products()')
    товары = {}
    for блок in re.finditer(
        r"^\s*'(\w+)'\s*=>\s*\[(.*?)^\s*\],", текст[начало:], re.S | re.M
    ):
        sku, тело = блок.group(1), блок.group(2)
        имя = re.search(r"'name'\s*=>\s*'(.*?)',", тело, re.S)
        папка = re.search(r"'dir'\s*=>\s*'(.*?)',", тело)
        if имя and папка:
            товары[sku] = {'name': имя.group(1), 'dir': папка.group(1)}
    return товары


def файлов_в_выдаче(папка):
    каталог_товара = МАСТЕРА / папка
    if not каталог_товара.is_dir():
        return None
    return sum(1 for f in каталог_товара.iterdir() if f.name not in НЕ_В_ВЫДАЧУ)


def карточки(страница):
    """Карточки чужих товаров: (sku, число файлов или None)."""
    текст = страница.read_text()
    свой = страница.stem.split('-')[0]
    for карточка in re.findall(
        r'<article[^>]*class="[^"]*product-card[^"]*"[^>]*>(.*?)</article>', текст, re.S
    ):
        ссылка = re.search(r'href="(?:\.\./)?(?:products/)?(\w+)-[a-z0-9-]+\.html', карточка)
        if not ссылка or ссылка.group(1) == свой:
            continue
        число = re.search(r'(\d+)\s+файл', карточка)
        yield ссылка.group(1), int(число.group(1)) if число else None


class ЧужойТоварОписанВерно(unittest.TestCase):
    def setUp(self):
        self.товары = каталог()
        self.страницы = sorted(СТРАНИЦЫ.glob('[pt][0-9]*.html'))
        self.assertTrue(self.страницы, 'страницы товаров не найдены')

    def test_число_файлов_чужого_комплекта_совпадает_с_его_выдачей(self):
        расхождения = []
        for страница in self.страницы:
            for sku, заявлено in карточки(страница):
                if заявлено is None or sku not in self.товары:
                    continue
                факт = файлов_в_выдаче(self.товары[sku]['dir'])
                if факт is not None and заявлено != факт:
                    расхождения.append(
                        f'{страница.name}: карточка {sku} обещает {заявлено} файлов, '
                        f'в выдаче {факт}'
                    )
        self.assertEqual([], расхождения, '\n' + '\n'.join(расхождения))

    def test_комплект_назван_именем_из_каталога(self):
        """Имя комплекта на странице — каталожное или его сокращение.

        Проверяется весь текст страницы, а не только карточки: Д-2 аудита
        T1–T6 жила в абзаце над карточкой, и проверка по карточкам её не
        видела — при том что двумя строками ниже в самой карточке стояло
        верное имя.

        Сокращение допускается намеренно: карточки режут длинный хвост
        каталожного имени, и запрещать это значило бы ломать витрину ради
        проверки. Не допускается имя, которого в каталоге нет вовсе, — снятое
        или перепутанное с чужим.
        """
        имена = {т['name'].replace('Комплект «', '').rstrip('»') for т in self.товары.values()}
        расхождения = []
        for страница in self.страницы:
            текст = unescape(re.sub(r'<[^>]+>', ' ', страница.read_text()))
            for название in sorted(set(re.findall(r'[Кк]омплект\w*\s+«([^»]+)»', текст))):
                if not any(
                    название in каталожное or каталожное in название
                    for каталожное in имена
                ):
                    расхождения.append(
                        f'{страница.name}: комплект назван «{название}» — '
                        f'такого имени в каталоге нет'
                    )
        self.assertEqual([], расхождения, '\n' + '\n'.join(расхождения))


if __name__ == '__main__':
    unittest.main(verbosity=2)
