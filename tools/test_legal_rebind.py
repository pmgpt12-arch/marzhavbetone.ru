#!/usr/bin/env python3
"""Что механизм переноса вердикта обязан отклонять. Сети не требует.

Перенос — единственное место контура, где вердикт переезжает на новую
версию файла без захода проверяющего. Значит, это же и единственное место,
через которое юридически значимую правку можно протащить незамеченной.
Здесь закреплено, что протащить нельзя.

Мутации написаны не «на всякий случай», а по способам обхода, которые
механизм действительно допустил бы без соответствующего запрета: широкий
токен, дата не о сверке, подмена формулы, подмена ссылки на норму, чужой
вид правки.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from legal_rebind import перенос_допустим  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# Кусок, похожий на настоящую врезку: дата сверки внутри предложения о сверке.
ВРЕЗКА = ("Порядок расчёта сверен с текстом действующих норм {дата}: "
          "нормативная сверка сопоставляет формулировки и порядок со "
          "статьями закона и правовой позиции по вашему спору не оценивает.")
ТЕЛО = (" Проценты по ст. 395 ГК РФ начисляются по день фактической уплаты. "
        "Число дней в году берётся фактическое. G4=ROUND($D4*$E4/100*$C4/$F4,2)")


def _пара(дата_было="15.08.2026", дата_стало="16.08.2026", хвост_новый=ТЕЛО):
    старый = ВРЕЗКА.format(дата=дата_было) + ТЕЛО
    новый = ВРЕЗКА.format(дата=дата_стало) + хвост_новый
    return старый, новый


def test_честная_правка_даты_проходит():
    старый, новый = _пара()
    можно, почему = перенос_допустим(старый, новый, "15.08.2026", "16.08.2026")
    assert можно, почему


def test_правка_смысла_вместе_с_датой_отклоняется():
    """Главный случай: дата прикрывает подмену правового утверждения."""
    старый, новый = _пара(хвост_новый=ТЕЛО.replace(
        "по день фактической уплаты", "по день вынесения решения суда"))
    можно, почему = перенос_допустим(старый, новый, "15.08.2026", "16.08.2026")
    assert not можно
    assert "не совпали" in почему, почему


def test_широкий_токен_не_пропускает_смысл():
    """«не подлежат» → «подлежат» равенство бы прошло, вид токена — нет."""
    старый = "Проценты не подлежат взысканию." + ВРЕЗКА.format(дата="15.08.2026")
    новый = "Проценты подлежат взысканию." + ВРЕЗКА.format(дата="15.08.2026")
    можно, почему = перенос_допустим(старый, новый, "не подлежат", "подлежат")
    assert not можно
    assert "не календарная дата" in почему, почему


def test_дата_вне_предложения_о_сверке_отклоняется():
    """Дата акта или срока — не наша дата сверки, переносу не подлежит."""
    старый = "Оплатить в срок до 15.08.2026 по договору."
    новый = "Оплатить в срок до 16.08.2026 по договору."
    можно, почему = перенос_допустим(старый, новый, "15.08.2026", "16.08.2026")
    assert not можно
    assert "не в предложении о сверке" in почему, почему


def test_подмена_формулы_отклоняется():
    старый, новый = _пара(хвост_новый=ТЕЛО.replace("/$F4,2)", "/365,2)"))
    можно, почему = перенос_допустим(старый, новый, "15.08.2026", "16.08.2026")
    assert not можно
    assert "не совпали" in почему, почему


def test_подмена_нормы_отклоняется():
    старый, новый = _пара(хвост_новый=ТЕЛО.replace("ст. 395 ГК РФ",
                                                   "ст. 317.1 ГК РФ"))
    можно, почему = перенос_допустим(старый, новый, "15.08.2026", "16.08.2026")
