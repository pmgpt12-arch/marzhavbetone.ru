def test_разное_число_вхождений_токена_отклоняется():
    старый = ВРЕЗКА.format(дата="15.08.2026") + ТЕЛО
    новый = ВРЕЗКА.format(дата="16.08.2026") + ТЕЛО + \
        " Сверка проведена 16.08.2026."
    можно, почему = перенос_допустим(старый, новый, "15.08.2026", "16.08.2026")
    assert not можно, почему


def test_ссылка_на_версию_это_полный_sha():
    """Относительная ссылка вида `abc123^` разъезжается вместе с историей.

    Замер 16.08.2026: `1a0c0f9^` работал локально и падал в Actions кодом
    128 — там клон глубиной 1, и родителя в нём просто нет. Полный SHA не
    чинит мелкий клон сам по себе, но убирает вторую переменную: ссылка
    либо разрешается, либо объекта нет, и третьего прочтения не остаётся.
    """
    import re
    import yaml
    записи = yaml.safe_load(
        (ROOT / "data/legal/rebinds.yaml").read_text(encoding="utf-8"))
    for з in записи.get("rebinds") or []:
        assert re.fullmatch(r"[0-9a-f]{40}", з["from_ref"]), \
            f"{з['from_ref']} — не полный SHA"


def test_объявленные_переносы_репозитория_годны():
    """Интеграция: реальная пара версий из истории, а не выдуманная."""
    p = subprocess.run([sys.executable, "tools/legal_rebind.py"], cwd=ROOT,
                       capture_output=True, text=True, timeout=120)
    assert p.returncode == 0, p.stdout + p.stderr


def main() -> int:
    tests = [v for k, v in sorted(globals().items()) if k.startswith("test_")]
    failed = 0
    for t in tests:
        try:
            t()
        except AssertionError as e:
            failed += 1
            print(f"  ✗ {t.__name__}: {e}")
        else:
            print(f"  ✓ {t.__name__}")
    print(f"\nПроверок {len(tests)}, упало {failed}.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
