#!/usr/bin/env python3
"""Отменённая лестница покупки не возвращается в пользовательский текст.

Дефект, ради которого написана проверка, пережил два прохода. MB005
зафиксировал модель: t1 и p1 — два самостоятельных товара под разный объём
задачи, обязательного маршрута между ними нет, зачёта, доплаты и апгрейда
не существует. Витрины t1/p1 вычищали, а два формулировочных остатка
доехали до MB008 и жили на живом сайте:

  · «…это следующая ступень» — статья neoplata называла комплект p1
    следующей ступенью после t1: последовательность покупки возвращалась
    одной фразой;
  · «…и это причина доплатить до старшего комплекта» — страница t3
    подавала старший комплект как платное повышение над купленным.

Проверка ловит возврат именно этих формулировок отменённой модели. Это
список фраз, а не выводимое правило, и в проекте уже была причина считать
список слабым сторожем: «список устарел бы молча» (check_storefront_claims).
Здесь он осознанно, потому что охраняется не утверждение о содержимом, а
возврат трёх стёртых формулировок — по одной на каждую правку MB008 и одну
на отменённый зачёт стоимости. Фраза общих слов («шаг», «ступень», «доплат»)
намеренно не является: слово «доплата» в юридическом тексте — это недоплата
по удержанию, а «первый шаг» — этап процедуры, и оба живут на витрине
законно.

Слово ищется в видимом тексте страницы: скрипты и разметка вырезаются, как
в check_storefront_claims, чтобы JSON-LD не удваивал находки, а код
диагностики не ловился собственным комментарием.

    python3 tools/test_mb005_no_ladder_copy.py

Код возврата 1, если отменённая формулировка вернулась на витрину.
"""
from __future__ import annotations

import pathlib
import re
import sys

SITE = pathlib.Path(__file__).resolve().parents[1]

# Отменённые формулировки модели MB005 — ровно те, что были сняты.
#   «следующая ступень»          — MB008-1: статья neoplata, маршрут t1 → p1;
#   «доплатить до»               — MB008-2: страница t3, платное повышение;
#   «зачёт стоимости»            — зачёт отменён решением владельца (MB005),
#                                  в тексте ему не место ни утверждением,
#                                  ни отрицанием;
#   «разрыв до ядра»             — то же: модель «ядро» больше не существует,
#                                  живёт только в исторических записях;
#   «апгрейд», «upgrade»         — апгрейда не существует.
ЛЕСТНИЦА = re.compile(
    r"следующая ступень|доплатить до|зачёт стоимости|разрыв до ядра|апгрейд|upgrade",
    re.I)

# Разделы, чей текст витриной не является: инструменты, тесты, история,
# выдача после покупки. Обход каталога — как в check_nav, чтобы новая
# витрина попадала под проверку сама.
ПРОПУСК_КАТАЛОГОВ = {"content", "data", "demo", "downloads", "media", "node_modules",
                     "orders", "products-storage", "tools", ".git", ".github",
                     ".claude", "docs", "taxonomy"}


def видимый_текст(html: str) -> str:
    без_скриптов = re.sub(r"<script.*?</script>", " ", html, flags=re.S)
    без_стилей = re.sub(r"<style.*?</style>", " ", без_скриптов, flags=re.S)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", без_стилей))


def витринные_страницы() -> list[pathlib.Path]:
    out = []
    for путь in sorted(SITE.glob("**/*.html")):
        части = set(путь.relative_to(SITE).parts[:-1])
        if части & ПРОПУСК_КАТАЛОГОВ:
            continue
        out.append(путь)
    return out


def main() -> int:
    беды = []
    проверено = 0
    for страница in витринные_страницы():
        текст = видимый_текст(страница.read_text(encoding="utf-8"))
        проверено += 1
        находка = ЛЕСТНИЦА.search(текст)
        if находка:
            имя = страница.relative_to(SITE)
            s = max(0, находка.start() - 90)
            e = min(len(текст), находка.end() + 90)
            беды.append(
                f"{имя}: в видимом тексте возвращена формулировка отменённой "
                f"модели («{находка.group(0)}»): …{текст[s:e]}…\n"
                "        Товары самостоятельные, маршрут между ними не "
                "описывается (MB005): граница объёма называется прямо, "
                "словами «другой комплект», «отдельный комплект», "
                "«другой объём работы».")

    for беда in беды:
        print(f"  ✗ {беда}")
    print(f"\nВитринных страниц проверено: {проверено}, дефектов: {len(беды)}")
    if not беды:
        print("Отменённая лестница покупки на витрине не читается.")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
