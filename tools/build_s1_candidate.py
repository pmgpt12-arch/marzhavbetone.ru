def note(ws, cell, text, bold=False):
    ws[cell] = text
    ws[cell].alignment = WRAP
    if bold:
        ws[cell].font = BOLD


def fit_height(ws, row, text, first_col: int, last_col: int):
    """Высота строки под текст в колонках first..last. Calc не подбирает
    высоту объединённых ячеек сам: без неё текст обрезается."""
    width = sum(ws.column_dimensions[get_column_letter(i)].width or 8.43 for i in range(first_col, last_col + 1))
    lines = max(1, -(-int(len(str(text)) * 1.15) // int(width)))
    ws.row_dimensions[row].height = max(ws.row_dimensions[row].height or 0, 15 * lines + 3)


def fit_banners(ws, last_col: int, rows=(1, 2)):
    """Заголовок (A1) и пояснение (A2) листа — на всю ширину таблицы. В колонке
    «№» шириной 5 знаков они рвали слова по слогам (S1-02А, проверка вёрстки)."""
    for r in rows:
        text = ws.cell(row=r, column=1).value
        if not text:
            continue
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=last_col)
        ws.cell(row=r, column=1).alignment = WRAP
        fit_height(ws, r, text, 1, last_col)


# ─────────────────────── воспроизводимость ───────────────────────────

STAMP = re.compile(rb"(<dcterms:(?:created|modified)[^>]*>)[^<]*(</dcterms:)")
# openpyxl пишет в docProps/app.xml свою версию: без фиксации сборка зависела бы от неё
APP = re.compile(rb"<Application>Microsoft Excel[^<]*</Application>")


def normalize(path: Path) -> None:
    """Фиксирует метки времени в zip и в docProps/core.xml, версию openpyxl в docProps/app.xml."""
    src = path.read_bytes()
    out = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(src)) as zin, \
            zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zout:
        for info in zin.infolist():
            data = zin.read(info.filename)
            if info.filename == "docProps/core.xml":
                data = STAMP.sub(rb"\g<1>2026-09-27T00:00:00Z\g<2>", data)
            elif info.filename == "docProps/app.xml":
                data = APP.sub(b"<Application>Microsoft Excel Compatible / Openpyxl 3.1.5</Application>", data)
            zi = zipfile.ZipInfo(info.filename, date_time=(2026, 9, 27, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            zout.writestr(zi, data)
    path.write_bytes(out.getvalue())


def save(obj, path: Path):
    if isinstance(obj, openpyxl.Workbook):
        # Печать: альбомная ориентация, все колонки листа на ширину страницы
        for ws in obj.worksheets:
            ws.page_setup.orientation = "landscape"
            ws.page_setup.paperSize = ws.PAPERSIZE_A4
            ws.sheet_properties.pageSetUpPr.fitToPage = True
            ws.page_setup.fitToWidth = 1
            ws.page_setup.fitToHeight = 0
    obj.save(str(path))
    normalize(path)


