def manifest(out: Path):
    lines = [
        "# S1 «Система получения оплаты за выполненные работы» — кандидат",
        "",
        f"Редакция: `{R.EDITION}`. Статус: **BUILD CANDIDATE / NO PUBLIC LAUNCH**.",
        "",
        "Внутренний документ. Кандидат не адресован ни одним sku в",
        "`products-config.php`, лежит вне `products-storage/` и вне деплоя.",
        "Собирается `tools/build_s1_candidate.py`; маршрут — `tools/s1_route.py`.",
        "",
        "## Состав",
        f"Покупателю уходило бы {len(R.FILES)} файлов.",
        "",
    ]
    for name, (purpose, _) in R.FILES.items():
        lines.append(f"- `{name}` — {purpose}")
    lines += ["", "## Служебные (не выдаются)", ""] + [f"- `{n}`" for n in sorted(R.INTERNAL)] + [""]
    (out / "MANIFEST.md").write_text("\n".join(lines), encoding="utf-8")
    (out / "ROUTE-MAP.json").write_text(
        json.dumps(R.route_map(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


BUILDERS = [f00, f01, f02, f03, f04, f05, f06, f07, f08, f09, f10, f11, f12, f13, f14, f15, manifest]


def build(out: Path) -> Path:
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for b in BUILDERS:
        b(out)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=R.CANDIDATE)
    args = ap.parse_args()
    out = build(args.out)
    for f in sorted(out.iterdir()):
        print(f"  {f.name}  {f.stat().st_size} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
