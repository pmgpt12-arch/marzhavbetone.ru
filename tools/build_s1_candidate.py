def head(ws, row, headers, widths=None):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font, c.fill, c.border, c.alignment = BOLD, GREY, BOX, WRAP
    if widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w


def inputs(ws, rng):
    for row in ws[rng]:
        for c in row:
            c.fill, c.border, c.font = YELLOW, BOX, BLUE_FONT


def boxed(ws, rng, fmt=None):
    for row in ws[rng]:
        for c in row:
            c.border = BOX
            c.alignment = WRAP
            if fmt:
                c.number_format = fmt


def listval(ws, rng, options):
    dv = DataValidation(type="list", formula1='"' + ",".join(options) + '"', allow_blank=True)
    dv.error = "Выберите значение из списка"
    dv.errorTitle = "Недопустимое значение"
    ws.add_data_validation(dv)
    dv.add(rng)


def note(ws, cell, text, bold=False):
    ws[cell] = text
    ws[cell].alignment = WRAP
    if bold:
        ws[cell].font = BOLD


