STAMP = re.compile(rb"(<dcterms:(?:created|modified)[^>]*>)[^<]*(</dcterms:)")


def normalize(path: Path) -> None:
    """Фиксирует метки времени в zip и в docProps/core.xml."""
    src = path.read_bytes()
    out = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(src)) as zin, \
            zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zout:
        for info in zin.infolist():
            data = zin.read(info.filename)
            if info.filename == "docProps/core.xml":
                data = STAMP.sub(rb"\g<1>2026-09-27T00:00:00Z\g<2>", data)
            zi = zipfile.ZipInfo(info.filename, date_time=(2026, 9, 27, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            zout.writestr(zi, data)
    path.write_bytes(out.getvalue())


def save(obj, path: Path):
    if isinstance(obj, openpyxl.Workbook):
        # Печать: альбомная ориентация, все колонки листа на ширину страницы
        for ws in obj.worksheets:
            ws.page_setup.orientation = "landscape"
            ws.page_setup.paperSize = ws.PAPERSIZE_A4
            ws.sheet_properties.pageSetUpPr.fitToPage = True
            ws.page_setup.fitToWidth = 1
            ws.page_setup.fitToHeight = 0
    obj.save(str(path))
    normalize(path)


