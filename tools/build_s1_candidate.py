def table(doc, headers, rows=(), blank_rows: int = 0, widths=None, pt=None):
    """`widths` — ширины колонок в см (сумма ≤ 15,2 — полоса набора): без них
    Writer делит ширину поровну, и в узких колонках слова рвутся посередине
    (#320, S-2). `pt` — кегль таблицы, если колонок много."""
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        cell.paragraphs[0].add_run(str(h)).bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
    for n in range(blank_rows):
        cells = t.add_row().cells
        cells[0].text = str(len(rows) + n + 1) if headers[0].startswith("№") else ""
    if widths:
        assert len(widths) == len(headers) and sum(widths) <= 15.24, widths
        t.autofit = False
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
            for cell in t.columns[i].cells:
                cell.width = Cm(w)
    if pt:
        for row in t.rows:
            for cell in row.cells:
                for par in cell.paragraphs:
                    for run in par.runs:
                        run.font.size = Pt(pt)
    doc.add_paragraph()
    return t


