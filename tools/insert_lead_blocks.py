MARKER = '    <section class="article-links"'


def block(slug: str, reason: str) -> str:
    m = FREE[slug]
    items = ''.join(f'<li>{f}</li>' for f in m['files'])
    return (
        '    <div class="article-lead" style="margin:40px 0;padding:32px;'
        'border:2px solid var(--orange);border-radius:8px;">\n'
        '      <p class="eyebrow" style="color:var(--orange);">'
        'БЕСПЛАТНО, ЗА EMAIL</p>\n'
        f'      <h3>{m["title"]}</h3>\n'
        f'      <p>{reason}</p>\n'
        f'      <ul>{items}</ul>\n'
        f'      <a class="button" href="/materialy/{slug}.html">'
        'Забрать материалы →</a>\n'
        '    </div>\n\n'
    )


def main() -> int:
    changed = 0
    for name, (slug, reason) in PAIRS.items():
        path = ROOT / 'articles' / f'{name}.html'
        text = path.read_text(encoding='utf-8')
        if 'class="article-lead"' in text:
            print(f'{name}: блок уже стоит, пропускаю')
            continue
        if text.count(MARKER) != 1:
            print(f'{name}: якорь «Читайте также» встречается '
                  f'{text.count(MARKER)} раз — не трогаю', file=sys.stderr)
            return 1
        path.write_text(text.replace(MARKER, block(slug, reason) + MARKER),
                        encoding='utf-8')
        print(f'{name} → {slug}')
        changed += 1
    print(f'изменено файлов: {changed}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
