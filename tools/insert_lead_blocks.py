"""Врезает блок бесплатного материала в семь статей, на которые ведёт Дзен.

Блок ставится после платного CTA и перед «Читайте также»: читатель,
готовый купить, видит комплект первым; читатель, не готовый, уходит
не пустым, а с четырьмя файлами и оставленным адресом.
"""
