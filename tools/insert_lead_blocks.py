MARKER = '    <section class="article-links"'


def block(slug: str, reason: str) -> str:
    m = FREE[slug]
    items = ''.join(f'<li>{f}</li>' for f in m['files'])
    return (
        '    <div class="article-lead" style="margin:40px 0;padding:32px;'
        'border:2px solid var(--orange);border-radius:8px;">\n'
        '      <p class="eyebrow" style="color:var(--orange);">'
        'БЕСПЛАТНО, ЗА EMAIL</p>\n'
        f'      <h3>{m["title"]}</h3>\n'
        f'      <p>{reason}</p>\n'
        f'      <ul>{items}</ul>\n'
        f'      <a class="button" href="/materialy/{slug}.html">'
        'Забрать материалы →</a>\n'
        '    </div>\n\n'
    )


# Уже стоящий блок целиком, вместе с отбивкой в две строки после него.
# Вложенных div внутри блока нет — первый же </div> его и закрывает.
STANDING = re.compile(r'[ \t]*<div class="article-lead".*?</div>\n\n',
                      re.S)


def main() -> int:
    inserted = updated = 0
    for name, (slug, reason) in PAIRS.items():
        path = ROOT / 'articles' / f'{name}.html'
        text = path.read_text(encoding='utf-8')
        wanted = block(slug, reason)

        standing = STANDING.search(text)
        if standing:
            if standing.group(0) == wanted:
                continue
            path.write_text(text[:standing.start()] + wanted
                            + text[standing.end():], encoding='utf-8')
            print(f'{name} → {slug} (блок заменён)')
            updated += 1
            continue

        if text.count(MARKER) != 1:
            print(f'{name}: якорь «Читайте также» встречается '
                  f'{text.count(MARKER)} раз — не трогаю', file=sys.stderr)
            return 1
        path.write_text(text.replace(MARKER, wanted + MARKER),
                        encoding='utf-8')
        print(f'{name} → {slug}')
        inserted += 1
    print(f'вставлено блоков: {inserted}, приведено к объявленному: {updated}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
