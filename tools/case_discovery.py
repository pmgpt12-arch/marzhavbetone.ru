#!/usr/bin/env python3
"""Discovery: сигналы для семантического ядра «Маржи в бетоне».

Сигнал — это формулировка боли, тема, угол подачи, поисковый запрос по
кейсам или продуктовая гипотеза, выписанная руками с форума, из вопросов,
отраслевой ленты или чужого блога. Он отвечает на вопрос «о чём люди
спрашивают и какими словами», и только на него.

СИГНАЛ НЕ СТАНОВИТСЯ ФАКТОМ. Форумное «КС-2 подписан, денег нет четыре
месяца» годится в тему, заголовок и поисковый запрос — и никуда больше.
Фактическое утверждение материала подтверждается первичным документом, и
занимается этим `case_package`, другой контур с другими правилами. Отсюда
здесь НЕТ ни гейта источника, ни нормативной сверки, ни проверки сроков,
цен и применимости: на этой стадии проверять в записи нечего, кроме её
структуры. `sudact.ru`, форум и чужой блог равны — важно, что спросили, а
не кто издал.

ЧЕГО ЗДЕСЬ НЕТ. Ни сети, ни парсинга сайтов, ни вызова модели, ни очереди
публикации, ни расписаний. Модуль читает файл, который владелец ведёт
руками, и печатает отчёт. Собирать сайты и звать модель он не умеет
по устройству, а не по договорённости: список импортов закрыт проверкой.

КАК ВЕСТИ. Файл JSONL, одна запись в строке:

    {"id": "pain-ks2-no-payment-001",
     "text": "КС-2 подписан, денег нет четыре месяца",
     "topic": "неоплата после приёмки",
     "source_url": "https://example.invalid/thread/1",
     "source_type": "forum",
     "found_at": "2026-09-19",
     "tags": ["кс-2", "неоплата", "подрядчик"],
     "possible_content_angle": "что фиксировать после подписания КС-2",
     "possible_case_query": "КС-2 подписан оплата не поступила арбитраж"}

Обязательны `text`, `topic`, `source_type`, `found_at`, `tags`. Адреса у
ручной заметки может не быть. `source_type` — одно из: forum, qa,
industry_media, law_firm_blog, competitor, official_index, manual.

Необязательные `possible_content_angle`, `possible_case_query` и
`possible_product_idea` — гипотезы, а не планы: отчёт их собирает, решение
по ним за владельцем.

    python3 tools/case_discovery.py import --input <jsonl>
    python3 tools/case_discovery.py report --input <jsonl>
    python3 tools/case_discovery.py report --input <jsonl> --json

`import` проверяет структуру и снимает точные дубли; `report` печатает
картину: что чаще болит и что брать в работу.

Файл с сигналами живёт в `data/`, которого в этом репозитории нет
(`.gitignore`: внутренние материалы только локально). Образец лежит в
самой проверке `tools/test_case_discovery.py`.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from collections import Counter
from pathlib import Path

# Типы источников. Перечень закрыт не ради строгости, а ради частот: пока
# тип пишется свободной строкой, «форум» и «forum» разъезжаются, и счёт по
# источникам перестаёт что-либо значить.
ТИПЫ_ИСТОЧНИКА = ("forum", "qa", "industry_media", "law_firm_blog",
                  "competitor", "official_index", "manual")

ОБЯЗАТЕЛЬНЫЕ = ("text", "topic", "source_type", "found_at", "tags")

# Необязательные поля гипотез. Пустые в отчёт не идут.
ГИПОТЕЗЫ = {
    "possible_content_angle": "angles",
    "possible_case_query": "queries",
    "possible_product_idea": "product_ideas",
}

ДАТА = re.compile(r"^\d{4}-\d{2}-\d{2}$")

# Сколько тем отдаётся в работу одним заходом. Не порог качества, а
# граница внимания: список на сорок строк не разбирается никогда.
В_РАБОТУ = 10


def _norm(значение: object) -> str:
    """Схлопывает пробелы и регистр. Для сравнения, не для показа."""
    текст = unicodedata.normalize("NFKC", str(значение or ""))
    return re.sub(r"\s+", " ", текст).strip().casefold()


def _чисто(значение: object) -> str:
    """Показываемое значение: пробелы по краям и внутри приведены."""
    текст = unicodedata.normalize("NFKC", str(значение or ""))
    return re.sub(r"\s+", " ", текст).strip()


def check_signal(запись: object) -> list[str]:
    """Структура записи. Смысл её не проверяется здесь ничем и никогда."""
    if not isinstance(запись, dict):
        return ["запись не объект JSON"]

    беды: list[str] = []
    for поле in ОБЯЗАТЕЛЬНЫЕ:
        if поле not in запись:
            беды.append(f"нет обязательного поля {поле}")
            continue
        значение = запись[поле]
        if поле == "tags":
            if not isinstance(значение, list) or not [т for т in значение if _чисто(т)]:
                беды.append("поле tags: нужен непустой список меток")
        elif not _чисто(значение):
            беды.append(f"поле {поле} пустое")

    тип = _чисто(запись.get("source_type"))
    if тип and тип not in ТИПЫ_ИСТОЧНИКА:
        беды.append(f"поле source_type: «{тип}» вне перечня "
                    f"({', '.join(ТИПЫ_ИСТОЧНИКА)})")

    дата = _чисто(запись.get("found_at"))
    if дата and not ДАТА.match(дата):
        беды.append(f"поле found_at: «{дата}» не в виде ГГГГ-ММ-ДД")

    return беды


def normalize_signal(запись: dict) -> dict:
    """Запись к одному виду. Слова не трогаются: они и есть материал."""
    сигнал = {
        "id": _чисто(запись.get("id")),
        "text": _чисто(запись.get("text")),
        "topic": _чисто(запись.get("topic")),
        "source_url": _чисто(запись.get("source_url")),
        "source_type": _чисто(запись.get("source_type")),
        "found_at": _чисто(запись.get("found_at")),
        "tags": [_чисто(т) for т in запись.get("tags") or [] if _чисто(т)],
    }
    for поле in ГИПОТЕЗЫ:
        значение = _чисто(запись.get(поле))
        if значение:
            сигнал[поле] = значение
    return сигнал


def signal_key(сигнал: dict) -> str:
    """Ключ дубля: нормализованные текст и тема, и ничего больше.

    Сравнение точное по устройству. Похожесть здесь вреднее пропуска:
    «денег нет четыре месяца» и «денег нет второй месяц» — две разные
    боли, и в семантическом ядре нужна частота каждой. Склеив их, мы
    потеряем то единственное, ради чего сигналы и собираются.
    """
    return _norm(сигнал.get("text")) + "\u0000" + _norm(сигнал.get("topic"))


def absorb_duplicate(оставленный: dict, дубль: dict) -> None:
    """Дубль вливается в оставленную запись, а не выбрасывается целиком.

    Формулировка у них одна, но выписаны они разными людьми и в разных
    местах: у одного стоит тег «подрядчик», у другого — угол подачи.
    Выбросив вторую запись со всем содержимым, мы теряем ровно тот
    словарь, ради которого Discovery и ведётся, — и теряем молча.

    Порядок вливания не важен: теги дописываются недостающими по
    алфавиту, из спорных гипотез берётся первая по алфавиту. Иначе отчёт
    по тем же сигналам в другом порядке строк давал бы другие числа —
    найдено собственной проверкой на переставленном вводе.
    """
    новые = sorted(set(дубль.get("tags") or []) - set(оставленный["tags"]))
    оставленный["tags"].extend(новые)
    for поле in ГИПОТЕЗЫ:
        значения = {з for з in (оставленный.get(поле), дубль.get(поле)) if з}
        if значения:
            оставленный[поле] = min(значения)


def load_signals(path: str | Path) -> dict:
    """JSONL → сигналы, дубли и невалидные записи. Каждая беда названа."""
    сигналы: list[dict] = []
    дубли: list[dict] = []
    невалидные: list[dict] = []
    видели: dict[str, dict] = {}

    текст = Path(path).read_text(encoding="utf-8")
    for номер, строка in enumerate(текст.splitlines(), 1):
        if not строка.strip():
            continue
        try:
            запись = json.loads(строка)
        except json.JSONDecodeError as ошибка:
            невалидные.append({
                "line": номер, "id": "", "raw": строка[:120],
                "problems": [f"строка {номер}: не разбирается как JSON ({ошибка.msg})"],
            })
            continue

        беды = check_signal(запись)
        if беды:
            имя = _чисто(запись.get("id")) if isinstance(запись, dict) else ""
            невалидные.append({"line": номер, "id": имя, "problems": беды})
            continue

        сигнал = normalize_signal(запись)
        сигнал["line"] = номер
        ключ = signal_key(сигнал)
        if ключ in видели:
            absorb_duplicate(видели[ключ], сигнал)
            дубли.append({"line": номер, "id": сигнал["id"],
                          "text": сигнал["text"], "topic": сигнал["topic"],
                          "tags": сигнал["tags"],
                          "source_type": сигнал["source_type"],
                          "duplicate_of": видели[ключ]["id"] or видели[ключ]["text"]})
            continue
        видели[ключ] = сигнал
        сигналы.append(сигнал)

    return {"signals": сигналы, "duplicates": дубли, "invalid": невалидные,
            "input": str(path)}


def _частоты(значения: list[str], формы_из: list[str] | None = None) -> list[list]:
    """Счёт по смыслу, порядок и подпись — устойчивые.

    Считается по нормализованному значению: «Неоплата после приёмки» и
    «неоплата после приёмки» — одна тема, и в частотах они обязаны
    сложиться. Найдено собственной проверкой на переставленном вводе: до
    этого счёт шёл по показываемой строке, и одна тема разъезжалась на
    две от того, какая запись пришла первой.

    Подпись выбирается той же нормализацией: самая частая форма записи, а
    при равенстве — первая по алфавиту. Голосуют за неё ВСЕ записи, включая
    снятые дублями (`формы_из`): иначе подпись зависела бы от того, какой
    из дублей пришёл первым, и отчёт по тем же сигналам в другом порядке
    строк подписывал бы тему иначе. На счёт дубли при этом не влияют.

    Порядок списка тоже задан явно: порядок словаря Python идёт порядком
    вставки, и без сортировки отчёт за эту неделю нельзя сравнить с прошлой.
    """
    счёт: Counter = Counter()
    формы: dict[str, Counter] = {}
    for значение in значения:
        ключ = _norm(значение)
        if not ключ:
            continue
        счёт[ключ] += 1
        формы.setdefault(ключ, Counter())[значение] += 1
    for значение in формы_из or []:
        ключ = _norm(значение)
        if ключ in формы:
            формы[ключ][значение] += 1

    подпись = {ключ: sorted(вид.items(), key=lambda п: (-п[1], п[0]))[0][0]
               for ключ, вид in формы.items()}
    return [[подпись[ключ], число] for ключ, число in
            sorted(счёт.items(), key=lambda п: (-п[1], подпись[п[0]]))]


def build_report(итог: dict) -> dict:
    """Картина по сигналам. Ни одного суждения — только счёт и перечни."""
    сигналы = итог["signals"]

    снятые = итог.get("duplicates") or []
    темы = _частоты([с["topic"] for с in сигналы if с["topic"]],
                    [д.get("topic", "") for д in снятые])
    теги = _частоты([т for с in сигналы for т in с["tags"]],
                    [т for д in снятые for т in д.get("tags") or []])
    # Источники считаются по ВСЕМ записям, включая снятые дублями: одна и
    # та же жалоба, найденная на форуме и в вопросах, встречена дважды, и
    # «откуда приходят сигналы» — вопрос про встречи, а не про боли.
    источники = _частоты([с["source_type"] for с in сигналы if с["source_type"]]
                         + [д.get("source_type", "") for д in снятые
                            if д.get("source_type")])
    формулировки = _частоты([с["text"] for с in сигналы if с["text"]])

    гипотезы = {}
    for поле, имя in ГИПОТЕЗЫ.items():
        гипотезы[имя] = sorted({с[поле] for с in сигналы if с.get(поле)})

    # «Боль» здесь — тема со своими формулировками: владельцу нужно и то,
    # как часто про это спрашивают, и какими словами.
    по_темам: dict[str, list[dict]] = {}
    for с in сигналы:
        по_темам.setdefault(_norm(с["topic"]), []).append(с)

    в_работу = []
    for тема, число in темы[:В_РАБОТУ]:
        свои = по_темам.get(_norm(тема), [])
        в_работу.append({
            "topic": тема,
            "signals": число,
            "phrasings": sorted({с["text"] for с in свои}),
            "queries": sorted({с["possible_case_query"] for с in свои
                               if с.get("possible_case_query")}),
            "angles": sorted({с["possible_content_angle"] for с in свои
                              if с.get("possible_content_angle")}),
        })

    return {
        "input": итог.get("input", ""),
        "signals": len(сигналы),
        "duplicates": len(итог["duplicates"]),
        "invalid": len(итог["invalid"]),
        "topics": темы,
        "tags": теги,
        "source_types": источники,
        "pains": темы,
        "phrasings": формулировки,
        "angles": гипотезы["angles"],
        "queries": гипотезы["queries"],
        "product_ideas": гипотезы["product_ideas"],
        "take_next": в_работу,
        "duplicate_records": итог["duplicates"],
        "invalid_records": итог["invalid"],
    }


def _перечень(заголовок: str, пары: list[list], предел: int = 15) -> list[str]:
    if not пары:
        return [f"{заголовок}: пусто"]
    строки = [f"{заголовок}:"]
    строки += [f"  {число:>3}  {имя}" for имя, число in пары[:предел]]
    if len(пары) > предел:
        строки.append(f"  … ещё {len(пары) - предел}")
    return строки


def render_report(отчёт: dict) -> str:
    """Отчёт владельцу: что болит и что брать в работу."""
    строки = [
        f"Сигналов: {отчёт['signals']}   "
        f"дублей снято: {отчёт['duplicates']}   "
        f"невалидных: {отчёт['invalid']}",
        "",
        "Сигнал — это тема, заголовок или запрос. Фактом статьи он не",
        "становится: факты подтверждает первичный документ, это другой контур.",
        "",
    ]
    строки += _перечень("Что чаще всего болит (темы)", отчёт["pains"])
    строки += [""] + _перечень("Слова, которыми это называют", отчёт["phrasings"])
    строки += [""] + _перечень("Теги", отчёт["tags"])
    строки += [""] + _перечень("Откуда сигналы (с учётом снятых дублей)",
                               отчёт["source_types"])

    строки += ["", f"Взять в работу (до {В_РАБОТУ} тем):"]
    for место, тема in enumerate(отчёт["take_next"], 1):
        строки.append(f"  {место}. {тема['topic']} — сигналов {тема['signals']}")
        for фраза in тема["phrasings"]:
            строки.append(f"       «{фраза}»")
        for запрос in тема["queries"]:
            строки.append(f"       запрос: {запрос}")
        for угол in тема["angles"]:
            строки.append(f"       угол: {угол}")

    for заголовок, ключ in (("Углы подачи", "angles"),
                            ("Запросы по кейсам", "queries"),
                            ("Продуктовые гипотезы", "product_ideas")):
        строки += ["", f"{заголовок}:"]
        строки += [f"  - {з}" for з in отчёт[ключ]] or ["  пусто"]

    строки += ["", f"Дубли ({отчёт['duplicates']}):"]
    строки += [f"  строка {д['line']}: «{д['text']}» ≡ {д['duplicate_of']}"
               for д in отчёт["duplicate_records"]] or ["  нет"]

    строки += ["", f"Невалидные записи ({отчёт['invalid']}):"]
    for запись in отчёт["invalid_records"]:
        имя = запись.get("id") or "без id"
        строки.append(f"  строка {запись['line']} ({имя}): "
                      + "; ".join(запись["problems"]))
    if not отчёт["invalid_records"]:
        строки.append("  нет")

    return "\n".join(строки) + "\n"


def render_import(итог: dict) -> str:
    """Что дал импорт: принято, снято дублями, отброшено с причиной."""
    строки = [f"Принято сигналов: {len(итог['signals'])}",
              f"Снято точными дублями: {len(итог['duplicates'])}"]
    строки += [f"  строка {д['line']}: «{д['text']}» ≡ {д['duplicate_of']}"
               for д in итог["duplicates"]]
    строки.append(f"Отброшено невалидных: {len(итог['invalid'])}")
    for запись in итог["invalid"]:
        имя = запись.get("id") or "без id"
        строки.append(f"  строка {запись['line']} ({имя}): "
                      + "; ".join(запись["problems"]))
    return "\n".join(строки) + "\n"


def main(argv=None) -> int:
    разбор = argparse.ArgumentParser(
        description="Discovery: сигналы для семантического ядра. "
                    "Сигнал не факт: юридической проверки здесь нет.")
    команды = разбор.add_subparsers(dest="команда", required=True)

    ввод = argparse.ArgumentParser(add_help=False)
    ввод.add_argument("--input", required=True, help="файл JSONL с сигналами")

    команды.add_parser("import", parents=[ввод],
                       help="проверить структуру и снять точные дубли")
    отчёт = команды.add_parser("report", parents=[ввод],
                               help="картина: что болит и что брать в работу")
    отчёт.add_argument("--json", action="store_true", help="машинный вывод")

    аргументы = разбор.parse_args(argv)
    путь = Path(аргументы.input)
    if not путь.exists():
        print(f"Файла нет: {путь}", file=sys.stderr)
        return 2

    итог = load_signals(путь)
    if аргументы.команда == "import":
        print(render_import(итог), end="")
        return 0

    собранное = build_report(итог)
    if getattr(аргументы, "json", False):
        print(json.dumps(собранное, ensure_ascii=False, indent=2, sort_keys=True))
    else:
        print(render_report(собранное), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
