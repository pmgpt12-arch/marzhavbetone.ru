#!/usr/bin/env python3
"""P5 не обещает результата, которого нечем подтвердить, и инструкция
описывает тот архив, который покупатель скачал.

Issue pmgpt12-arch/marzhavbetone.ru#306 (MB001-R2-P5). В `00-START-HERE.txt`
P5 стояло «половина удержаний не переживает эту проверку»: доли нет ни в
одном файле, ни в одном замере, источника у неё нет (дефект P5-01, PR #300).
Страница P5 обещала «инструкцию по возврату каждого рубля» и «сроки исковой
давности» — в составе есть одна строка про давность в PDF `07` (S-9, PR #293).
Инструкция при этом велела открыть первым файл 07 и тут же утверждала, что
файлы пронумерованы в порядке применения, а про 06, 08 и 10 не говорила
ничего.

Проверяется то, что читает покупатель: `00-START-HERE.txt` P5 и страница
P5 целиком — видимый текст, meta, og и Schema.org. Тексты .docx/.pdf P5
собирает `products-storage/build_paid_07.py`, их правка ждёт слияния
PR #298 и здесь не проверяется.

Запуск без pytest: python3 tools/test_p5_claims.py
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_packages as cp                              # noqa: E402

P5 = cp.STORAGE / "07-uderzhaniya-shtrafy-zachety"
START = P5 / "00-START-HERE.txt"
PAGE = cp.PAGES / "p5-shtrafy-uderzhaniya.html"

# Доля или частота без источника. Цифра с «%» в тексте P5 — всегда такая
# доля или договорное условие, выданное за общее правило («удержали 5%»).
СТАТИСТИКА = re.compile(
    r"\d+(?:[.,]\d+)?\s*%"
    r"|\bполовин\w*"
    r"|\bтрет(?:ь|и|ью)\b"
    r"|\bчетверт\w*"
    r"|\bбольшинств\w*"
    r"|\bв\s+\d+\s+случа\w*\s+из\s+\d+",
    re.I)

# Обещания результата и свойств, которых в составе нет. Причина — рядом:
# снимать строку можно только вместе с тем, что делает её правдой.
ОБЕЩАНИЯ = {
    "каждого рубля": "результат спора не зависит от комплекта",
    "каждый рубль": "результат спора не зависит от комплекта",
    "исковой давност": "о давности в составе одна строка в PDF 07 (S-9, PR #293)",
    "контррасч": "в 02 и 03 контррасчёта нет, расчёт — в 04",
    "прямо названы случаи": "случаев «когда идти к юристу» в файлах P5 нет, есть форма 10",
    "сказано прямо": "о приоритете договора в файлах P5 не сказано",
    "не переживает": "доля без источника (P5-01, PR #300)",
}

# Раздел 4 инструкции: строка «   имя.ext» или «   имя.ext   ← …»
СТРОКА_СОСТАВА = re.compile(r"^\s{3}(\d{2}-[\w.-]+\.\w+)\b", re.M)
НОМЕР_В_СКОБКАХ = re.compile(r"\((\d{2}(?:\s*,\s*\d{2})*)\)")


def текст_страницы(raw: str) -> str:
    """Всё, что страница утверждает: видимый текст, meta и Schema.org."""
    raw = re.sub(r"<style\b.*?</style>", " ", raw, flags=re.S)
    raw = re.sub(r"<script\b(?![^>]*ld\+json)[^>]*>.*?</script>", " ", raw, flags=re.S)
    meta = " ".join(re.findall(r'<meta\b[^>]*\bcontent="([^"]*)"', raw))
    return html.unescape(re.sub(r"<[^>]+>", " ", raw) + " " + meta)


def раздел(текст: str, номер: int) -> str:
    m = re.search(rf"^{номер}\. .*?(?=^\d+\. |^-{{10,}}|\Z)", текст, re.M | re.S)
    assert m, f"в инструкции нет раздела {номер}"
    return m.group(0)


def неподтверждённое(текст: str) -> list[str]:
    найдено = [f"«{m.group(0)}» — доля без источника" for m in СТАТИСТИКА.finditer(текст)]
    найдено += [f"«{фраза}» — {почему}" for фраза, почему in ОБЕЩАНИЯ.items()
                if фраза in текст.lower()]
    return найдено


def расхождения_инструкции(текст: str, файлы: list[str]) -> list[str]:
    """Что инструкция говорит о составе неверно или не говорит вовсе."""
    проблемы = []
    выдаётся = set(файлы)

    перечень = set(СТРОКА_СОСТАВА.findall(раздел(текст, 4))) | {"00-START-HERE.txt"}
    if перечень != выдаётся:
        проблемы.append(
            f"раздел 4: лишние {sorted(перечень - выдаётся)}, не названы {sorted(выдаётся - перечень)}")

    по_номеру = {f[:2]: f for f in файлы}
    первый = [f for f in по_номеру.values() if f in раздел(текст, 2)]
    if len(первый) != 1:
        проблемы.append(f"раздел 2 называет не один файл, а {первый}")
    названы = {n.strip() for m in НОМЕР_В_СКОБКАХ.finditer(раздел(текст, 3))
               for n in m.group(1).split(",")}
    нет_файла = sorted(n for n in названы if n not in по_номеру)
    if нет_файла:
        проблемы.append(f"раздел 3 ссылается на номера без файла: {нет_файла}")
    рабочие = {n for n in по_номеру if n != "00"} - {p[:2] for p in первый}
    молчит = sorted(рабочие - названы)
    if молчит:
        проблемы.append(f"раздел 3 не говорит, когда нужны файлы {молчит}")

    номера = sorted(int(n) for n in по_номеру if n != "00")
    пропуски = [f"{n:02d}" for n in range(номера[0], номера[-1] + 1) if f"{n:02d}" not in по_номеру]
    for n in пропуски:
        if not re.search(rf"[Нн]омера\s+{n}\s+нет", текст):
            проблемы.append(f"номера {n} в архиве нет, и инструкция не говорит почему")

    if первый and первый[0] != по_номеру[f"{номера[0]:02d}"] and "в котором их обычно применяют" in текст:
        проблемы.append("первым открывается не первый по номеру файл, а инструкция "
                        "называет нумерацию порядком применения")

    pdf = [f for f in файлы if f.endswith(".pdf")]
    if len(pdf) == 1 and re.search(r"PDF\s+—\s+\S+ы\b", текст):
        проблемы.append(f"PDF в архиве один ({pdf[0]}), а инструкция говорит о нескольких")
    return проблемы


# ─────────────────────────────── проверки ───────────────────────────────

def test_инструкция_p5_без_неподтверждённых_обещаний() -> None:
    плохое = неподтверждённое(START.read_text(encoding="utf-8"))
    assert not плохое, "00-START-HERE.txt P5:\n  " + "\n  ".join(плохое)


def test_страница_p5_без_неподтверждённых_обещаний() -> None:
    плохое = неподтверждённое(текст_страницы(PAGE.read_text(encoding="utf-8")))
    assert not плохое, f"{PAGE.name}:\n  " + "\n  ".join(плохое)


def test_инструкция_p5_совпадает_с_составом() -> None:
    файлы = sorted(cp.delivered(P5))
    проблемы = расхождения_инструкции(START.read_text(encoding="utf-8"), файлы)
    assert not проблемы, "00-START-HERE.txt P5 не совпадает с архивом:\n  " + "\n  ".join(проблемы)


def test_детекторы_различают_случаи() -> None:
    """Сторож самой проверки: иначе зелёный результат ничего не значит."""
    assert неподтверждённое("половина удержаний не переживает эту проверку")
    assert неподтверждённое("Когда удержали 5% гарантийного взноса")
    assert неподтверждённое("инструкция по возврату каждого рубля")
    assert not неподтверждённое("Посмотреть комплект")
    assert not неподтверждённое("Здесь 3 документа из 6")

    файлы = ["00-START-HERE.txt", "01-a.docx", "02-b.pdf", "04-c.xlsx"]
    верно = ("2. ОТКРОЙТЕ\n   02-b.pdf\n3. КОГДА\n   (01) и (04). Номера 03 нет.\n"
             "4. ЧТО\n   00-START-HERE.txt\n   01-a.docx\n   02-b.pdf\n   04-c.xlsx\n5. Х\n")
    assert расхождения_инструкции(верно, файлы) == []
    assert расхождения_инструкции(верно.replace("(04)", "(05)"), файлы)
    assert расхождения_инструкции(верно.replace("   04-c.xlsx\n5", "5"), файлы)
    assert расхождения_инструкции(верно.replace(" Номера 03 нет.", ""), файлы)
    assert расхождения_инструкции(
        верно + "Файлы пронумерованы в том порядке, в котором их обычно применяют.", файлы)
    assert расхождения_инструкции(верно + "PDF — чек-листы и алгоритмы.", файлы)
    assert not расхождения_инструкции(верно + "PDF (02) — алгоритм проверки.", файлы)


def main() -> int:
    провал = 0
    for имя, проверка in sorted(globals().items()):
        if not имя.startswith("test_"):
            continue
        try:
            проверка()
        except AssertionError as ошибка:
            провал += 1
            print(f"ПРОВАЛ  {имя}\n{ошибка}")
        else:
            print(f"ок  {имя}")
    return 1 if провал else 0


if __name__ == "__main__":
    sys.exit(main())
