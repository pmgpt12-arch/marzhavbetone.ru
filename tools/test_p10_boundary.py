#!/usr/bin/env python3
"""Граница P10 ↔ P12: что названо входящим — то и выдаётся, и один файл — один текст.

P10 «Ответ на претензию» выделен 11.08.2026 из прежнего единого комплекта,
который остался за P12 «Спор с суммой». Восемь документов P10 лежат в P12
под теми же именами. Аудит #300 нашёл, что тексты переехали в P10 вместе с
утверждениями о составе P12: словарь полей называл «входящими в комплект»
соглашение и акт передачи фронта, страница P10 говорила о «трёх документах
из девятнадцати». Первая правка (#311) развела четыре общих файла: под одним
именем в двух архивах оказались два разных текста. Это вторая поломка того
же рода — покупатель обоих комплектов и владелец видят один файл, а читают
разное, и следующая правка одного из них молча не доедет до другого.

Правила, которые здесь проверяются:

1. **Одно имя — один покупательский файл.** Всякий документ с одинаковым
   именем в архивах P10 и P12 совпадает побайтно. Свои у каждого товара
   только `00-START-HERE.txt` (оглавление архива) и служебный MANIFEST.
2. **Общий документ говорит правду в обоих архивах.** Файл, которого нет в
   одном из комплектов, называется номером с пометкой «только в «Споре с
   суммой»», а не «файлом этого комплекта».
3. **Ссылка ведёт в выдаваемый файл.** «Шаблон NN», «файл NN», «чек-лист NN»
   в документах и книгах указывают на номер, который есть в архиве, где они
   лежат (или несут пометку правила 2).
4. **Состав называется по архиву.** START-HERE, MANIFEST и страница каждого
   товара перечисляют ровно то, что уходит покупателю, и одно число файлов.
5. **Граница считается по двум папкам.** Все документы P10 есть в P12; счёт
   «новыми будут N из M» равен разности; тот же состав записан в исходнике
   страниц (ai-business-os, `P10_Page_Composition.md`), когда он рядом.
6. **Старые ложные номера и утверждения не возвращаются.**

Запуск без pytest: python3 tools/test_p10_boundary.py
"""
from __future__ import annotations

import html
import os
import re
import sys
import zipfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СКЛАД = КОРЕНЬ / "products-storage"
P10 = СКЛАД / "15-otvet-na-pretenziyu-baza"
P12 = СКЛАД / "12-otvet-na-pretenziyu"
СТРАНИЦА_P10 = КОРЕНЬ / "products" / "p10-otvet-na-pretenziyu.html"
СТРАНИЦА_P12 = КОРЕНЬ / "products" / "p12-spor-s-summoy.html"
ИСХОДНИК = Path(os.environ.get("AI_BUSINESS_OS", КОРЕНЬ.parent / "ai-business-os")) \
    / "projects" / "marzha_v_betone" / "product" / "P10_Page_Composition.md"

# Тот же перечень, что в mvb_build_product_zip (products-config.php).
СЛУЖЕБНЫЕ = {".htaccess", "00-PISMO-POSLE-POKUPKI.txt", "MANIFEST.md"}
СВОИ_У_ТОВАРА = {"00-START-HERE.txt"}
ПОМЕТКА = "только в «Споре с суммой»"

ЧИСЛА = {"восемь": 8, "девять": 9, "одиннадцать": 11, "двенадцать": 12,
         "девятнадцать": 19, "девятнадцати": 19, "двадцать": 20, "двадцати": 20}

# Правило 6: формулировки, которые уже были ложными в выдаче.
СТАРЫЕ_ЛОЖНЫЕ = (
    "чек-лист профилактики",             # такого файла нет ни в P10, ни в P12
    "чек-лист 06", "чек-листа 06",       # номер из прежнего единого комплекта
    "Т40 (17)",                          # код без расшифровки в примере 41
    "(файл этого комплекта)",            # о соглашении, которого в P10 нет
    "(входит в комплект)",               # то же в словаре полей
    "редакции 1.1",                      # история выпуска в документе покупателя
    "«шаблон 12»", "(шаблон 12)", "(шаблон 13)", "(шаблон 14)",
    "файла «Алгоритм действий при задержке оплаты»",   # файл P1/T1
    "по файлу «Алгоритм действий при задержке оплаты»",
    "PDF — чек-листы",                   # в P10 и P12 нет ни одного PDF
)

# Документы, которые есть только в P12: по ним общий файл может лишь
# сослаться с пометкой, а не назвать их своими.
ЧУЖИЕ_ПРИЗНАКИ = ("соглашени", "акт передачи фронта", "входного контроля",
                  "регламент", "реестр", "опись доказательств", "вопрос",
                  "предупреждени")


def архив(папка: Path) -> list[str]:
    return sorted(p.name for p in папка.iterdir()
                  if p.is_file() and p.name not in СЛУЖЕБНЫЕ)


def рабочие(папка: Path) -> list[str]:
    return [f for f in архив(папка) if f not in СВОИ_У_ТОВАРА]


def номера(папка: Path) -> set[str]:
    return {f[:2] for f in рабочие(папка)}


def тексты(путь: Path) -> list[str]:
    """Видимый текст файла по абзацам (docx) или ячейкам (xlsx)."""
    with zipfile.ZipFile(путь) as z:
        if путь.suffix == ".docx":
            части = [n for n in z.namelist() if n.startswith("word/") and n.endswith(".xml")]
            out = []
            for n in части:
                xml = z.read(n).decode("utf-8")
                for блок in re.findall(r"<w:p[ >].*?</w:p>", xml, re.S):
                    out.append(html.unescape("".join(re.findall(r"<w:t[^>]*>(.*?)</w:t>", блок, re.S))))
            return out
        out = []
        for n in z.namelist():
            if n.startswith("xl/") and n.endswith(".xml") and ("worksheets/" in n or "comments" in n
                                                               or n.endswith("sharedStrings.xml")):
                xml = z.read(n).decode("utf-8")
                for блок in re.findall(r"<(?:c|si|comment)\b.*?</(?:c|si|comment)>", xml, re.S):
                    out.append(html.unescape(re.sub(r"<[^>]+>", "", блок)))
        return out


def поля(текст: str) -> set[str]:
    return {re.split(r"[:,—]", m)[0].strip() for m in re.findall(r"\{\{(.*?)\}\}", текст)}


def видимый_текст(разметка: str) -> str:
    без_кода = re.sub(r"<(script|style)\b.*?</\1>", " ", разметка, flags=re.S)
    без_комментариев = re.sub(r"<!--.*?-->", " ", без_кода, flags=re.S)
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", без_комментариев)))


def документы(папка: Path) -> list[Path]:
    return [папка / f for f in рабочие(папка) if f.endswith((".docx", ".xlsx"))]


# ------------------------------------------------------ 1. одно имя — один файл

def test_общие_документы_P10_и_P12_совпадают_побайтно() -> None:
    общие = sorted(set(рабочие(P10)) & set(рабочие(P12)))
    assert общие, "у P10 и P12 нет общих документов"
    разные = [f for f in общие if (P10 / f).read_bytes() != (P12 / f).read_bytes()]
    assert not разные, f"одно имя — два текста: {разные}"


# ------------------------------------------- 2–3, 6. ссылки и старые формулировки

def test_ссылки_на_номера_ведут_в_выдаваемые_файлы() -> None:
    for папка in (P10, P12):
        есть = номера(папка)
        for путь in документы(папка):
            for абзац in тексты(путь):
                for m in re.finditer(r"(?:шаблон[а-я]*|файл[а-я]*|чек-лист[а-я]*)\s+«?(\d{1,2})\b"
                                     r"(?:\s*(?:и|,)\s*(\d{2})\b)?", абзац):
                    for n in filter(None, m.groups()):
                        if n in есть:
                            continue
                        assert папка == P10 and n in номера(P12) and ПОМЕТКА in абзац, (
                            f"{папка.name}/{путь.name}: «{m.group(0)}» — такого файла в архиве нет: "
                            f"{абзац[:200]}")


def test_старые_ложные_номера_и_утверждения_не_возвращаются() -> None:
    for папка in (P10, P12):
        for путь in документы(папка) + [папка / "00-START-HERE.txt"]:
            части = тексты(путь) if путь.suffix in (".docx", ".xlsx") else [путь.read_text(encoding="utf-8")]
            for часть in части:
                for фраза in СТАРЫЕ_ЛОЖНЫЕ:
                    assert фраза not in часть, f"{папка.name}/{путь.name}: вернулось «{фраза}»"


def test_общие_документы_не_называют_своими_документы_только_P12() -> None:
    for путь in документы(P10):
        for абзац in тексты(путь):
            for фраза in re.split(r"(?<=[.;])\s+", абзац):
                низ = фраза.lower()
                if not re.search(r"(этого комплекта|входит в комплект|входят в комплект"
                                 r"|документы комплекта|банк[а-я]* вопросов комплекта"
                                 r"|перечню комплекта)", низ):
                    continue
                if not any(p in низ for p in ЧУЖИЕ_ПРИЗНАКИ):
                    continue
                assert ПОМЕТКА in фраза or re.search(r"\bнет\b|не входит|не входят", низ), (
                    f"{путь.name}: документ P12 назван частью P10: {фраза[:200]}")


def test_словарь_описывает_поля_существующих_документов_и_метит_чужие_разделы() -> None:
    словарь = "\n".join(тексты(P12 / "30-slovar-poley-oborona.docx"))
