#!/usr/bin/env python3
"""P10: что входит в комплект — ровно то, что лежит в его архиве.

Аудит #300 (находки P10-01 и P10-05) нашёл два обещания, которых архив P10
не выполнял. Словарь полей был побайтной копией словаря P12 и называл
«входящими в комплект» соглашение о разграничении, акт передачи фронта,
банк вопросов эксперту и опись доказательств — в P10 их нет. Страница
говорила о «трёх документах из девятнадцати», хотя в архиве девять файлов и
документов профилактики нет вовсе.

Дефект один и тот же: P10 выделен из P12, и тексты P12 переехали в него
вместе с утверждениями о составе P12. Поэтому проверка сравнивает каждое
утверждение о составе с папкой выдачи, а не с другим текстом:

- каждый файл, названный входящим в P10 (START-HERE, MANIFEST, страница),
  есть в архиве, и число файлов везде одно;
- документы P10 не называют «файлом этого комплекта» то, чего в нём нет, и
  ссылаются только на существующие номера;
- словарь полей описывает только поля документов P10;
- граница с P12 считается по двум папкам: все документы P10 есть в P12 под
  теми же именами, и счёт «новыми будут N из M» совпадает с разностью.

Запуск без pytest: python3 tools/test_p10_boundary.py
"""
from __future__ import annotations

import html
import re
import sys
import zipfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
P10 = КОРЕНЬ / "products-storage" / "15-otvet-na-pretenziyu-baza"
P12 = КОРЕНЬ / "products-storage" / "12-otvet-na-pretenziyu"
СТРАНИЦА = КОРЕНЬ / "products" / "p10-otvet-na-pretenziyu.html"

# Тот же перечень, что в mvb_build_product_zip (products-config.php):
# покупателю уходит всё, кроме служебных файлов.
СЛУЖЕБНЫЕ = {".htaccess", "00-PISMO-POSLE-POKUPKI.txt", "MANIFEST.md"}

ЧИСЛА = {"восемь": 8, "девять": 9, "одиннадцать": 11, "двенадцать": 12,
         "девятнадцать": 19, "девятнадцати": 19, "двадцать": 20, "двадцати": 20}

# Документы, которые есть в P12 и которых нет в P10: по ним P10 может
# только сослаться как на внешние, а не назвать своими.
ЧУЖИЕ_ПРИЗНАКИ = ("соглашени", "акт передачи фронта", "входного контроля",
                  "регламент", "реестр", "опись доказательств",
                  "вопрос", "чек-лист профилактики", "предупреждени")


def архив(папка: Path) -> list[str]:
    return sorted(p.name for p in папка.iterdir()
                  if p.is_file() and p.name not in СЛУЖЕБНЫЕ)


def рабочие(папка: Path) -> list[str]:
    return [f for f in архив(папка) if f != "00-START-HERE.txt"]


def абзацы(путь: Path) -> list[str]:
    with zipfile.ZipFile(путь) as z:
        xml = z.read("word/document.xml").decode("utf-8")
    out = []
    for блок in re.findall(r"<w:p[ >].*?</w:p>", xml, re.S):
        текст = "".join(re.findall(r"<w:t[^>]*>(.*?)</w:t>", блок, re.S))
        out.append(html.unescape(текст))
    return out


def поля(текст: str) -> set[str]:
    return {re.split(r"[:,—]", m)[0].strip()
            for m in re.findall(r"\{\{(.*?)\}\}", текст)}


def страница() -> str:
    return СТРАНИЦА.read_text(encoding="utf-8")


def видимый_текст(разметка: str) -> str:
    без_кода = re.sub(r"<(script|style)\b.*?</\1>", " ", разметка, flags=re.S)
    без_комментариев = re.sub(r"<!--.*?-->", " ", без_кода, flags=re.S)
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", без_комментариев)))


# --------------------------------------------------------------- архив и счёт

def test_архив_p10_это_START_HERE_и_восемь_документов_word() -> None:
    файлы = архив(P10)
    assert len(файлы) == 9, файлы
    assert "00-START-HERE.txt" in файлы
    assert all(f.endswith(".docx") for f in рабочие(P10)), рабочие(P10)


def test_START_HERE_перечисляет_ровно_архив() -> None:
    текст = (P10 / "00-START-HERE.txt").read_text(encoding="utf-8")
    m = re.search(r"файлов в архиве: (\d+)", текст)
    assert m and int(m.group(1)) == len(архив(P10)), m and m.group(0)
    раздел = текст.split("4. ЧТО В АРХИВЕ", 1)[1].split("5. ", 1)[0]
    названные = sorted(set(re.findall(r"\b\d\d-[A-Za-z0-9-]+\.(?:docx|xlsx|pdf|txt)", раздел)))
    assert названные == архив(P10), (названные, архив(P10))
    # Формат назван по факту: в архиве нет ни Excel, ни PDF.
    assert "Excel" not in текст and "PDF" not in текст, "START-HERE обещает Excel/PDF"


def test_MANIFEST_перечисляет_ровно_архив() -> None:
    текст = (P10 / "MANIFEST.md").read_text(encoding="utf-8")
    раздел = текст.split("## Состав", 1)[1].split("## ", 1)[0]
    названные = sorted(set(re.findall(r"`([^`]+\.(?:docx|xlsx|pdf|txt))`", раздел)))
    assert названные == архив(P10), (названные, архив(P10))


def test_страница_называет_тот_же_состав_и_счёт() -> None:
    разметка = страница()
    текст = видимый_текст(разметка)
    n = len(архив(P10))
    счета = {int(x) for x in re.findall(r"\b(\d+) файл", разметка)}
    assert счета == {n}, f"на странице счёт файлов {счета}, в архиве {n}"
    блок = разметка.split('class="kit-composition"', 1)[1].split("</section>", 1)[0]
    номера = sorted(re.findall(r"<strong>(\d\d)\. ", блок))
    assert номера == [f[:2] for f in рабочие(P10)], (номера, рабочие(P10))
    assert "из девятнадцати" not in текст, "страница считает состав P12"
    assert "Word и Excel" not in текст, "страница обещает Excel, которого в P10 нет"
    assert "расчётные инструменты" not in текст, "в P10 нет расчётных инструментов"
    assert "три документа комплекта подписываются" not in текст.lower(), (
        "страница называет документы профилактики P12 документами P10")
    assert "Разбор ситуации и профилактика" not in текст
    hero = разметка.split('class="product-features"', 1)[1].split("</ul>", 1)[0]
    assert "Профилактика" not in hero, "шапка обещает профилактику"


# ---------------------------------------------------------- документы P10

def test_ссылки_на_шаблоны_ведут_в_файлы_P10() -> None:
    номера = {f[:2] for f in рабочие(P10)}
    for f in рабочие(P10):
        for абзац in абзацы(P10 / f):
            for ссылка in re.findall(r"шаблон[а-я]* «?(\d+)", абзац):
                assert ссылка in номера, f"{f}: «шаблон {ссылка}» — такого файла в P10 нет"


def test_документы_P10_не_называют_своими_документы_P12() -> None:
    for f in рабочие(P10):
        for абзац in абзацы(P10 / f):
            for фраза in re.split(r"(?<=[.;])\s+", абзац):
                низ = фраза.lower()
                if not re.search(r"(этого комплекта|входит в комплект|входят в комплект"
                                 r"|документы комплекта|банк[а-я]* вопросов комплекта"
                                 r"|перечню комплекта)", низ):
                    continue
                if not any(p in низ for p in ЧУЖИЕ_ПРИЗНАКИ):
                    continue
                assert re.search(r"\bнет\b|не входит|не входят", низ), (
                    f"{f}: документ P12 назван частью P10: {фраза[:200]}")


def test_ни_один_файл_P10_не_отсылает_к_файлу_другого_комплекта() -> None:
    # «Алгоритм действий при задержке оплаты» — файл P1/T1, в P10 его нет.
    for f in рабочие(P10):
        for абзац in абзацы(P10 / f):
            assert not re.search(r"файл[а-я]* «Алгоритм действий при задержке оплаты»", абзац), (
                f"{f}: отсылка к файлу, которого в P10 нет: {абзац[:200]}")


def test_словарь_P10_описывает_только_поля_документов_P10() -> None:
    словарь = "\n".join(абзацы(P10 / "30-slovar-poley-oborona.docx"))
    свои: set[str] = set()
    for f in рабочие(P10):
        if not f.startswith("30-"):
            свои |= поля("\n".join(абзацы(P10 / f)))
    лишние = sorted(поля(словарь) - свои - {"ИМЯ_ПОЛЯ"})
    assert not лишние, f"в словаре P10 поля документов, которых в P10 нет: {лишние}"
    assert "входит в комплект" not in словарь
    assert "редакции 1.1" not in словарь, "внутренняя история выпуска в документе покупателя"


# ------------------------------------------------------------ граница с P12

def test_все_документы_P10_есть_в_P12_под_теми_же_именами() -> None:
    assert set(рабочие(P10)) <= set(рабочие(P12)), (
        sorted(set(рабочие(P10)) - set(рабочие(P12))))


def test_счёт_границы_с_P12_совпадает_с_папками() -> None:
    свои = len(рабочие(P10))
    всего = len(рабочие(P12))
    новых = len(set(рабочие(P12)) - set(рабочие(P10)))
    текст = (P10 / "00-START-HERE.txt").read_text(encoding="utf-8")
    текст = re.sub(r"\s+", " ", текст)
    m = re.search(r"новыми будут (\w+) документов из (\w+)", текст)
    assert m, "START-HERE §7 не называет, сколько нового в «Споре с суммой»"
    assert (ЧИСЛА[m.group(1)], ЧИСЛА[m.group(2)]) == (новых, всего), m.group(0)
    assert re.search(rf"все {'восемь' if свои == 8 else свои} ваших документов", текст), (
        "START-HERE не говорит, что все документы P10 входят в P12")
    стр = видимый_текст(страница())
    assert "включает этот комплект целиком" in стр
    assert "Брать оба смысла нет" in стр
    # Страница P12 считает так же: «те же восемь документов и ещё одиннадцать».
    p12 = видимый_текст((КОРЕНЬ / "products" / "p12-spor-s-summoy.html").read_text(encoding="utf-8"))
    assert "те же восемь документов и ещё одиннадцать" in p12
    assert (свои, новых) == (8, 11)


def main() -> int:
    провал = 0
    for имя, проверка in sorted(globals().items()):
        if not имя.startswith("test_"):
            continue
        try:
            проверка()
        except AssertionError as ошибка:
            провал += 1
            print(f"ПРОВАЛ  {имя}\n{ошибка}")
        else:
            print(f"ок  {имя}")
    return 1 if провал else 0


if __name__ == "__main__":
    sys.exit(main())
