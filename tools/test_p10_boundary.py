# ------------------------------------------------------ 4. состав по архиву

def _start_here(папка: Path) -> str:
    return (папка / "00-START-HERE.txt").read_text(encoding="utf-8")


def test_START_HERE_перечисляет_ровно_архив() -> None:
    for папка in (P10, P12):
        текст = _start_here(папка)
        m = re.search(r"файлов в архиве: (\d+)", текст)
        assert m and int(m.group(1)) == len(архив(папка)), (папка.name, m and m.group(0))
        раздел = текст.split("4. ЧТО В АРХИВЕ", 1)[1].split("5. ", 1)[0]
        названные = sorted(set(re.findall(r"\b\d\d-[A-Za-z0-9-]+\.(?:docx|xlsx|pdf|txt)", раздел)))
        assert названные == архив(папка), (папка.name, названные)
    assert "Excel" not in _start_here(P10) and "PDF" not in _start_here(P10)


def test_MANIFEST_перечисляет_ровно_архив() -> None:
    for папка in (P10, P12):
        текст = (папка / "MANIFEST.md").read_text(encoding="utf-8")
        раздел = текст.split("## Состав", 1)[1].split("\n## ", 1)[0]
        названные = sorted(set(re.findall(r"`([^`]+\.(?:docx|xlsx|pdf|txt))`", раздел)))
        assert названные == архив(папка), (папка.name, названные)


def test_страницы_называют_тот_же_состав_и_счёт() -> None:
    for страница, папка in ((СТРАНИЦА_P10, P10), (СТРАНИЦА_P12, P12)):
        разметка = страница.read_text(encoding="utf-8")
        счета = {int(x) for x in re.findall(r"\b(\d+) файл", разметка)}
        assert счета == {len(архив(папка))}, (страница.name, счета)
        блок = разметка.split('class="kit-composition"', 1)[1].split("</section>", 1)[0]
        assert sorted(re.findall(r"<strong>(\d\d)\. ", блок)) == sorted(номера(папка)), страница.name
    текст = видимый_текст(СТРАНИЦА_P10.read_text(encoding="utf-8"))
    for ложное in ("из девятнадцати", "Word и Excel", "расчётные инструменты",
                   "Разбор ситуации и профилактика"):
        assert ложное not in текст, f"страница P10: «{ложное}»"
    assert "три документа комплекта подписываются" not in текст.lower()
    разметка = СТРАНИЦА_P10.read_text(encoding="utf-8")
    hero = разметка.split('class="product-features"', 1)[1].split("</ul>", 1)[0]
    assert "Профилактика" not in hero


# ------------------------------------------------------ 5. граница с P12

def test_все_документы_P10_есть_в_P12() -> None:
    assert set(рабочие(P10)) <= set(рабочие(P12)), sorted(set(рабочие(P10)) - set(рабочие(P12)))


def test_счёт_границы_совпадает_с_папками() -> None:
    свои, всего = len(рабочие(P10)), len(рабочие(P12))
    новых = len(set(рабочие(P12)) - set(рабочие(P10)))
    текст = re.sub(r"\s+", " ", _start_here(P10))
    m = re.search(r"новыми будут (\w+) документов из (\w+)", текст)
    assert m, "START-HERE P10 §7 не называет, сколько нового в «Споре с суммой»"
    assert (ЧИСЛА[m.group(1)], ЧИСЛА[m.group(2)]) == (новых, всего), m.group(0)
    assert "все восемь ваших документов" in текст and свои == 8
    стр10 = видимый_текст(СТРАНИЦА_P10.read_text(encoding="utf-8"))
    assert "включает этот комплект целиком" in стр10 and "Брать оба смысла нет" in стр10
    стр12 = видимый_текст(СТРАНИЦА_P12.read_text(encoding="utf-8"))
    assert "те же восемь документов и ещё одиннадцать" in стр12 and новых == 11


def _разделы_исходника(текст: str) -> dict[str, list[str]]:
    out = {}
    for sku in ("P10", "P12"):
        m = re.search(rf"^## Текст блока {sku}\b.*?(?=^## |\Z)", текст, re.S | re.M)
        assert m, f"в исходнике нет раздела «## Текст блока {sku}»"
        out[sku] = sorted(re.findall(r"^\| (\d\d)\. ", m.group(0), re.M))
    return out


def test_исходник_страниц_в_ai_business_os_называет_тот_же_состав() -> None:
    if not ИСХОДНИК.is_file():
        print(f"  НЕТ ДАННЫХ: {ИСХОДНИК} — сверка с исходником не выполнялась")
        return
    текст = ИСХОДНИК.read_text(encoding="utf-8")
    разделы = _разделы_исходника(текст)
    assert разделы["P10"] == sorted(номера(P10)), разделы["P10"]
    assert разделы["P12"] == sorted(номера(P12)), разделы["P12"]
    p10 = re.search(r"^## Текст блока P10\b.*?(?=^## |\Z)", текст, re.S | re.M).group(0)
    assert "девятнадцат" not in p10 and "профилактика" not in p10.split("####", 1)[1].split("\n", 1)[0].lower()


def main() -> int:
    провал = 0
    for имя, проверка in sorted(globals().items()):
        if not имя.startswith("test_"):
            continue
        try:
            проверка()
        except AssertionError as ошибка:
            провал += 1
            print(f"ПРОВАЛ  {имя}\n{ошибка}")
        else:
            print(f"ок  {имя}")
    return 1 if провал else 0


if __name__ == "__main__":
    sys.exit(main())
