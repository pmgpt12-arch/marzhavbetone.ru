<?php
/**
 * Редиректор воронки: короткая ссылка из Instagram/ManyChat → Telegram-бот.
 *
 * Зачем отдельная страница, а не прямая ссылка t.me в ManyChat: ключ
 * материала должен доехать до бота параметром deep-link (?start=<ключ>),
 * а промежуточный переход через свой домен оставляет точку измерения —
 * переходы видны Метрике и логам сервера, чего прямая ссылка не даёт.
 *
 * Словарь ЗАКРЫТЫЙ, как в lead.php, и по той же причине: значение уходит
 * в параметр start чужого сервиса, и подстановка произвольной строки
 * недопустима. Неизвестный ключ — честный 404, а не редирект «куда-то».
 *
 * Проверка: https://marzhavbetone.ru/get/?k=gu → 302 → t.me/…?start=gu
 */
declare(strict_types=1);

const MVB_BOT = 'marzhafunnel_bot';

/** Ключ → название материала. Названия здесь для читателя кода и 404-страницы:
 *  файл отдаёт бот, соответствие ключ → PDF живёт на его стороне. */
const MVB_KEYWORDS = [
    'zakrytie' => 'Чек-лист закрытия работ',
    'dengi'    => '7 проверок при неоплате',
    'dop'      => 'Фиксация допработ',
    'ks'       => 'Проверочный лист КС',
    'gu'       => 'Гарантийное удержание',
    'dogovor'  => 'Красные флаги договора',
    'bank'     => 'Проверка контрагента',
    'avans'    => 'Проверка условий аванса',
    'kvartira' => 'Работы за квартиры',
    'id'       => 'Проверка ИД',
    'akt'      => 'Акты скрытых работ',
];

$key = (string)($_GET['k'] ?? '');

if (!array_key_exists($key, MVB_KEYWORDS)) {
    http_response_code(404);
    header('Content-Type: text/html; charset=utf-8');
    echo '<!doctype html><meta charset="utf-8"><title>Материал не найден</title>'
        . '<body style="font-family:sans-serif;max-width:560px;margin:80px auto;padding:0 16px">'
        . '<h1 style="font-size:22px">Материал не найден</h1>'
        . '<p>Проверьте ссылку или посмотрите все бесплатные материалы на сайте.</p>'
        . '<p><a href="/materialy/">Бесплатные материалы</a> · <a href="/">Главная</a></p>';
    exit;
}

/* Ключ прошёл закрытый словарь — в URL уходит ровно он, без пользовательского
 * ввода. 302, а не 301: соответствие ключей боту может меняться, и кэшировать
 * редирект навсегда в браузерах подписчиков нельзя. */
header('Location: https://t.me/' . MVB_BOT . '?start=' . $key, true, 302);
exit;
