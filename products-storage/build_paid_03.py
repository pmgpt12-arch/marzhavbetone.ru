def base_document() -> Document:
    doc = Document()
    for section in doc.sections:
        section.page_width, section.page_height = Cm(21), Cm(29.7)
        section.left_margin = Cm(2.5)
        section.right_margin = Cm(1.5)
        section.top_margin = section.bottom_margin = Cm(2)
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(11)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.paragraph_format.space_after = Pt(3)
    props = doc.core_properties
    props.author = ""
    props.last_modified_by = ""
    props.comments = ""
    props.keywords = ""
    props.revision = 1
    props.created = props.modified = FIXED_TIME
    props.last_printed = FIXED_TIME
    return doc


def add_runs(paragraph, text: str, *, bold=False, italic=False, size=None,
             color=None) -> None:
    """Текст с полями {{…}}: поле выделено цветом, как обещает страница."""
    for part in FIELD.split(text):
        if not part:
            continue
        run = paragraph.add_run(part)
        run.bold = bold
        run.italic = italic
        if size:
            run.font.size = Pt(size)
        if color is not None:
            run.font.color.rgb = color
        if FIELD.fullmatch(part):
            run.font.highlight_color = WD_COLOR_INDEX.YELLOW


def para(container, text: str, *, bold=False, italic=False, size=None,
         align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, color=None,
         before=0, after=3):
    p = container.add_paragraph()
    p.alignment = align
    fmt = p.paragraph_format
    fmt.space_before, fmt.space_after = Pt(before), Pt(after)
    if indent and not text.startswith("- "):
        fmt.first_line_indent = Cm(1)
    elif text.startswith("- "):
        fmt.left_indent = Cm(0.5)
    add_runs(p, text, bold=bold, italic=italic, size=size, color=color)
    return p


def page_number_footer(doc: Document) -> None:
    footer = doc.sections[0].footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = footer.add_run()
    for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            element = OxmlElement("w:fldChar")
            element.set(qn("w:fldCharType"), kind)
        else:
            element = OxmlElement("w:instrText")
            element.set(qn("xml:space"), "preserve")
            element.text = text
        run._r.append(element)
    run.font.size = Pt(9)


def cell_paragraphs(cell, lines: list[str], *, bold=False, size=10,
                    align=WD_ALIGN_PARAGRAPH.LEFT) -> None:
    first = True
    for line in lines:
        p = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        p.alignment = align
        p.paragraph_format.space_after = Pt(2)
        add_runs(p, line, bold=bold, size=size)


def grid(doc: Document, rows: int, cols: int):
    table = doc.add_table(rows=rows, cols=cols)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    return table


