def normalize_docx(path: Path) -> None:
    """Одинаковые байты на каждом прогоне: время записей архива фиксируется."""
    with zipfile.ZipFile(path) as source:
        entries = [(info.filename, source.read(info.filename))
                   for info in source.infolist()]
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as target:
        for name, data in entries:
            info = zipfile.ZipInfo(name, date_time=FIXED_TIME.timetuple()[:6])
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            target.writestr(info, data)


def save(doc: Document, path: Path) -> None:
    doc.save(path)
    normalize_docx(path)


