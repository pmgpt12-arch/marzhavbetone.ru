# ---------------------------------------------------------------- документ

def new_doc(title, intro=None):
    doc = Document()
    doc.add_heading(title, level=1)
    if intro:
        doc.add_paragraph(intro)
    doc.add_paragraph()
    block(doc, DISCLAIMER)
    doc.add_paragraph()
    return doc


def block(doc, lines):
    """Врезка-оговорка: таблица в одну ячейку, первая строка — заголовок."""
    table = doc.add_table(rows=1, cols=1)
    table.style = "Table Grid"
    cell = table.cell(0, 0)
    first = cell.paragraphs[0]
    first.add_run(lines[0]).bold = True
    for line in lines[1:]:
        cell.add_paragraph(line)


def h2(doc, text):
    doc.add_heading(text, level=2)


def p(doc, text=""):
    doc.add_paragraph(text)


def strong_p(doc, lead, tail):
    para = doc.add_paragraph()
    para.add_run(lead).bold = True
    para.add_run(tail)


def checks(doc, items):
    for item in items:
        doc.add_paragraph(f"☐  {item}")


def bullets(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def numbered(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Number")


def table(doc, headers, rows):
    grid = doc.add_table(rows=1, cols=len(headers))
    grid.style = "Table Grid"
    for i, head in enumerate(headers):
        cell = grid.rows[0].cells[i]
        cell.paragraphs[0].add_run(head).bold = True
    for row in rows:
        cells = grid.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
    doc.add_paragraph()


def page_break(doc):
    para = doc.add_paragraph()
    para.add_run().add_break(WD_BREAK.PAGE)


def howto(doc, lines):
    """Служебная страница «Как пользоваться»: в отправляемый документ не идёт."""
    page_break(doc)
    doc.add_heading("Как пользоваться этим документом", level=1)
    p(doc, "Примечание покупателю. Эта страница в отправляемый документ не "
           "входит. Не входят в него и заголовок файла с врезкой-оговоркой "
           "в начале: они адресованы вам, а не второй стороне. Отправляется "
           "текст между врезкой и разрывом страницы.")
    for line in lines:
        p(doc, line)


def save(doc, name):
    path = os.path.join(FOLDER, name)
    doc.save(path)
    print(f"  [Word]  {path}")


# ------------------------------------------------------------------ Excel

def sheet_header(ws, headers, widths):
    ws.append(headers)
    for idx, _ in enumerate(headers, 1):
        cell = ws.cell(row=1, column=idx)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center",
                                   wrap_text=True)
        cell.border = thin_border
    for idx, width in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(idx)].width = width
    ws.freeze_panes = "A2"


