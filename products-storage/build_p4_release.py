#!/usr/bin/env python3
"""Состав P4 «Акты скрытых работ и исполнительная документация» — выпуск 28.09.2026.

Две правки состава, обе по дефектам аудита (#300 P4-01, P4-03; Issue #308).

**Письмо-предупреждение по ст. 716 ГК РФ добавлено файлом 43.** Акт
входного контроля `42` (побайтная копия P12 `38`) пишет покупателю:
«Шаблон письма-предупреждения входит в комплект», и что акт без письма
последствий не создаёт. Письма в P4 не было. Текст не пишется заново: 43
выводится из P12 `35-preduprezhdenie-po-st-716.docx` — того самого письма,
которое прошло вычитку юристом («ред. 3», принята владельцем 01.08.2026) и
нормативную сверку (`Normative_Check_Oborona_2026-08-01.md`: ст. 716 —
«подтверждена» для файлов 35 и 38). Так же 03.08.2026 в P4 пришли 41 и 42.

Правка ровно одна и объявлена в `ПРАВКИ`: в примечании письмо отсылает к
«ответу на претензию (отдельный документ комплекта)» — это документ P12,
в P4 его нет. Текст самого предупреждения, рамка и остальное не меняются:
каждая запись архива, кроме `word/document.xml`, переносится побайтно, с
теми же метаданными, поэтому выпуск воспроизводим.

**Сравнительная таблица `10` из выдачи снята.** Цена внутри купленного
файла, «окупаемость», сравнение со снятым «Полным комплектом» и свойства,
которых в комплекте нет. Так же снята таблица P5
(`test_p5_не_отдаёт_снятую_сравнительную_таблицу`). Генератор
`build_paid_06.py` пишет её в неадресуемую папку `06-id-blokiruet-oplatu`
и не тронут: исторические архивы не правятся.

    python3 products-storage/build_p4_release.py          # сверка, код 1 при расхождении
    python3 products-storage/build_p4_release.py --write  # записать 43, убрать 10
"""
from __future__ import annotations

import sys
import zipfile
from io import BytesIO
from pathlib import Path

STORAGE = Path(__file__).resolve().parent
ИСТОЧНИК = STORAGE / "12-otvet-na-pretenziyu" / "35-preduprezhdenie-po-st-716.docx"
P4 = STORAGE / "08-pto-bez-zamechaniy"
ПИСЬМО = P4 / "43-preduprezhdenie-po-st-716.docx"
СНЯТЫЕ = ("10-sravnitelnaya-tablica.docx",)

ДОКУМЕНТ = "word/document.xml"
# (было, стало): каждое «было» обязано встретиться в источнике ровно один раз
ПРАВКИ = (
    ("в ответе на претензию (отдельный документ комплекта) ссылаются",
     "в ответе на претензию ссылаются"),
)


def письмо_p4(источник: Path = ИСТОЧНИК) -> bytes:
    """Файл 43 из письма P12: те же записи в том же порядке, правка — только
    в тексте документа."""
    выход = BytesIO()
    with zipfile.ZipFile(источник) as src, \
            zipfile.ZipFile(выход, "w") as dst:
        for запись in src.infolist():
            данные = src.read(запись.filename)
            if запись.filename == ДОКУМЕНТ:
                текст = данные.decode("utf-8")
                for было, стало in ПРАВКИ:
                    найдено = текст.count(было)
                    if найдено != 1:
                        raise SystemExit(
                            f"{источник.name}: «{было}» встречается {найдено} раз, "
                            "ожидался один — источник изменился, правку пересмотреть")
                    текст = текст.replace(было, стало)
                данные = текст.encode("utf-8")
            dst.writestr(запись, данные)
    return выход.getvalue()


def содержимое(архив: bytes | Path) -> list[tuple[str, tuple, bytes]]:
    """Записи .docx для сравнения: имя, дата, распакованные байты. Сжатые
    байты не сравниваются — они зависят от сборки zlib, а не от выпуска."""
    with zipfile.ZipFile(BytesIO(архив) if isinstance(архив, bytes) else архив) as z:
        return [(i.filename, i.date_time, z.read(i.filename)) for i in z.infolist()]


def расхождения() -> list[str]:
    найдено = []
    if not ПИСЬМО.is_file():
        найдено.append(f"нет {ПИСЬМО.name}")
    elif содержимое(ПИСЬМО) != содержимое(письмо_p4()):
        найдено.append(f"{ПИСЬМО.name} не совпадает с выводом из {ИСТОЧНИК.name}")
    for имя in СНЯТЫЕ:
        if (P4 / имя).exists():
            найдено.append(f"снятый {имя} лежит в выдаче")
    return найдено


def main(argv: list[str]) -> int:
    if "--write" in argv:
        ПИСЬМО.write_bytes(письмо_p4())
        for имя in СНЯТЫЕ:
            (P4 / имя).unlink(missing_ok=True)
    найдено = расхождения()
    for строка in найдено:
        print(f"РАСХОЖДЕНИЕ  {строка}")
    if not найдено:
        print(f"ок  {P4.name}: 43 выведен из P12 35, снятые файлы в выдаче отсутствуют")
    return 1 if найдено else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
