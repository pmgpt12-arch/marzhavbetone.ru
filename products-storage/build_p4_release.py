# Правки письма 43 — для обратной совместимости с выпуском 28.09.2026
ПРАВКИ = tuple((было, стало) for _, было, стало in ВЫПУСК[ПИСЬМО.name][1])


def вывести(имя: str) -> bytes:
    """Файл выдачи из источника: те же записи в том же порядке и с теми же
    метаданными, правки — только объявленные в `ВЫПУСК`."""
    источник, правки = ВЫПУСК[имя]
    выход = BytesIO()
    with zipfile.ZipFile(источник) as src, \
            zipfile.ZipFile(выход, "w") as dst:
        for запись in src.infolist():
            данные = src.read(запись.filename)
            свои = [(было, стало) for часть, было, стало in правки if часть == запись.filename]
            if свои:
                текст = данные.decode("utf-8")
                for было, стало in свои:
                    найдено = текст.count(было)
                    if найдено != 1:
                        raise SystemExit(
                            f"{источник.name}/{запись.filename}: «{было}» встречается "
                            f"{найдено} раз, ожидался один — источник изменился, "
                            "правку пересмотреть")
                    текст = текст.replace(было, стало)
                данные = текст.encode("utf-8")
            dst.writestr(запись, данные)
    return выход.getvalue()


def письмо_p4(источник: Path = ИСТОЧНИК) -> bytes:
    """Файл 43 из письма P12."""
    assert источник == ИСТОЧНИК, "источник письма 43 задан в ВЫПУСК"
    return вывести(ПИСЬМО.name)


def содержимое(архив: bytes | Path) -> list[tuple[str, tuple, bytes]]:
    """Записи .docx для сравнения: имя, дата, распакованные байты. Сжатые
    байты не сравниваются — они зависят от сборки zlib, а не от выпуска."""
    with zipfile.ZipFile(BytesIO(архив) if isinstance(архив, bytes) else архив) as z:
        return [(i.filename, i.date_time, z.read(i.filename)) for i in z.infolist()]


def расхождения() -> list[str]:
    найдено = []
    for имя, (источник, _) in ВЫПУСК.items():
        if not (P4 / имя).is_file():
            найдено.append(f"нет {имя}")
        elif содержимое(P4 / имя) != содержимое(вывести(имя)):
            найдено.append(f"{имя} не совпадает с выводом из {источник.name}")
    for имя in СНЯТЫЕ:
        if (P4 / имя).exists():
            найдено.append(f"снятый {имя} лежит в выдаче")
    return найдено


def main(argv: list[str]) -> int:
    if "--write" in argv:
        for имя in ВЫПУСК:
            (P4 / имя).write_bytes(вывести(имя))
        for имя in СНЯТЫЕ:
            (P4 / имя).unlink(missing_ok=True)
    найдено = расхождения()
    for строка in найдено:
        print(f"РАСХОЖДЕНИЕ  {строка}")
    if not найдено:
        print(f"ок  {P4.name}: {len(ВЫПУСК)} файлов выведены из источников "
              "объявленными правками, снятые файлы в выдаче отсутствуют")
    return 1 if найдено else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
