# Воспроизводимая сборка. python-docx и openpyxl пишут в zip текущее время
# (метка каждого файла внутри архива, а openpyxl — ещё и dcterms:modified),
# reportlab — дату создания и случайный идентификатор PDF. Два прогона одного
# генератора давали разные байты при одинаковом тексте, и по хэшу нельзя было
# сказать, изменился ли документ. Время фиксируется датой редакции комплекта.
РЕДАКЦИЯ = (2026, 9, 28, 0, 0, 0)
_W3CDTF = "%04d-%02d-%02dT%02d:%02d:%02dZ" % РЕДАКЦИЯ


def _freeze_ooxml(path):
    """Переписывает .docx/.xlsx с фиксированным временем внутри архива."""
    with zipfile.ZipFile(path) as src:
        items = [(info, src.read(info.filename)) for info in src.infolist()]
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as dst:
        for info, data in items:
            if info.filename == "docProps/core.xml":
                text = data.decode("utf-8")
                text = re.sub(r"(<dcterms:(?:created|modified)[^>]*>)[^<]*(<)",
                              r"\g<1>" + _W3CDTF + r"\g<2>", text)
                data = text.encode("utf-8")
            fixed = zipfile.ZipInfo(info.filename, date_time=РЕДАКЦИЯ)
            fixed.compress_type = zipfile.ZIP_DEFLATED
            fixed.external_attr = 0o644 << 16
            dst.writestr(fixed, data)


def create_excel(filepath, sheet_name="Лист1", headers=None, rows=None, col_widths=None):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet_name
    
    if headers:
        ws.append(headers)
        for col_idx, h in enumerate(headers, 1):
            cell = ws.cell(row=1, column=col_idx)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = thin_border
    
    if rows:
        for r in rows:
            ws.append(r)
            row_num = ws.max_row
            for col_idx in range(1, len(r) + 1):
                cell = ws.cell(row=row_num, column=col_idx)
                cell.border = thin_border
                cell.alignment = Alignment(vertical="top", wrap_text=True)
    
    if col_widths:
        for idx, w in enumerate(col_widths, 1):
            ws.column_dimensions[get_column_letter(idx)].width = w
    
    wb.save(filepath)
    _freeze_ooxml(filepath)
    print(f"  [Excel] {filepath}")


def create_word_doc(filepath, title, sections):
    doc = Document()
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph()
    
    for section in sections:
        if "heading" in section:
            doc.add_heading(section["heading"], level=1)
        
        if "text" in section:
            doc.add_paragraph(section["text"])
        
        if "bullet" in section:
            for item in section["bullet"]:
                doc.add_paragraph(item, style='List Bullet')
        
        if "table" in section:
            table_data = section["table"]
            if table_data:
                table = doc.add_table(rows=len(table_data), cols=len(table_data[0]))
                table.style = 'Table Grid'
                for i, row_data in enumerate(table_data):
                    for j, cell_text in enumerate(row_data):
                        table.cell(i, j).text = str(cell_text)
                doc.add_paragraph()
        
        if "numbered" in section:
            for item in section["numbered"]:
                doc.add_paragraph(item, style='List Number')
    
    doc.save(filepath)
    _freeze_ooxml(filepath)
    print(f"  [Word]  {filepath}")


# Кириллица в PDF: стандартные шрифты reportlab (Helvetica и прочие из
# «стандартных четырнадцати») кодируются WinAnsi и кириллических глифов не
# содержат — c.drawString() отрабатывает молча и не рисует ничего. Так и
# получились файлы 08-*.pdf: 2 290 и 2 305 байт при 85–91 КБ у соседних,
# нулевой видимый текст, ни одной ошибки при сборке. Регистрируем шрифт со
# славянским набором.
#
# Liberation Sans выбран по метрической совместимости с Arial: уже собранные
# PDF комплектов несут подмножества ArialMT и Arial-BoldMT, и замена на
# метрический клон сохраняет вид страницы. Самого Arial в окружении сборки
# нет.
_ШРИФТЫ = (
    ("MVBSans", "MVBSans-Bold",
     "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
     "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"),
    ("MVBSans", "MVBSans-Bold",
     "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
     "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
)


def _register_cyrillic_font():
    """Имена шрифтов для основного текста и заголовка.

    Возвращает стандартные Helvetica только если ни один файл шрифта не
    нашёлся. Это не тихий откат: вызывающий обязан проверить, что в
    собранном PDF есть текст, — проверка в отчёте о правке.
    """
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    for обычный, жирный, файл_о, файл_ж in _ШРИФТЫ:
        if not (os.path.exists(файл_о) and os.path.exists(файл_ж)):
            continue
        if обычный not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont(обычный, файл_о))
            pdfmetrics.registerFont(TTFont(жирный, файл_ж))
        return обычный, жирный
    return "Helvetica", "Helvetica-Bold"


def create_pdf_simple(filepath, title, lines):
    обычный, жирный = _register_cyrillic_font()
    c = canvas.Canvas(filepath, pagesize=A4, invariant=1)
    width, height = A4
    
    c.setFont(жирный, 16)
    c.drawCentredString(width/2, height - 2*cm, title)
    
    c.setFont(обычный, 11)
    y = height - 3.5*cm
    for line in lines:
        if y < 2*cm:
            c.showPage()
            y = height - 2*cm
            c.setFont(обычный, 11)
        c.drawString(2*cm, y, line)
        y -= 0.6*cm
    
    c.save()
    print(f"  [PDF]   {filepath}")


