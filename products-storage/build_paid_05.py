def _fonts(doc):
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(11)
    rpr = style.element.get_or_add_rPr()
    fonts = rpr.get_or_add_rFonts()
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(attr), "Times New Roman")
    style.paragraph_format.space_after = Pt(3)
    section = doc.sections[0]
    section.orientation = WD_ORIENT.PORTRAIT
    section.page_width, section.page_height = Cm(21), Cm(29.7)
    section.left_margin = Cm(2)
    section.right_margin = Cm(1.5)
    section.top_margin = section.bottom_margin = Cm(1.5)


def _para(doc, text, bold=False, italic=False, size=None, center=False,
          before=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold, run.italic = bold, italic
    if size:
        run.font.size = Pt(size)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if before is not None:
        p.paragraph_format.space_before = Pt(before)
    return p


def _grid(doc, rows, widths, header=True, blank_height=0.75):
    """Таблица формы: шапка жирным, пустые ячейки — поля для заполнения."""
    table = doc.add_table(rows=len(rows), cols=len(widths))
    table.style = "Table Grid"
    table.autofit = False
    # Ширина ячейки (tcW) Word читает, а Writer берёт ширины из сетки
    # таблицы (tblGrid): без неё колонки в LibreOffice встают равными и
    # таблица не доходит до правого поля. Задаются обе.
    for column, width in zip(table._tbl.tblGrid.gridCol_lst, widths):
        column.w = Cm(width)
    for i, values in enumerate(rows):
        row = table.rows[i]
        if i > 0 or not header:
            row.height = Cm(blank_height)
            row.height_rule = WD_ROW_HEIGHT_RULE.AT_LEAST
        else:
            # Шапка повторяется на новой странице: без этого таблица подписей
            # рвётся так, что шапка остаётся внизу листа, а строки уходят на
            # следующий (замечено в Writer на форме 5).
            header_flag = OxmlElement("w:tblHeader")
            header_flag.set(qn("w:val"), "true")
            row._tr.get_or_add_trPr().append(header_flag)
        for j, value in enumerate(values):
            cell = row.cells[j]
            cell.width = Cm(widths[j])
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            if isinstance(value, tuple):
                label, hint = value
                p.add_run(label).bold = header and i == 0
                note = p.add_run("\n" + hint)
                note.italic = True
                note.font.size = Pt(9)
            else:
                run = p.add_run(value)
                run.bold = header and i == 0
                if header and i == 0:
                    run.font.size = Pt(10)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return table


