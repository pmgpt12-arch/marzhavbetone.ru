GRAPHITE = RGBColor(38, 47, 55)
GOLD = RGBColor(142, 111, 50)


def start(title: str, intro: str) -> Document:
    doc = Document()
    section = doc.sections[0]
    section.page_width, section.page_height = Cm(21), Cm(29.7)
    section.top_margin = section.bottom_margin = Cm(1.7)
    section.left_margin = section.right_margin = Cm(1.8)
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(10.5)
    normal.font.color.rgb = GRAPHITE
    normal.paragraph_format.space_after = Pt(5)
    h1 = doc.styles["Heading 1"]
    h1.font.name = "Times New Roman"
    h1.font.color.rgb = GOLD
    h1.font.size = Pt(12)
    h1.font.bold = True
    h1.paragraph_format.space_before = Pt(9)
    h1.paragraph_format.space_after = Pt(5)
    style = doc.styles["Title"]
    style.font.name = "Times New Roman"
    style.font.color.rgb = RGBColor(0, 0, 0)
    style.font.size = Pt(17)
    style.font.bold = True
    style.paragraph_format.space_after = Pt(9)
    border = style.element.get_or_add_pPr().find(qn("w:pBdr"))
    if border is not None:
        style.element.get_or_add_pPr().remove(border)
    p = doc.add_paragraph(style="Title")
    p.add_run(title)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    body(doc, intro)
    return doc


def rows(doc: Document, headers: list[str], values: list[list[str]]) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.autofit = False
    for c, h in zip(table.rows[0].cells, headers):
        fill(c, h, bold=True)
        shade(c)
    no_split(table.rows[0])
    for record in values:
        cells = table.add_row().cells
        no_split(table.rows[-1])
        for c, v in zip(cells, record):
            fill(c, v)


def parties(doc: Document, *, kind: str) -> None:
    heading(doc, "Реквизиты")
    two_column(doc, [
        ("Документ", f"{kind} № [___] от [___]; место [___]"),
        ("Договор", "Договор подряда № [___] от [___]; исходное приложение / смета [___]"),
        ("Объект", "Наименование, адрес, участок или захватка [___]"),
        ("Подрядчик", "Полное наименование, ИНН, адрес [___]"),
        ("Заказчик", "Полное наименование, ИНН, адрес [___]"),
    ])


def finish(doc: Document, *, delivery: bool = True, unilateral: bool = False) -> None:
    if delivery:
        heading(doc, "Направление и подписи")
        two_column(doc, [
            ("Передача", "Канал [___], адресат [___], дата [___], подтверждение доставки [___]"),
            ("Ответ", "Дата [___], входящий № / письмо [___], приложен к делу объекта [___]"),
        ])
    else:
        heading(doc, "Подписи сторон")
    if unilateral:
        two_column(doc, [
            ("Подрядчик", "Должность, Ф. И. О., основание полномочий [___]"),
            ("Подпись", "[___]  Дата подписания [___]"),
            ("Получение", "Отметка заказчика / входящий № [___] или отдельное подтверждение доставки [___]"),
        ])
    else:
        signature_table(doc)


