def create_excel(filepath, sheets):
    """Книга из нескольких листов. Каждый лист — словарь с ключами
    name, headers, rows, widths и необязательным note."""
    wb = openpyxl.Workbook()
    wb.remove(wb.active)

    for sheet in sheets:
        ws = wb.create_sheet(sheet["name"])
        if sheet.get("note"):
            ws.append([sheet["note"]])
            ws.cell(row=1, column=1).font = Font(italic=True, size=10)
            ws.cell(row=1, column=1).alignment = Alignment(wrap_text=True, vertical="top")
            ws.append([])

        header_row = ws.max_row + 1
        ws.append(sheet["headers"])
        for col_idx in range(1, len(sheet["headers"]) + 1):
            cell = ws.cell(row=header_row, column=col_idx)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = thin_border

        first_data_row = ws.max_row + 1
        for row in sheet.get("rows", []):
            ws.append(row)
            row_num = ws.max_row
            for col_idx in range(1, len(sheet["headers"]) + 1):
                cell = ws.cell(row=row_num, column=col_idx)
                cell.border = thin_border
                cell.alignment = Alignment(vertical="top", wrap_text=True)

        # Диапазон итога считается по факту, а не пишется руками: строка
        # заголовка съезжает от одной пояснительной строки сверху, и
        # захардкоженный =SUM(D3:D10) молча складывает заголовок с чужими
        # ячейками. Ошибку такого рода видно только в открытом файле у
        # покупателя — ровно как кириллическое =СУММ, которое отдавало ему
        # #ИМЯ? в двух прошлых материалах.
        total = sheet.get("total")
        if total:
            last_data_row = ws.max_row
            column = get_column_letter(total["column"])
            row = [""] * len(sheet["headers"])
            row[0] = total["label"]
            row[total["column"] - 1] = (
                f"=SUM({column}{first_data_row}:{column}{last_data_row})")
            ws.append(row)
            for col_idx in range(1, len(sheet["headers"]) + 1):
                cell = ws.cell(row=ws.max_row, column=col_idx)
                cell.border = thin_border
                cell.font = Font(bold=True)
                cell.alignment = Alignment(vertical="top", wrap_text=True)

        for idx, width in enumerate(sheet.get("widths", []), 1):
            ws.column_dimensions[get_column_letter(idx)].width = width

    wb.save(filepath)
    print(f"  [Excel] {filepath}")


def create_word_doc(filepath, title, sections):
    doc = Document()
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph()

    for section in sections:
        if "heading" in section:
            doc.add_heading(section["heading"], level=1)
        if "text" in section:
            doc.add_paragraph(section["text"])
        if "bullet" in section:
            for item in section["bullet"]:
                doc.add_paragraph(item, style='List Bullet')
        if "numbered" in section:
            for item in section["numbered"]:
                doc.add_paragraph(item, style='List Number')
        if "table" in section:
            data = section["table"]
            if data:
                table = doc.add_table(rows=len(data), cols=len(data[0]))
                table.style = 'Table Grid'
                for i, row in enumerate(data):
                    for j, text in enumerate(row):
                        table.cell(i, j).text = str(text)
                doc.add_paragraph()

    doc.save(filepath)
    print(f"  [Word]  {filepath}")


