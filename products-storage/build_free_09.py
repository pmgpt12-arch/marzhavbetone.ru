"""Бесплатный материал 09: «Исполнительная документация: проверка комплекта
до передачи».

Закрывает последнюю дыру воронки — кластер исполнительной документации.
Пять статей кластера (`ispolnitelnaya-dokumentaciya-sostav`,
`akt-skrytyh-rabot-obrazec`, `akt-osvidetelstvovaniya-skrytyh-rabot`,
`akt-peredachi-stroitelnoy-ploshchadki-obrazec`,
`pyat-dokazatelstv-vypolneniya`) ведут в платный комплект P4, а бесплатный
выход из них указывал на чужой узел — на материал по возврату КС и на
материал по невыплате. Узел магнита и узел товара теперь совпадают.

Граница с платным комплектом P4 проведена по действию, как у остальных
бесплатных. Бесплатный материал даёт **увидеть и сверить**: из чего состоит
комплект, какими связями он держится, какая позиция КС-2 не подтверждена ни
одним документом, из-за чего комплекты возвращают и о чём спросить вторую
сторону до первой передачи. Платный комплект даёт **делать и отвечать**:
формы актов и схем, журналы, реестры, уведомление о готовности, акт приёмки
ИД, письмо-ответ на замечания по пунктам, график устранения и служебную
записку о блокировке оплаты.

Отсюда правило состава: здесь нет ни одной формы документа. Названо, что
должно быть в комплекте и чем это проверяется, — а сам бланк лежит в
платном. Это та же граница, что у бесплатного материала по авансу, где нет
ни одной формулировки-замены, и держится она в файлах явно.

Правила материала:
  * ни одной числовой константы законодательства — ни сроков, ни процентов,
    ни размеров. Норма называется актом и статьёй, а не значением; состав
    комплекта задаётся договором, проектом и действующей редакцией
    требований, и об этом сказано прямо;
  * ни одного перечня форм с номерами: наименования форм меняются, и
    выписанный сюда номер устарел бы молча;
  * никаких обещаний результата: материал не обещает, что комплект примут с
    первого раза и что оплата придёт в срок;
  * никаких утверждений о конкретных организациях;
  * даты и суммы вводит пользователь, единственная формула — итог `=SUM`
    латиницей: кириллическое `=СУММ` Excel сохраняет буквально и показывает
    покупателю `#ИМЯ?`;
  * оговорка о границе с юристом — в каждом файле.
"""

