/** Ищет продукт по sku, затем по точному названию (для старых корзин). */
function mvb_resolve_product(array $item): ?array
{
    $catalog = mvb_products();
    $sku = (string)($item['sku'] ?? '');
    if ($sku !== '' && isset($catalog[$sku])) {
        return ['sku' => $sku] + $catalog[$sku];
    }
    $name = (string)($item['name'] ?? '');
    foreach ($catalog as $key => $product) {
        if ($product['name'] === $name) {
            return ['sku' => $key] + $product;
        }
    }
    return null;
}

/**
 * Собирает (и кэширует) архив продукта в DELIVERY_DIR.
 * Возвращает абсолютный путь к zip либо null при ошибке.
 */
function mvb_build_product_zip(string $sku): ?string
{
    $catalog = mvb_products();
    if (!isset($catalog[$sku])) {
        return null;
    }
    $sourceDir = PRODUCTS_DIR . '/' . $catalog[$sku]['dir'];
    $zipPath = DELIVERY_DIR . '/' . $catalog[$sku]['zip'];

    if (is_file($zipPath) && filesize($zipPath) > 0) {
        return $zipPath;
    }
    if (!is_dir($sourceDir)) {
        @file_put_contents(ORDERS_DIR . '/delivery-errors.log',
            date('c') . " нет папки продукта: {$sourceDir}\n", FILE_APPEND);
        return null;
    }

    $zip = new ZipArchive();
    if ($zip->open($zipPath, ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
        return null;
    }
    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($sourceDir, FilesystemIterator::SKIP_DOTS)
    );
    foreach ($iterator as $file) {
        if (!$file->isFile()) {
            continue;
        }
        $local = substr($file->getPathname(), strlen($sourceDir) + 1);
        // Служебные файлы не отдаём покупателю. MANIFEST.md — внутренний
        // документ: состав «как задумано», ценовые гипотезы, связь с
        // бесплатными материалами. Покупатель пакета за 1 990 ₽ читал в нём
        // «ценовая гипотеза 12 900–16 900 ₽».
        // Список именно перечислением, а не маской: маска однажды съест файл,
        // за который заплатили. Число файлов на страницах товаров считается
        // по этому же списку исключений.
        $service = ['.htaccess', '00-PISMO-POSLE-POKUPKI.txt', 'MANIFEST.md'];
        if (in_array(basename($local), $service, true)) {
            continue;
        }
        $zip->addFile($file->getPathname(), $local);
    }
    $zip->close();
    return is_file($zipPath) ? $zipPath : null;
}

/**
 * Готовит выдачу для оплаченного заказа: собирает архивы, генерирует токен,
 * дописывает блок delivery в массив заказа. Возвращает список ссылок.
 */
function mvb_prepare_delivery(array &$order): array
{
    if (empty($order['delivery']['token'])) {
        $order['delivery'] = [
            'token'      => bin2hex(random_bytes(16)),
            'created_at' => date('c'),
            'expires_at' => date('c', time() + DELIVERY_TTL_DAYS * 86400),
            'downloads'  => 0,
            'items'      => [],
        ];
    }

    $links = [];
    foreach ($order['items'] ?? [] as $item) {
        $product = mvb_resolve_product($item);
        if (!$product) {
            continue;
        }
        $zipPath = mvb_build_product_zip($product['sku']);
        if (!$zipPath) {
            continue;
        }
        $order['delivery']['items'][$product['sku']] = basename($zipPath);
        $links[] = [
            'sku'  => $product['sku'],
            'name' => $product['name'],
            'url'  => SITE_URL . '/download.php?o=' . rawurlencode($order['id'])
                . '&t=' . $order['delivery']['token']
                . '&f=' . $product['sku'],
        ];
    }
    return $links;
}

/**
 * Читает заказ, отдаёт его обработчику и записывает обратно — под
 * исключительной блокировкой.
 *
 * Заведено 15.08.2026 по разбору гонки. Выдачу зовут два независимых
 * процесса: webhook.php по уведомлению ЮKassa и check-payment.php по
 * заходу покупателя на success.html. Это не редкий случай, а обычный:
 * покупатель возвращается на сайт ровно в тот момент, когда касса шлёт
 * уведомление.
 *
 * Защита от повторной выдачи стояла на поле delivery.email_sent_at, и
 * против последовательных вызовов она работает. Против одновременных —
 * нет: оба процесса читают файл заказа до того, как любой из них успел
 * записать, оба видят пустое email_sent_at, оба шлют письмо. Второй
 * дефект той же природы — потерянное обновление: запись, сделанная
 * позже, затирает поля, проставленные первым процессом.
 *
 * Блокировка берётся на отдельном .lock-файле, а не на самом заказе:
 * запись идёт через временный файл и rename, то есть исходный inode
 * заменяется, и блокировка на нём была бы снята с чужого файла.
 */
function mvb_with_order_lock(string $orderFile, callable $fn)
{
    $lock = @fopen($orderFile . '.lock', 'c');
    if ($lock === false) {
        // Взять блокировку не удалось. Выполняем без неё: пропущенная
        // выдача дороже возможного повтора письма.
        $order = json_decode((string)@file_get_contents($orderFile), true);
        if (!is_array($order)) {
            return null;
        }
        $result = $fn($order);
        mvb_write_order($orderFile, $order);
        return $result;
    }

    @flock($lock, LOCK_EX);
    $order = json_decode((string)@file_get_contents($orderFile), true);
    if (!is_array($order)) {
        @flock($lock, LOCK_UN);
        fclose($lock);
        return null;
    }
    try {
        $result = $fn($order);
        mvb_write_order($orderFile, $order);
    } finally {
        @flock($lock, LOCK_UN);
        fclose($lock);
    }
    return $result;
}

/** Запись заказа целиком: через временный файл и rename, чтобы читатель
 *  никогда не увидел половину JSON. */
function mvb_write_order(string $orderFile, array $order): void
{
    $json = json_encode($order, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE);
    $tmp = $orderFile . '.tmp' . getmypid();
    if (@file_put_contents($tmp, $json) !== false) {
        @rename($tmp, $orderFile);
    } else {
        @file_put_contents($orderFile, $json);
    }
}

/**
 * Полный цикл выдачи для оплаченного заказа: архивы, ссылки, письмо покупателю.
 * Письмо уходит один раз (email_sent_at). Повторные вызовы безопасны только
 * под mvb_with_order_lock(): сама по себе проверка email_sent_at от
 * одновременных вызовов не защищает — см. разбор гонки выше.
 * Возвращает список ссылок на скачивание.
 */
function mvb_deliver_and_notify(array &$order): array
{
    $links = mvb_prepare_delivery($order);
    $orderId = (string)($order['id'] ?? '');

    if (!$links) {
        @file_put_contents(ORDERS_DIR . '/delivery-errors.log',
            date('c') . " заказ {$orderId}: не удалось подготовить выдачу (нет файлов продуктов?)\n", FILE_APPEND);
        return [];
    }

    if (!empty($order['delivery']['email_sent_at'])) {
        return $links;
    }

    if (!empty($order['email'])) {
        $subject = 'Ваши материалы «Маржа в бетоне» — заказ оплачен';
        $headers = [
            'From: site@marzhavbetone.ru',
            'Reply-To: ' . ADMIN_EMAIL,
            'Content-Type: text/plain; charset=UTF-8',
        ];
        $sent = mail(
            (string)$order['email'],
            '=?UTF-8?B?' . base64_encode($subject) . '?=',
            mvb_delivery_email($order, $links),
            implode("\r\n", $headers)
        );
        if ($sent) {
            $order['delivery']['email_sent_at'] = date('c');
        } else {
            @file_put_contents(ORDERS_DIR . '/delivery-errors.log',
                date('c') . " не удалось отправить письмо покупателю, заказ {$orderId}\n", FILE_APPEND);
        }
    } else {
        // Покупатель без email (только телефон) — админ высылает ссылки вручную
        @file_put_contents(ORDERS_DIR . '/delivery-errors.log',
            date('c') . " заказ {$orderId} без email: ссылки выдачи в {$orderId}.json, телефон {$order['phone']}\n", FILE_APPEND);
    }
    return $links;
}

