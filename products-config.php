/**
 * Пути, по которым ищутся мастера продуктов, в порядке предпочтения.
 *
 * Ответ не один и зависит от машины. В репозитории, на машине разработчика и
 * в прогоне CI мастера лежат рядом с сайтом — `products-storage/`. На боевом
 * сервере их там нет и быть не должно: deploy.yml перечисляет
 * `products-storage` в исключениях заливки сайта и кладёт мастера отдельным
 * шагом ВНЕ webroot, в `$PRODUCTS_PATH` (по умолчанию
 * `~/products-marzhavbetone`), чтобы их нельзя было скачать прямой ссылкой.
 */
function mvb_products_dir_candidates(string $siteDir): array
{
    return [
        // Репозиторий, локальная машина, прогон CI.
        $siteDir . '/products-storage',
        // Боевой reg.ru: сайт в ~/www/<домен>, мастера в ~/products-marzhavbetone.
        $siteDir . '/../../products-marzhavbetone',
        // Тот же сервер, если сайт лежит прямо в домашней папке.
        $siteDir . '/../products-marzhavbetone',
    ];
}

/**
 * Каталог годится, только если внутри лежит хотя бы одна непустая папка
 * продукта.
 *
 * Проверяется наличие товара, а не наличие каталога, и это не придирка:
 * пустой `products-storage/`, оставшийся от прежней заливки, существует —
 * и, если считать существование достаточным, перебивает настоящие мастера
 * за пределами webroot. Подводит здесь именно первый факт.
 */
function mvb_products_dir_has_masters(string $dir): bool
{
    if (!is_dir($dir)) {
        return false;
    }
    foreach (glob(rtrim($dir, '/') . '/*', GLOB_ONLYDIR) ?: [] as $sub) {
        if (glob($sub . '/*')) {
            return true;
        }
    }
    return false;
}

/**
 * Где лежат мастера продуктов на этой машине.
 *
 * Прежняя редакция подставляла `products-storage/` рядом с сайтом
 * безусловно и надеялась, что на боевом сервере владелец руками
 * переопределит константу в config.php. Надежда ничем не подкреплена:
 * config.php тоже исключён из заливки и живёт только на сервере, в шаблоне
 * этой константы не было, а DEPLOY.md, на который ссылаются подсказки
 * деплоя, в репозитории отсутствует вовсе.
 *
 * Цена забытой строки — молчаливая и ровно в размер продажи: покупатель
 * платит, вебхук зовёт mvb_build_product_zip(), тот не находит папку
 * продукта, возвращает null, ссылок нет, письмо не уходит. Деньги списаны,
 * товар не выдан, а в delivery-errors.log лежит одна строка, которую никто
 * не читает, пока не напишет покупатель.
 *
 * Поэтому путь не угадывается, а ищется: побеждает первый каталог, в
 * котором мастера действительно лежат. Явный define в config.php старше
 * всего — он объявлен владельцем и остаётся способом задать любой путь.
 */
function mvb_resolve_products_dir(string $siteDir): string
{
    foreach (mvb_products_dir_candidates($siteDir) as $candidate) {
        if (mvb_products_dir_has_masters($candidate)) {
            return $candidate;
        }
    }
    // Ни одного каталога с мастерами. Возвращаем путь по умолчанию, чтобы
    // строка в delivery-errors.log называла ожидаемое место, а не пустоту.
    return $siteDir . '/products-storage';
}

